/** Хуудасны эрхүүдээр автоматаар нээгдэх харагдацын нэрс — «Хуваарь батлах · Хуваарь» */
export const paneViewsText = (p: ErhPane): string =>
  [...new Set(PANE_CAPS[p].flatMap((k) => CAP_HOST_VIEW[k]))]
    .map((v) => VIEWS.find((x) => x.key === v)?.title ?? v)
    .join(' · ');

/** Юу олгох вэ — НЭГ энгийн өгүүлбэр */
const paneSummary = (p: ErhPane): string => {
  if (p === 'guits') return tr('Зургаан шат бүрд аккаунт томилж, аль багцыг хариуцахыг зааж өгнө.');
  if (p === 'huvaari') return tr('Багц тус бүрд хуваарь зохиогч (огноо төлөвлөж илгээх) ба батлагч аккаунтыг томилно.');
  if (p === 'ajil') return tr('Багц тус бүрд шинэ ажлын мөр нэмэгч ба батлагч аккаунтыг томилно.');
  if (p === 'obyem') return tr('Багц тус бүрд инженерийн төлөвлөсөн обьём засварлагч ба батлагч аккаунтыг томилно.');
  if (p === 'chanar') return tr('Багц тус бүрд чанарын баримт (MS · QMP · PRC · MA · MIR · FIC) ирүүлэгч ба ТУХ · Чанар · ХАБЭА · ТУГ · ЧХ инженер хянагчийг томилно.');
  if (p === 'qaqc') return tr('Багц тус бүрд Inspection Test Plan (М-акт · FIC · MA · MIR) бөглөх аккаунтыг томилно.');
  if (p === 'butets') return tr('Багц тус бүрд инженерийн шугамын атрибут (урт, бүс, баримт) засах аккаунтыг томилно.');
  if (p === 'zovshoorol') return tr('Зөвшөөрөл нэмэх, засах, устгах эрх — аккаунтаар олгоно.');
  /* ⚠️ 2026-10-04: IPC нь гүйцэтгэлийн батлалтаас автоматаар (`ipcAutoWrite`) — эрхээр засагдахгүй */
  if (p === 'fin') return tr('Cashflow хүснэгтийн утга засах ба мөр нэмэх эрх — аккаунтаар, тус тусад нь олгоно.');
  if (p === 'gazar') return tr('Нэгж талбарын төлөв, явцын мэдээ, эзэмшигчийг засах эрх — аккаунтаар олгоно.');
  if (p === 'hamaaral') return tr('Багц хоорондын хамаарлын холбоо нэмэх, устгах эрх — аккаунтаар олгоно.');
  if (p === 'habea') return tr('ХАБЭА хуудасны «Бусад үзүүлэлт» ба «Хог хаягдал»-д бүртгэл нэмэх, үзлэгийн тайлан татах эрх — аккаунтаар олгоно.');
  return '';
};

/** Дэд гарчиг: юу олгох вэ + аль харагдац автоматаар нээгдэх вэ */
export const paneSubtitle = (p: ErhPane): string => {
  const views = paneViewsText(p);
  return views
    ? `${paneSummary(p)} ${tr('Эрх олгоход «{0}» харагдац тухайн хүнд автоматаар нээгдэнэ.', views)}`
    : paneSummary(p);
};

