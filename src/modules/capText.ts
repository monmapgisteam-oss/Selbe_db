/** Дэд гарчиг: юу олгох вэ + аль харагдац автоматаар нээгдэх вэ */
export const paneSubtitle = (p: ErhPane): string => {
  const views = paneViewsText(p);
  return views
    ? `${paneSummary(p)} ${tr('Эрх олгоход «{0}» харагдац тухайн хүнд автоматаар нээгдэнэ.', views)}`
    : paneSummary(p);
};

