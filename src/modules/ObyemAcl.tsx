'use client';

/**
 * ИНЖЕНЕРИЙН ТӨЛӨВЛӨСӨН ОБЬЁМЫН ЭРХ ТОХИРУУЛАХ ПАНЕЛ — БАГЦААР.
 *
 * ⚠️ ЛОГИК НЬ `ScopedAclPanel.tsx`-Д (2026-09-10) — `HuvaariAcl.tsx`-тэй
 * хуваалцсан. Тэр хоёр нь нэрээс бусад бүрэн ижил байсныг нэг бүрэлдэхүүн
 * болгов; энд зөвхөн ЯЛГАА нь үлдэнэ.
 *
 * ⚠️ `HuvaariAcl`-ТЭЙ ИЖИЛ БҮТЭЦ, ӨӨР АСУУЛТ (2026-09-08). Тэр нь
 * ОГНОО («хэзээ»), энэ нь ОБЬЁМ («хэр их») төлөвлөх эрхийг хуваарилна.
 *
 * ⚠️ БАГЦ БҮРД ХОЁР ҮҮРЭГ:
 *   · Засварлагч — «Гүйцэтгэл бөглөх» хуудасны «Инженерийн төлөвлөсөн обьём»
 *                  баганын нүднүүдийг засаж, батлуулахаар илгээнэ
 *   · Батлагч    — илгээгдсэнийг батлах / буцаах
 *
 * ⚠️ Нэг хүн НЭГ БАГЦАД хоёр үүрэгтэй байвал ӨӨРИЙГӨӨ БАТЛАХ зам нээгдэхгүй:
 * `obyemBatlah.decideObyem` зохиогч=батлагч тохиолдлыг татгалзана. Панел нь
 * анхааруулга харуулна — тийм тохиргоо хийвэл тэр багцын обьёмын засвар гацна.
 */

import { t as tr } from '@/lib/i18nCore';
import {
  listObyemAssigns, obyemFailedUsers, removeObyemAssign, setObyemGrants,
  subscribeObyemAcl, type ObyemRole,
} from '@/lib/obyemAcl';
import { ScopedAclPanel, type AclPanelSpec } from './ScopedAclPanel';

/**
 * ⚠️ Шошго ба зурвасыг ФУНКЦ болгож өгнө — модулийн түвшинд `tr()` дуудвал
 *    хэл солиход шинэчлэгдэхгүй (зурагдах агшинд дуудагдах ёстой).
 */
const SPEC: AclPanelSpec<ObyemRole> = {
  roles: ['editor', 'approver'],
  roleLabel: (r) => (r === 'editor' ? tr('Засварлагч') : tr('Батлагч')),
  emptyLabel: (r) => (r === 'editor' ? tr('Засварлагч томилоогүй') : tr('Батлагч томилоогүй')),

  list: listObyemAssigns,
  failedUsers: obyemFailedUsers,
  subscribe: subscribeObyemAcl,
  setGrants: setObyemGrants,
  remove: (user) => removeObyemAssign(user),

  notes: () => [
    tr('Багц тус бүрд Засварлагч ба Батлагч аккаунтыг тусад нь томилно. Нэг багцад хэдэн ч аккаунт байж болно.'),
    tr('Засварлагч «Гүйцэтгэл бөглөх» хуудасны «Инженерийн төлөвлөсөн обьём» баганыг засаж батлуулахаар илгээнэ; батлагч зөвшөөрсний дараа л утга үндсэн өгөгдөлд бичигдэнэ.'),
    tr('⚠️ Гүйцэтгэлийн урсгал ба хуваарийн эрхээс ТУСДАА: обьёмын үүрэг олгосон нь гүйцэтгэл зөвшөөрөх, хуваарь засах эрх өгөхгүй.'),
  ],
  confirmRemoveAll: (user) =>
    tr('«{0}»-г инженерийн обьёмын хуваарилалтаас бүрэн хасах уу? «Инженерийн обьём засах» ба «Инженерийн обьём батлах» эрх нь мөн буцаагдана.', user),
  stuckMsg: () =>
    tr('⚠️ Батлагч нь засварлагчтай ижил хүн — өөрийн илгээснийг өөрөө батлах боломжгүй тул энэ багцын обьёмын засвар гацна. Өөр батлагч нэмнэ үү.'),
  noApproverMsg: () =>
    tr('⚠️ Батлагч томилоогүй — илгээсэн засварыг хэн ч батлахгүй.'),
};

export function ObyemAcl() {
  return <ScopedAclPanel spec={SPEC} />;
}
