/* ══════════════════ Хэмжүүр ══════════════════ */

/**
 * ХЭМЖҮҮР — нэг харьцаа, лавлах утгатай.
 * ⚠️ Нэг баганатай баганан график БИШ: цорын ганц тоог зурвасаар харуулна.
 */
/**
 * ХОЦРОГДЛЫН БОСГО — (төлөвлөсөн − бодит) нэгж хувь энэ ба түүнээс дээш бол
 * «хоцрогдол». `Meter`-ийн өнгө ба `ExecReport`-ийн KPI шошго НЭГ босго.
 * ⚠️ 2026-09-24: эх нь `@/lib/execReport` (дэлгэц · PDF · инфографик НЭГ тоо);
 *    энд зөвхөн дахин экспорт — хуучин import-ууд эвдрэхгүй.
 */
import { LATE_GAP } from '@/lib/execReport';
export { LATE_GAP };

/**
 * ⚠️ 2026-10-09 («бүх графикийн загварыг жигдлэх»): ӨӨРИЙН 8px хэмжүүр ХАСАГДСАН — `ui.Meter`
 *    ШУУД (2px зам, төлөвлөгөөний зураас ±4px, hover = `useTip`). Энд зөвхөн тайлангийн
 *    ДҮРЭМ үлдэв: хоцрогдлын өнгө (`LATE_GAP`) ба 2 оронтой «Бодит · Төлөвлөгөө» бичвэр.
 *    Хэвлэлтийн өнгө `.meterBlock`-ийн `@media print`-д.
 */
export function PlanMeter({
  value,
  plan,
  label,
}: {
  /** 0–100 хувь */
  value: number | null;
  /** Төлөвлөгөөт хувь — лавлах зураас (0–100) */
  plan?: number | null;
  label: string;
}) {
  if (value == null || !Number.isFinite(value)) return null;
  /* ⚠️ Хоцрогдлыг ӨНГӨӨР заана — статусын өнгө яг энэ зориулалттай.
     ⚠️ 2026-09-23: босго `LATE_GAP` — урьд нь `value < plan` (0.1 ч хоцрол
     шар) байсан тул KPI «хуваарийн дагуу» гэж бичихэд хэмжүүр шар болдог байв. */
  const hasP = plan != null && Number.isFinite(plan);
  const late = hasP && plan - value >= LATE_GAP;
  return (
    <div className={c.meterBlock}>
      <Meter
        label={label}
        value={value}
        plan={hasP ? plan : null}
        decimals={2}
        tone={late ? 'warn' : 'data'}
        display={hasP
          ? `${tr('Бодит')}: ${pct(value, 2)} · ${tr('Төлөвлөгөө')}: ${pct(plan, 2)}`
          : `${tr('Бодит')}: ${pct(value, 2)}`}
      />
    </div>
  );
}

/* ══════════════════ Үзүүлэлтийн эгнээ ══════════════════ */

export type Kpi = { label: string; value: string; sub?: string };

/**
 * ГОЛ ҮЗҮҮЛЭЛТИЙН ЭГНЭЭ — цөөн толгой тоо.
 * ⚠️ Эдгээрийг график болгохгүй: нэг тоог багана болгон зурах нь мэдээлэл
 *    нэмэхгүй, зөвхөн зай иднэ. Тоо нь өөрөө «график».
 */
export function KpiRow({ items, cols }: {
  items: Kpi[];
  /**
   * БАГАНЫН ТОО — өгөөгүй бол өргөнөөр өөрөө хуваагдана (`auto-fit`).
   * ⚠️ Тодорхой тоо өгөх шалтгаан: 4 картыг өргөн дэлгэц дээр НЭГ мөрөнд
   * хавчуулбал нэр нь таслагдана; 2×2 нь уншигдахуйц (хэрэглэгчийн заавар).
   */
  cols?: number;
}) {
  if (!items.length) return null;
  return (
    <div
      className={c.kpis}
      style={cols ? { gridTemplateColumns: `repeat(${cols}, minmax(0, 1fr))` } : undefined}
    >
      {items.map((k, i) => (
        <div key={`${k.label}-${i}`} className={c.kpi}>
          <span className={c.kpiLabel}>{k.label}</span>
          <b className={c.kpiVal}>{k.value}</b>
          {k.sub && <span className={c.kpiSub}>{k.sub}</span>}
        </div>
      ))}
    </div>
  );
}
