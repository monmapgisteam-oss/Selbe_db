export type Negj = 'м³' | 'м²' | 'м' | 'тн' | 'ш';

export function unitLabel(u: Negj | null): string {
  switch (u) {
    case 'м³': return tr('м³');
    case 'м²': return tr('м²');
    case 'м': return tr('м');
    case 'тн': return tr('тн');
    case 'ш': return tr('ш');
    default: return '';
  }
}

/**
 * Кирилл кодчилолын гажилтыг жигдэлнэ.
 */
