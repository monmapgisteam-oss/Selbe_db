/**
 * ХЭМЖИХ НЭГЖИЙГ АЖЛЫН НЭРНЭЭС ТААВАРЛАХ.
 *
 * ⚠️ ЭНЭ НЬ ТААМАГ, БАРИМТ БИШ. Эх төсвийн «Хэмжих нэгж» багана ArcGIS-т
 * импортлогдохдоо ОРХИГДСОН тул 10 үйлчилгээний нэг ч талбарт нэгж алга.
 * Ажлын нэрнээс дүрмээр таамаглаж байгаа бөгөөд заавал алдаа гарна:
 *   · «өрөх» нь тоосгонд м³, ALC гулдмайд м² байж болно,
 *   · «угсрах» нь ширхэг ч, тонн ч байж болно.
 *
 * ⚠️ Тиймээс дэлгэцэнд ЗААВАЛ «таамаг» гэж ялгаж харуулна, тайланд ОРУУЛАХГҮЙ,
 * ямар ч тооцоонд ХЭРЭГЛЭХГҮЙ. Дүрэм таарахгүй бол `null` — буруу нэгж
 * харуулахаас хоосон үлдээх нь ХАВЬГҮЙ дээр.
 *
 * ⚠️ ЖИНХЭНЭ ЗАСВАР: эх excel-ийн «Хэмжих нэгж» баганыг үйлчилгээ рүү
 * импортлох. Тэр өдөр энэ файл хэрэггүй болно.
 */

/**
 * ⚠️ ТАВАН НЭГЖ, өөр байхгүй. Барилгын төсвийн мөр нь ХЭМЖЭЭГЭЭР
 * хэмжигдэнэ; машин-цаг, хүн-цаг зэрэг нь НОРМЫН ДОТОР сууж, нэгж
 * өртөгт шингэдэг тул мөрийн нэгж болж хэзээ ч гарахгүй.
 *
 * ⚠️ Урьд нь «цаг» гэсэн ангитай байсныг хассан: «Хүйтэн усны өргөлтийн
 * насос N=2.2кВт» гэх мөрүүд тэнд ороод байв — тэдгээр нь тоноглол
 * ХУДАЛДАН АВЧ УГСРАХ (ш) ажил болохоос механизмын ажиллагаа биш.
 */
export type Negj = 'м³' | 'м²' | 'м' | 'тн' | 'ш';

/**
 * Кирилл кодчилолын гажилтыг жигдэлнэ.
 * ⚠️ Эх excel-ээс `є` (U+0454) ба `ї` (U+0457) буруу орсон — эдгээр нь
 * УКРАИН үсэг бөгөөс монгол `ө`/`ү` БИШ. Жигдлэхгүй бол дүрмийн 30 орчим
 * хувь нь таарахаа болино.
 */
const norm = (s: string): string =>
  s.toLowerCase().replace(/є/g, 'ө').replace(/ї/g, 'ү').replace(/\([^)]*\)/g, ' ');

/**
 * ДҮРМҮҮД — ДЭС ДАРААЛАЛ ЧУХАЛ, эхний таарсан нь ялна.
 *
 * ⚠️ Тодорхой зүйлийг ЕРӨНХИЙГӨӨС ӨМНӨ тавина. Жишээ: «бөмбөлгөн хаалт
 * d=32мм байрлуулах» нь ШИРХЭГ; хэрэв «хоолой → м» дүрэм түрүүлбэл тэр мөр
 * буруугаар метр болно.
 */
