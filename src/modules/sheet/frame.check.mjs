/**
 * АРХИВЫН ЖААЗ ТАСЛАХ ДҮРЭМ.
 *   node --experimental-transform-types --import ./tools/ts-alias.mjs src/modules/sheet/frame.check.mjs
 *
 * ⚠️ Логик ХУУЛБАРЛААГҮЙ — `bagtsSheet.ts`-ийн ЖИНХЭНЭ `lastFrame`-ийг
 * импортолж шалгана. Тэндээ зассан зүйл энд шууд тусна.
 *
 * Хамгаалж буй алдаа (2026-09-01-нд бодитоор гарсан):
 *   `applyAdds` нь 500 мөрийн БАГЦААР бичдэг ба `rollbackOnFailure` зөвхөн нэг
 *   багц дотор үйлчилнэ. Нийтлэх дунд нь тасалдвал ДУТУУ жааз үлдэнэ. Урьд нь
 *   `lastFrame` уртыг шалгалгүй тэр дутуу жаазыг «хамгийн сүүлийн агшин» гэж
 *   буцаадаг байсан тул `Bagts_2_9f` (жаазууд [1386,1386,1386,1000]) дээр
 *   «Гүйцэтгэл бөглөх», «Хуваарь», хоцрогдлын тооцоо гурвуулаа НЭЭГДЭХЭЭ
 *   больж, алдааны бичвэр нь «шатлалын зураглал» гэж БУРУУ шалтгаан заадаг байв.
 */
import assert from 'node:assert/strict';
import { alignInsertions, lastFrame, numLoose } from './bagtsSheet.ts';

const NO = 'dugaar';

/** №-ийн жагсаалтаас Feature массив — эхний № нь жаазны заагийг тэмдэглэнэ. */
const feats = (nos) => nos.map((n) => ({ attributes: { [NO]: n } }));

/** N мөрийн бүтэн жааз: «A» -ээр эхэлж, дараа нь b1..b(N-1) */
const frame = (n, tag) => ['A', ...Array.from({ length: n - 1 }, (_, i) => `${tag}${i + 1}`)];

const nosOf = (fs) => fs.map((f) => f.attributes[NO]);

/* ── 1. Ганц жааз — хэвээр буцаана ── */
{
  const all = feats(frame(5, 'x'));
  assert.equal(lastFrame(all, NO, 5).length, 5, 'ганц жааз бүтнээрээ');
}

/* ── 2. Хоёр БҮТЭН жааз — сүүлийнхийг авна ── */
{
  const all = feats([...frame(4, 'x'), ...frame(4, 'y')]);
  const got = lastFrame(all, NO, 4);
  assert.equal(got.length, 4, 'сүүлийн жаазын урт');
  assert.equal(got[1].attributes[NO], 'y1', 'СҮҮЛИЙН жааз сонгогдов');
}

/* ── 3. ГОЛ ТОХИОЛДОЛ: сүүлийн жааз ТАСАРСАН — өмнөх бүтнийг авна ──
   Bagts_2_9f-ийн бодит хэлбэр: [бүтэн, бүтэн, бүтэн, дутуу] */
{
  const all = feats([...frame(6, 'a'), ...frame(6, 'b'), ...frame(6, 'c'), ...frame(3, 'd')]);
  const got = lastFrame(all, NO, 6);
  assert.equal(got.length, 6, 'дутуу жаазыг алгасаж БҮТЭН жааз буцаана');
  assert.equal(got[1].attributes[NO], 'c1', 'сүүлийн БҮТЭН жааз (c) сонгогдов');
  assert.ok(!nosOf(got).includes('d1'), 'тасарсан жаазын мөр ОРООГҮЙ');
}

/* ── 4. Дараалсан ХОЁР тасалдал — хамгийн сүүлийн бүтнийг олтол ухарна ── */
{
  const all = feats([...frame(6, 'a'), ...frame(6, 'b'), ...frame(2, 'c'), ...frame(3, 'd')]);
  const got = lastFrame(all, NO, 6);
  assert.equal(got.length, 6, 'хоёр тасалдлыг давж бүтэн жааз олов');
  assert.equal(got[1].attributes[NO], 'b1', 'жааз b сонгогдов');
}

/* ── 5. МӨР НЭМЭГДСЭН жааз — уртсасныг тасарсан гэж БУРУУ бодохгүй ──
   ⚠️ Энэ бол сөрөг шалгуур: мөр нэмэх боломж нь бүтэн ажиллах ёстой. */
{
  const all = feats([...frame(6, 'a'), ...frame(8, 'b')]);
  const got = lastFrame(all, NO, 6);
  assert.equal(got.length, 8, 'нэмэгдсэн мөртэй ШИНЭ жааз хэвээр сонгогдов');
  assert.equal(got[1].attributes[NO], 'b1', 'сүүлийн (уртассан) жааз');
}

/* ── 6. Мөр нэмэгдсэний ДАРАА тасалдсан ──
   Өмнөх жааз 8 мөр, сүүлийнх 5 → тасарсан гэж үзнэ. */
{
  const all = feats([...frame(6, 'a'), ...frame(8, 'b'), ...frame(5, 'c')]);
  const got = lastFrame(all, NO, 6);
  assert.equal(got.length, 8, 'өмнөхөөсөө богино жааз хаягдав');
  assert.equal(got[1].attributes[NO], 'b1');
}

/* ── 7. Зураглалаас БОГИНО ганц давхардал — expect хамгаална ──
   Хоёр жааз хоёулаа 4 мөр ч зураглал 6 мөр хүлээж байвал сүүлийнх нь ч
   бүтэн биш. Ийм үед хамгийн эхнийх рүү ухарч, `loadRows`-ийн хатуу алдаа
   ажиллана — ЧИМЭЭГҮЙ буруу мөр буцаахаас дээр. */
{
  const all = feats([...frame(4, 'a'), ...frame(4, 'b')]);
  const got = lastFrame(all, NO, 6);
  assert.equal(got[1].attributes[NO], 'a1', 'бүтэн жааз олдоогүй тул эхнийх рүү ухарна');
}

/* ── 8. `expect` өгөөгүй (суурь агшин) — зөвхөн уртын харьцаагаар шийднэ ── */
{
  const all = feats([...frame(6, 'a'), ...frame(3, 'b')]);
  const got = lastFrame(all, NO);
  assert.equal(got.length, 6, 'expect-гүй ч тасарсан жаазыг таньна');
}

/* ── 9. Хоосон/богино оролт — унахгүй ── */
{
  assert.equal(lastFrame([], NO, 3).length, 0, 'хоосон массив');
  assert.equal(lastFrame(feats(['A']), NO, 3).length, 1, 'ганц мөр');
  assert.equal(lastFrame(feats(['', 'x']), NO, 3).length, 2, 'эхний № хоосон бол бүгдийг');
}

console.log('frame.check: ok — ганц ✓ хоёр бүтэн ✓ тасарсан ✓ давхар тасалдал ✓ '
  + 'мөр нэмэгдсэн ✓ нэмэгдээд тасарсан ✓ expect хамгаалалт ✓ суурь ✓ хязгаар ✓');

/* ── ТЕКСТЭЭР ХАДГАЛАГДСАН ТОО (2026-09-03) ──
   Багц 4.2·12F-ийн «Мөнгөн_дүн» нь String бөгөөд мянгатын таслалтай
   («13,670,427,055»). Урьд нь Number() NaN өгч, тэр багцын БҮХ 1,593 мөрд
   мөнгөн дүн null болж багана хоосон харагддаг байв. */
{
  const eq = (a, b, m) => assert.equal(a, b, `${m}: ${JSON.stringify(a)} ≠ ${JSON.stringify(b)}`);
  eq(numLoose('13,670,427,055'), 13670427055, 'мянгатын таслал');
  eq(numLoose('-58,555,780'), -58555780, 'сөрөг мянгатын таслал');
  eq(numLoose('1 234 567'), 1234567, 'зайгаар тусгаарласан');
  eq(numLoose('2,166.943'), 2166.943, 'таслал + аравтын цэг');
  eq(numLoose(42), 42, 'тоо шууд дамжина');
  eq(numLoose('42'), 42, 'энгийн тоон мөр');
  eq(numLoose(0), 0, 'тэг нь null БИШ');
  /* ⚠️ null ≠ 0 — уншигдахгүйг тэг болгож БОЛОХГҮЙ */
  eq(numLoose(null), null, 'null хэвээр');
  eq(numLoose(undefined), null, 'undefined → null');
  eq(numLoose(''), null, 'хоосон мөр → null');
  eq(numLoose('   '), null, 'зөвхөн зай → null');
  eq(numLoose('м³'), null, 'тоо биш текст → null (0 БИШ)');
  eq(numLoose('12abc'), null, 'хагас тоо → null');
  eq(numLoose('1,2,3'), 123, 'зөвхөн тоо ба таслал бол нийлүүлнэ');
  console.log('✅ текстээр хадгалагдсан тоо — мянгатын таслал уншигдана, null≠0 хэвээр');
}

/* ── ХООСОН МӨРТЭЙ ЗЭРЭГЦҮҮЛЭЛТ (2026-09-04-ний бодит эвдрэл) ──
   «Багц 3.1 · 9 давхар»-ын суурь жаазны СҮҮЛИЙН мөр нь № ба Ажил хоёулаа
   хоосон. loadRows түүнийг алгасдаг тул дэлгэцэд 1,470 мөр гарч, нийтлэхэд
   архивт ЯГ ТЭР 1,470 мөр бичигдэнэ. Дараа нь тэр жаазыг ачаалахад лавлахын
   хоосон мөр хэзээ ч таарахгүй тул зэрэгцүүлэлт null буцааж, багцын бөглөх
   хуудас БА хянагчийн харагдац хоёулаа «1470 мөр ирлээ, 1471 байх ёстой»
   гэсэн хатуу алдаагаар бүрмөсөн хаагддаг байв.

   ⚠️ ХАСАЛТЫГ ЗӨВХӨН ХООСОН мөрд зөвшөөрнө. Утга бүхий мөр дутвал null
   хэвээр — чимээгүй буруу шатлалаас хатуу алдаа ХАВЬГҮЙ дээр. */
{
  const K = (n, w) => n + " ¦ " + w;
  const BLANK = " ¦ ";

  /* 1. Хэвийн: ижил дараалал */
  {
    const ref = [K("1", "a"), K("2", "b"), K("3", "c")];
    assert.deepEqual(alignInsertions(ref.slice(), ref), [0, 1, 2], "ижил дараалал");
  }

  /* 2. Мөр НЭМЭГДСЭН — шинэ мөрд -1 */
  {
    const ref = [K("1", "a"), K("2", "b")];
    const cur = [K("1", "a"), K("1.1", "шинэ"), K("2", "b")];
    assert.deepEqual(alignInsertions(cur, ref), [0, -1, 1], "нэмэгдсэн мөр -1 авна");
  }

  /* 3. СҮҮЛИЙН хоосон мөр лавлахад байгаа ч жаазад алга — таарах ЁСТОЙ */
  {
    const ref = [K("1", "a"), K("2", "b"), BLANK];
    const cur = [K("1", "a"), K("2", "b")];
    assert.deepEqual(alignInsertions(cur, ref), [0, 1], "сүүлийн хоосон мөр алгасагдана");
  }

  /* 4. ДУНД байрлалын хоосон мөр — байрлалын зураглал гулсах ёсгүй */
  {
    const ref = [K("1", "a"), BLANK, K("2", "b")];
    const cur = [K("1", "a"), K("2", "b")];
    assert.deepEqual(alignInsertions(cur, ref), [0, 2], "дунд хоосон мөр — индекс 2 руу заана");
  }

  /* 5. ОЛОН хоосон мөр — дунд ба сүүл хамт */
  {
    const ref = [K("1", "a"), BLANK, K("2", "b"), BLANK, BLANK];
    const cur = [K("1", "a"), K("2", "b")];
    assert.deepEqual(alignInsertions(cur, ref), [0, 2], "олон хоосон мөр");
  }

  /* 6. Хоосон мөр ба НЭМЭГДСЭН мөр зэрэг */
  {
    const ref = [K("1", "a"), K("2", "b"), BLANK];
    const cur = [K("1", "a"), K("1.1", "шинэ"), K("2", "b")];
    assert.deepEqual(alignInsertions(cur, ref), [0, -1, 1], "хоосон ба нэмэлт зэрэг");
  }

  /* 7. ⚠️ УТГАТАЙ мөр дутвал null — энэ хамгаалалт СУЛРАХ ЁСГҮЙ */
  {
    const ref = [K("1", "a"), K("2", "b"), K("3", "c")];
    const cur = [K("1", "a"), K("3", "c")];
    assert.equal(alignInsertions(cur, ref), null, "утгатай мөр дутвал null");
  }

  /* 8. ⚠️ Дараалал ЗӨРВӨЛ null (эх хүснэгтийн бүтэц өөрчлөгдсөн) */
  {
    const ref = [K("1", "a"), K("2", "b")];
    const cur = [K("2", "b"), K("1", "a")];
    assert.equal(alignInsertions(cur, ref), null, "дараалал зөрвөл null");
  }

  /* 9. Зөвхөн зайнаас бүрдсэн нүд ч ХООСОН гэж тооцогдоно */
  {
    const ref = [K("1", "a"), "   ¦    "];
    const cur = [K("1", "a")];
    assert.deepEqual(alignInsertions(cur, ref), [0], "зайтай хоосон түлхүүр");
  }

  /* 10. ⚠️ ХООСОН МӨР cur ТАЛД байвал — лавлахад байхгүй ч ГУЛСАХГҮЙ.
     Архивт хоосон мөр буцаж бичигдсэн (эсвэл гараар нэмэгдсэн) тохиолдол:
     тэр нь «нэмэгдсэн мөр» (-1) болох ба ард нь байгаа мөрүүд лавлахын ЗӨВ
     индекс рүү заасаар үлдэнэ — гүн нь өөр ажлаас уншигдахгүй. */
  {
    const ref = [K("1", "a"), K("2", "b")];
    const cur = [K("1", "a"), BLANK, K("2", "b")];
    assert.deepEqual(alignInsertions(cur, ref), [0, -1, 1], "cur талын хоосон мөр гулсуулахгүй");
  }

  /* 11. ⚠️ ХООСОН мөр дутсан ч УТГАТАЙ мөр ДУТВАЛ хатуу алдаа ХЭВЭЭР.
     Энэ бол хамгаалалтын гол шалгуур: хоосныг алгасах эрх нь «дурын мөрийг
     алгасах» эрх БОЛЖ ХУВИРАХ ЁСГҮЙ — rowKey нь b31_9f-д 1,471-ийн зөвхөн 580
     нь давтагдашгүй (61% давхардал) тул чөлөөт алгаслалт мөрийг буруу
     байрлалд наагаад бүлэг/ажил чимээгүй хольцолдоно. */
  {
    const ref = [K("1", "a"), K("2", "b"), K("3", "c"), BLANK];
    const cur = [K("1", "a"), BLANK, K("3", "c")];
    assert.equal(alignInsertions(cur, ref), null, "хоосон байсан ч утгатай мөр дутвал null");
  }

  /* 12. ХОЁР+ хоосон мөр ДУНД, нэмэлт мөртэй хамт — индекс нэг бүрчлэн зөв */
  {
    const ref = [K("1", "a"), BLANK, BLANK, K("2", "b"), BLANK, K("3", "c")];
    const cur = [K("1", "a"), K("2", "b"), K("2.1", "шинэ"), K("3", "c")];
    assert.deepEqual(alignInsertions(cur, ref), [0, 3, -1, 5], "2+ хоосон + нэмэлт");
  }

  /* 13. ⚠️ «Багц 3.1 · 9 давхар»-ын БОДИТ хэлбэр, бүтэн масштабаар.
     Суурь жааз 1,471 мөр (сүүлийнх нь № ба Ажил хоёулаа хоосон) ↔ 2026-09-04-ний
     архивын жааз 1,470 мөр (хоосонгүй). Зэрэгцүүлэлт нь БАЙРЛАЛ ТУТМАА хэвээр
     үлдэх ёстой: map[i] === i. Эс бөгөөс гүнийг `treeDepth(map[i])`-ээр өөр
     ажлаас уншиж, шатлал бүхэлдээ гулсана. */
  {
    const ref = Array.from({ length: 1470 }, (_, i) => K(String(i), "ажил " + i)).concat([BLANK]);
    const cur = ref.slice(0, 1470);
    const map = alignInsertions(cur, ref);
    assert.ok(map, "1470 ↔ 1471 (сүүлийн мөр хоосон) — зэрэгцүүлэлт бүтнэ");
    assert.equal(map.length, 1470, "буцаах массивын урт нь cur-тай тэнцүү");
    assert.ok(map.every((v, i) => v === i), "байрлал НЭГ Ч мөрөөр гулсаагүй");
  }

  /* 14. Хоосон мөр ХАМГИЙН ЭХЭНД — цөөн тохиолдох ч дүрэм ижил ажиллана */
  {
    const ref = [BLANK, K("1", "a"), K("2", "b")];
    const cur = [K("1", "a"), K("2", "b")];
    assert.deepEqual(alignInsertions(cur, ref), [1, 2], "эхний хоосон мөр алгасагдана");
  }

  console.log("✅ зэрэгцүүлэлт — хоосон мөр (эхэн·дунд·сүүл, олноороо) алгасагдана, "
    + "1470↔1471 бодит масштабт гулсалт 0, утгатай мөр дутвал хатуу алдаа хэвээр");
}

/* ── ДАВХАРДСАН СУУРЬ ЖААЗ — `loadBaseKeys`-ийн зам (2026-09-04) ──
   `loadBaseKeys` нь зэрэгцүүлэлтийн ЛАВЛАХ дарааллаа суурь агшнаас
   (`buglusun_ognoo IS NULL`) татдаг. Суурь нь ч ДАВХАРДАЖ болно:
   `Bagts_1_9f`-ийн суурьт 2,740 мөр = 2 × 1,370 (амьдаар хэмжсэн).
   Урьд нь тэнд `expect` дамждаггүй байсан тул суурьт ХАГАС хуулбар үүсэхэд
   лавлах богиносч, `ref.length === expect` унаж, хуудас «шатлалын зураглалыг
   дахин гаргах шаардлагатай» гэсэн БУРУУ шалтгаантай хатуу алдаагаар
   хаагдана. Одоо `lastFrame(out, no, TREES[key].length)`-ээр таслана. */
{
  /* 1. Давхардсан суурь [бүтэн, бүтэн] — сүүлийн бүтнийг авна (b1_9f-ийн хэлбэр) */
  {
    const all = feats([...frame(6, 'a'), ...frame(6, 'b')]);
    const got = lastFrame(all, NO, 6);
    assert.equal(got.length, 6, 'давхардсан суурь — нэг жааз');
    assert.equal(got[1].attributes[NO], 'b1', 'сүүлийн бүтэн хуулбар');
  }

  /* 2. Суурьт ХАГАС хуулбар үлдсэн [бүтэн, хагас] — expect түүнийг таслана */
  {
    const all = feats([...frame(6, 'a'), ...frame(3, 'b')]);
    const got = lastFrame(all, NO, 6);
    assert.equal(got.length, 6, 'хагас хуулбарыг алгасаж БҮТЭН лавлах буцаана');
    assert.equal(got[1].attributes[NO], 'a1', 'бүтэн жааз (a) сонгогдов');
  }

  /* 3. [хагас, бүтэн] дараалал — сүүлийнх нь бүтэн тул шууд буцаана */
  {
    const all = feats([...frame(3, 'a'), ...frame(6, 'b')]);
    assert.equal(lastFrame(all, NO, 6).length, 6, 'сүүлийн бүтэн жааз');
  }

  console.log('✅ давхардсан суурь — loadBaseKeys нь lastFrame(expect)-ээр бүтэн лавлах авна');
}
