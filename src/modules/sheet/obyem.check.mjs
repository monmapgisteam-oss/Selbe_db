/**
 * «Гүйцэтгэл обьёмоор» бөглөх дүрмийг шалгана.
 *   node --experimental-transform-types --import ./tools/ts-alias.mjs \
 *        src/modules/sheet/obyem.check.mjs
 *
 * Хамгаалж буй ХОЁР дүрэм:
 *   1. Обьём нь ХЭМЖИЛТ — зөвхөн гараар бичигдэнэ, хэзээ ч бодогдохгүй.
 *   2. Гүйцэтгэлийн хувь нь ЗӨВХӨН обьёмоос бодогдоно — гараар бичих зам
 *      байхгүй. Хуваарь (мөрийн Обьём) алга бол хадгалагдсан хувь нь хэвээр.
 */
import assert from 'node:assert/strict';
import { computeAll, cellObyem } from './bagtsSheet.ts';

const ASOF = Date.parse('2026-08-20T00:00:00Z');

/** Нэг блоктой (n=1) навч мөр — бусад талбар нь тооцоонд оролцохгүй. */
const leaf = (o) => ({
  oid: o.oid ?? 1,
  no: o.no ?? '1',
  work: o.work ?? 'ажил',
  depth: o.depth ?? 1,
  group: false,
  wC: null,
  wD: null,
  vol: o.vol ?? null,
  unit: o.unit ?? 1,
  money: null,
  act: [o.act ?? null],
  obyem: [o.obyem ?? null],
  start: [null],
  end: [null],
});
const run = (rows, edits = {}, has = [true]) =>
  computeAll(rows, 1, ASOF, edits, {}, has);

/* ── Обьём нь ЗӨВХӨН гараар — хувиас буцааж бодогдохгүй ── */
assert.equal(
  cellObyem(leaf({ act: 0.4, vol: 1000 }), 0, {}),
  null,
  'хувь 40%, Обьём 1000 байсан ч обьём нь ХООСОН — таамаглахгүй',
);
assert.equal(cellObyem(leaf({ obyem: 400 }), 0, {}), 400, 'хадгалагдсанаа');
assert.equal(cellObyem(leaf({}), 0, { '1:0': '250' }), 250, 'нийтлээгүй засвар');
assert.equal(cellObyem(leaf({ obyem: 400 }), 0, { '1:0': '' }), null, 'хоосон = цэвэрлэх');
assert.equal(cellObyem(leaf({ obyem: 400 }), 0, { '1:0': '-9' }), 0, 'сөрөг → 0');
assert.equal(cellObyem(leaf({ obyem: 400 }), 0, { '1:0': 'x' }), 400, 'хог утга нөлөөлөхгүй');

/* ── Бичсэн обьём нь ШУУД утга (нэмэлт БИШ) ── */
let c = run([leaf({ vol: 1000, obyem: 300 })], { '1:0': '500' })[0];
assert.equal(c.obyem[0], 500, '500 гэж бичвэл 500 — 300+500 БИШ');
assert.equal(c.act[0], 0.5, '500 / 1000 = 50%');

/* ── Обьёмгүй үед хувь нь ХӨНДӨГДӨХГҮЙ (хуучин явц алдагдахгүй) ── */
c = run([leaf({ vol: 1000, act: 0.4 })])[0];
assert.equal(c.obyem[0], null, 'обьём хоосон хэвээр');
assert.equal(c.act[0], 0.4, 'хадгалагдсан 40% хэвээр');

/* ── ХУВЬ ГАРААР БИЧИГДЭХГҮЙ ──
 * Хоёр эх сурвалж (гараар бичсэн хувь vs обьёмоос бодогдсон) зэрэгцвэл аль
 * нь үнэн болох нь тодорхойгүй болж тайлан зөрнө. Тиймээс ганц зам үлдээв. */
assert.equal(c.act[0], 0.4, 'хувийн засвар гэж байхгүй — хадгалагдсанаа хэвээр');

/* ── Хуваарьгүй мөр: обьём бүртгэгдэнэ, хувь нь ХЭВЭЭР ── */
c = run([leaf({ act: 0.4 })], { '1:0': '80' })[0];
assert.equal(c.obyem[0], 80, 'мөрийн Обьёмгүй ч обьём бүртгэгдэнэ');
assert.equal(c.act[0], 0.4, 'хувь нь бодогдох аргагүй — хуучин утга хэвээр');

/* ── Обьёмын багангүй блок: юу ч хөндөгдөхгүй ── */
c = run([leaf({ vol: 1000, act: 0.4 })], { '1:0': '900' }, [false])[0];
assert.equal(c.obyem[0], null, 'багана байхгүй — хадгалах газаргүй');
assert.equal(c.act[0], 0.4, 'хадгалагдсан хувь нь хэвээр');

/* ── Обьёмоос хэтэрч болно — эх өгөгдлийн зөрүү нуугдахгүй ── */
c = run([leaf({ vol: 1000 })], { '1:0': '1200' })[0];
assert.equal(c.act[0], 1.2, '120% — гуйвуулж таслахгүй');

/* ══ 100%-ИАС ИХ ГҮЙЦЭТГЭЛ (2026-09-04) ═══════════════════════════════════
 * ХОЁР шаардлагыг ЗЭРЭГ хамгаална:
 *   1. НҮД нь түүхий утгаа хэвээр харуулна (`act`) — эс тэгвээс эх өгөгдлийн
 *      алдаа бүрмөсөн нуугдаж, хэн ч засахгүй өнгөрнө;
 *   2. ДЭЭШ нэгтгэгдэх утга (`actAgg` → бүлэг · J · E) 1-ээр таслагдана — эс
 *      тэгвээс нэг эвдэрсэн нүд бүлгийн гүйцэтгэлийг хиймлээр өсгөнө.
 * Амьд эх сурвалж: Багц 1·9F oid 31534 блок «5/3» 443 ÷ 142.96 = 3.0988;
 *                  Багц 2·12F oid 1699 блок «29/2» 200 ÷ 142.96 = 1.3990,
 *                  улмаар эцэг бүлэг oid 1698 нь 1.0641 = 106.4% байв. */
assert.equal(c.actAgg[0], 1, 'нэгтгэлд 100%-иар таслагдана');
assert.equal(c.actOver[0], true, '1-ээс их гэдгийг тугаар ил гаргана');
assert.equal(c.J, 1, 'J нь таслагдсанаас — 1.2 БИШ');
assert.equal(c.E, 1, 'E = C×J ≤ C (энд C=1)');

/* Амьд тоо: 443 ÷ 142.96 = 3.0988 — нүдэнд бүтнээрээ, нэгтгэлд 1 */
c = run([leaf({ oid: 3, vol: 142.96 })], { '3:0': '443' })[0];
assert.ok(Math.abs(c.act[0] - 3.0987688864017904) < 1e-12, 'нүд 309.9% хэвээр');
assert.equal(c.actAgg[0], 1, 'нэгтгэлд 1');

/* ── ХИЛИЙН ТОХИОЛДОЛ: яг 1.0 ба 0.999 нь ХӨНДӨГДӨХГҮЙ ── */
c = run([leaf({ oid: 4, vol: 1000 })], { '4:0': '1000' })[0];
assert.equal(c.act[0], 1, 'яг 100%');
assert.equal(c.actAgg[0], 1, 'яг 1.0 — таслалт нөлөөлөхгүй');
assert.equal(c.actOver[0], false, '1.0 нь «их» БИШ');
c = run([leaf({ oid: 5, vol: 1000 })], { '5:0': '999' })[0];
assert.equal(c.act[0], 0.999, '99.9%');
assert.equal(c.actAgg[0], 0.999, '0.999 хэвээр — тэглэхгүй, дугуйруулахгүй');
assert.equal(c.actOver[0], false, '0.999 нь «их» БИШ');

/* ── ХЭМЖИГДЭЭГҮЙ нүд: таслалт нь `null`-ыг 0 БОЛГОХГҮЙ ── */
c = run([leaf({ oid: 6, vol: 1000 })])[0];
assert.equal(c.act[0], null, 'бөглөөгүй нүд null хэвээр');
assert.equal(c.actAgg[0], null, 'null → null (0 БИШ)');
assert.equal(c.actOver[0], false, 'хэмжигдээгүй нүд тугтай болохгүй');

/* ── БҮЛЭГТ ЯАЖ НӨЛӨӨЛӨХ ВЭ: 300% + 50% ── */
const over = [
  { ...leaf({ oid: 20, vol: null, depth: 0 }), group: true },
  leaf({ oid: 21, vol: 100, obyem: 300, depth: 1 }), // 300%
  leaf({ oid: 22, vol: 100, obyem: 50, depth: 1 }), // 50%
];
const og = computeAll(over, 1, ASOF, {}, {}, [true]);
assert.ok(Math.abs(og[1].act[0] - 3) < 1e-9, 'дэд мөрд 300% ил хэвээр');
assert.equal(og[1].actAgg[0], 1, 'дээш нь 100% болж таслагдана');
assert.ok(
  Math.abs(og[0].act[0] - 0.75) < 1e-9,
  'бүлэг = (100% + 50%) / 2 = 75% — таслаагүй бол 175% болно',
);
assert.ok(og[0].act[0] <= 1, 'бүлгийн гүйцэтгэл 100%-иас ХЭТРЭХГҮЙ');
assert.equal(og[0].actOver[0], false, 'бүлэг өөрөө «их» гэж тэмдэглэгдэхгүй');
assert.ok(og[0].E <= og[0].C + 1e-12, 'бүлгийн E нь өөрийн жин C-ээс хэтрэхгүй');

/* Амьд Багц 2·12F-ийн хэлбэр: 1.3990 нь эцгээ 1.0641 болгож байсан.
 * Жин нь тэнцүү хоёр дэд мөрийн нэг нь 139.9%, нөгөө нь 77% гэвэл
 * таслаагүй үед (1.3990+0.77)/2 = 1.0845 > 1 болно. */
const b2 = [
  { ...leaf({ oid: 30, vol: null, depth: 0 }), group: true },
  leaf({ oid: 31, vol: 142.96, obyem: 200, depth: 1 }),
  leaf({ oid: 32, vol: 142.96, obyem: 110.08, depth: 1 }),
];
const b2c = computeAll(b2, 1, ASOF, {}, {}, [true]);
assert.ok(b2c[1].act[0] > 1, 'дэд мөр 139.9% — ил хэвээр');
assert.ok(b2c[0].act[0] <= 1, 'эцэг бүлэг 100%-иас давахаа болив');
assert.ok(b2c[0].J <= 1, 'мөрийн J мөн адил');

/* ── ОБЬЁМГҮЙ МӨР: хувь нь бодогдох аргагүй тул ХЭВЭЭР ──
 * Мөрийн Обьём нь ЭХ ӨГӨГДЛӨӨС ирдэг тогтмол тоо — энэ хуудаснаас
 * засагдахгүй. Хоосон байвал тэр мөрийн хувь зүгээр л хөдөлгөөнгүй үлдэнэ.
 */
const empty = leaf({ oid: 7, vol: null, act: 0.4 });
c = run([empty], { '7:0': '250' })[0];
assert.equal(c.obyem[0], 250, 'обьём бүртгэгдэнэ');
assert.equal(c.act[0], 0.4, 'хувь нь хуваарьгүй тул хэвээр');

// Обьёмтой мөрд хувь нь тэр дороо бодогдоно.
c = run([leaf({ oid: 7, vol: 1000 })], { '7:0': '250' })[0];
assert.equal(c.act[0], 0.25, '250 / 1000 = 25%');

// Мөнгөн дүн = Обьём × Нэгж өртөг — эх өгөгдлөөс шууд.
c = run([{ ...leaf({ oid: 8, vol: 50 }), unit: 2 }])[0];
assert.equal(c.H, 100, 'H = 50 × 2');
/* ── Бүлгийн мөр: обьём НИЙЛҮҮЛЭХГҮЙ (нэгж нь зөрдөг), хувь нь дундаж ── */
const grp = [
  { ...leaf({ oid: 10, vol: null, depth: 0 }), group: true },
  leaf({ oid: 11, vol: 100, obyem: 50, depth: 1 }),
  leaf({ oid: 12, vol: 100, obyem: 100, depth: 1 }),
];
const g = computeAll(grp, 1, ASOF, {}, {}, [true]);
assert.equal(g[0].obyem[0], null, 'бүлэгт обьём бодогдохгүй');
assert.ok(Math.abs(g[0].act[0] - 0.75) < 1e-9, 'бүлэг = жинтэй дундаж (50% ба 100%)');

console.log('obyem.check: ok');
