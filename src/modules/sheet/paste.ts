/**
 * ОЛОН НҮДНИЙ БУУЛГАЛТ — Excel-ээс хуулсан блокийг хүснэгтийн нүднүүдэд
 * БАЙРЛУУЛАХ цэвэр логик. React-гүй, DOM-гүй — тиймээс тестлэгдэнэ
 * (`paste.check.mjs`).
 *
 * ⚠️ ЯАГААД ТУСДАА ФАЙЛ: энэ логикийн цорын ганц бодит эрсдэл нь ЭГНЭЭ
 * ГУЛСАХ — нэг утга буруу мөрд бичигдвэл хэрэглэгч анзаарахгүй, дараа нь
 * тайлан чимээгүй худал болно. `FillNew` дотор үлдээвэл React-гүйгээр
 * шалгах арга байхгүй.
 */

/** Нэг нүдний зорилт: аль мөрийн индекс, аль блок, ямар утга */
export type PasteHit = { row: number; b: number; v: string };

export type PastePlan = {
  hits: PasteHit[];
  /** Байрлалаа эзэлсэн ч бичигдээгүй нүд (бүлэг, талбаргүй блок, хоосон, хальсан) */
  skipped: number;
  /** Тоо болгож уншигдаагүй утга */
  bad: number;
};

/**
 * Санамсаргүй асар том буулгалтаас хамгаална (жиш. бүтэн хуудас хуулах).
 * ⚠️ Хязгаараас хэтэрсэн хэсэг нь `skipped` болж ТООЛОГДОНО — чимээгүй
 * алга болохгүй, хэрэглэгчид тоогоор нь мэдэгдэнэ.
 */
export const PASTE_MAX_CELLS = 5000;

/**
 * Хавтангийн текстийг 2 хэмжээст сүлжээ болгоно.
 *
 * ⚠️ Excel сүүлд НЭМЭЛТ мөрийн шилжилт тавьдаг — түүнийг хасахгүй бол
 * жагсаалтын төгсгөлд хоосон мөр үүсч, доорх ажил санамсаргүй «алгасагдсан»
 * гэж тоологдоно.
 *
 * ⚠️ ХАШИЛТТАЙ НҮД (TSV, 2026-09-25-ны аудит): Excel мөр шилжилт (Alt+Enter),
 *    таб, хашилт агуулсан нүдийг `"…"`-ээр хүрээлж, доторх `"`-ийг `""`
 *    болгож хуулдаг. Урьд нь `\n` бүрээр тасалдаг тул олон мөрт ганц нүд
 *    («"Суурь\nцутгалт"») нэг мөрийг ХОЁР болгож, доорх БҮХ утга нэг мөр
 *    доошилж БУРУУ ажилд бичигддэг байв — энэ файлын толгойн «хамгийн аюултай
 *    гэмтэл». Одоо хашилт доторх `\n`/`\t` нүдэндээ үлдэнэ.
 * ⚠️ БҮРЭН БИШ хашилт (хаагдаагүй, эсвэл хаах `"`-ийн ард таб/мөр/төгсгөл биш
 *    тэмдэгт ирсэн, жиш. `"abc` · `"12" см`) нь ЭНГИЙН текст — тэр нүд нь
 *    дараагийн таб/мөр хүртэл үсгээрээ уншигдана. Эс бөгөөс ганц `"` нь
 *    санах ойн үлдсэн бүх нүдийг залгиж, байрлал бүхэлдээ гулсана.
 */
export function parseGrid(text: string): string[][] {
  const s = text.replace(/\r\n?/g, '\n').replace(/\n+$/, '');
  const n = s.length;
  const out: string[][] = [];
  let row: string[] = [];
  let i = 0;
  /* Давталт бүр НЭГ нүд уншина: `i` = нүдний эхлэл, `j` = түүний төгсгөл (таб/мөр/төгсгөл) */
  for (;;) {
    let cell: string | null = null;
    let j = i;
    if (s[i] === '"') {
      let buf = '';
      let k = i + 1;
      let closed = false;
      while (k < n) {
        const c = s[k];
        if (c === '"') {
          if (s[k + 1] === '"') { buf += '"'; k += 2; continue; }
          closed = k + 1 >= n || s[k + 1] === '\t' || s[k + 1] === '\n';
          k += 1;
          break;
        }
        buf += c;
        k += 1;
      }
      if (closed) { cell = buf; j = k; }
    }
    if (cell === null) {
      let k = i;
      while (k < n && s[k] !== '\t' && s[k] !== '\n') k += 1;
      cell = s.slice(i, k);
      j = k;
    }
    row.push(cell);
    if (j >= n) { out.push(row); break; }
    if (s[j] === '\t') { i = j + 1; continue; }
    out.push(row);
    row = [];
    i = j + 1;
  }
  return out;
}

/**
 * ТАСЛАЛ НЬ МЯНГАТЫН Ч, АРАВТЫН Ч БАЙЖ БОЛОХ бичлэг — `1,250` · `-12,500`.
 *
 * ⚠️ ЯАГААД (2026-09-25-ны аудит): en-US Excel-ийн `#,##0` формат 1250 м³-ийг
 *    «1,250» гэж хуулдаг; урьд нь эхний таслалыг ҮРГЭЛЖ аравтын цэг гэж үзэж
 *    1.25 (1000 дахин БАГА) болгон ЧИМЭЭГҮЙ бичдэг байв — «тоо биш» ч гэж
 *    тоологдохгүй. Харин ru/mn форматад «1,250» нь үнэхээр 1.25 байж болно.
 *    Аль нь болохыг ТААМАГЛАХГҮЙ — няцааж, хэрэглэгчээр тодруулна.
 * ⚠️ `0,125` (0-ээр эхэлсэн) ба `1234,5` (эхний бүлэг 3-аас урт, эсвэл
 *    таслалын ард 3 биш орон) нь мянгатын бичлэг байж ЧАДАХГҮЙ — аравтын.
 */
export const isAmbiguousComma = (raw: string): boolean =>
  /^-?[1-9]\d{0,2},\d{3}$/.test(raw.trim().replace(/^\+/, ''));

/**
 * Нүдний текстийг тоон мөр болгоно. Тоо биш бол `null`.
 *
 * ⚠️ Excel-ийн мянгатын тасалбар нь энгийн зай БАЙХГҮЙ: NBSP (` `) эсвэл
 * нарийн зай (` `) байдаг. Тэдгээрийг хасахгүй бол «1 234» нь `NaN`
 * болж, хэрэглэгчийн зөв өгөгдөл «тоо биш» гэж хаягдана.
 *
 * ⚠️ Хувийн тэмдэг ба урд талын нэмэх тэмдгийг хасна — `commit`-тэй ижил
 * дүрэм байх ёстой, эс тэгвээс гараар бичихэд зөвшөөрөгддөг утга буулгахад
 * няцаагдана. (2026-09-25-наас `commit` ЭНЭ функцийг шууд дууддаг.)
 *
 * ⚠️ ТАСЛАЛ ба ЦЭГ (2026-09-25-ны аудит — `isAmbiguousComma`-ийн ⚠️):
 *    · хоёулаа байвал СҮҮЛИЙНХ нь аравтын тэмдэг, нөгөө нь мянгат —
 *      `1,234.5` · `1.234,5` → 1234.5; бүлэглэлт буруу бол (`1,2.5`) тоо биш;
 *    · зөвхөн таслал: `1,234,567` (2+ бүлэг) → мянгат; `1,250` → ТОДОРХОЙГҮЙ
 *      тул `null` (буулгалтад «буруу» гэж тоологдож ИЛ мэдэгдэнэ); бусад
 *      (`12,5` · `0,125`) → аравтын.
 */
export function normCell(raw: string): string | null {
  const t0 = raw
    .trim()
    .replace(/[\s  ]/g, '')
    .replace(/^\+/, '')
    .replace(/%$/, '');
  if (t0 === '') return null;
  let t = t0;
  const dot = t.lastIndexOf('.');
  const comma = t.lastIndexOf(',');
  if (dot >= 0 && comma >= 0) {
    if (comma > dot) {
      /* `1.234,5` — цэг мянгат, таслал аравтын */
      if (!/^-?\d{1,3}(\.\d{3})+,\d*$/.test(t)) return null;
      t = t.replace(/\./g, '').replace(',', '.');
    } else {
      /* `1,234.5` — таслал мянгат, цэг аравтын */
      if (!/^-?\d{1,3}(,\d{3})+\.\d*$/.test(t)) return null;
      t = t.replace(/,/g, '');
    }
  } else if (comma >= 0) {
    if (/^-?\d{1,3}(,\d{3}){2,}$/.test(t)) t = t.replace(/,/g, '');
    else if (isAmbiguousComma(t)) return null;
    else t = t.replace(',', '.');
  }
  return Number.isFinite(Number(t)) ? t : null;
}

/**
 * Сүлжээг ХАРАГДАХ мөрүүд дээр байрлуулна.
 *
 * @param grid     `parseGrid`-ийн үр дүн
 * @param vis      харагдах мөрүүдийн ЭХ индексүүд (шүүлт/эвхэлтийн дараах)
 * @param nBld     блокийн тоо (баруун хязгаар)
 * @param startVi  `vis` доторх эхлэх байрлал (зангуу нүдний мөр)
 * @param startB   эхлэх блок
 * @param canWrite (эх мөрийн индекс, блок) → тэр нүдэнд бичиж болох уу
 *
 * ⚠️ БАЙРЛАЛ ХАДГАЛАГДАНА: бичигдэхгүй нүд (бүлгийн мөр, обьёмын талбаргүй
 * блок, хоосон утга) нь байрлалаа ЭЗЛЭЭД утгаа хаяна. Алгасвал доорх бүх
 * утга нэг мөр дээшилж, чимээгүй БУРУУ мөрд бичигдэнэ — энэ бол хамгийн
 * аюултай гэмтэл, учир нь дэлгэц дээр зөв мэт харагдана.
 */
export function planPaste(
  grid: string[][],
  vis: number[],
  nBld: number,
  startVi: number,
  startB: number,
  canWrite: (row: number, b: number) => boolean,
): PastePlan {
  const hits: PasteHit[] = [];
  let skipped = 0;
  let bad = 0;
  let seen = 0;

  for (let gr = 0; gr < grid.length; gr++) {
    const vi = startVi + gr;
    for (let gc = 0; gc < grid[gr].length; gc++) {
      seen += 1;
      /* Хамгаалалтын дээд хязгаар — үлдсэнийг «алгасав» гэж тоолно */
      if (seen > PASTE_MAX_CELLS) { skipped += 1; continue; }
      const b = startB + gc;
      /* Хүснэгтийн доод/баруун ирмэгээс хальсан */
      if (vi >= vis.length || b >= nBld) { skipped += 1; continue; }
      const row = vis[vi];
      if (!canWrite(row, b)) { skipped += 1; continue; }
      const t = normCell(grid[gr][gc]);
      if (t === null) {
        /* ⚠️ ХООСОН нүд нь «устга» ГЭСЭН УТГАГҮЙ — алгасна. Excel-ийн блокт
           хоосон нүд элбэг тохиолддог тул устгал гэж үзвэл бөглөсөн өгөгдөл
           бөөнөөрөө арилна. Тоо биш утгыг тусад нь тоолно. */
        if (grid[gr][gc].trim() === '') skipped += 1;
        else bad += 1;
        continue;
      }
      /* ⚠️ СӨРӨГ утгыг ЧИМЭЭГҮЙ 0 болгохгүй (2026-09-03-ны аудит): урьд нь
         `Math.max(0, …)` нь «−5»-ыг 0 болгодог байсан бөгөөд «БУУРНА»
         баталгаажуулалт нь `stored != null` шаарддаг тул ХООСОН нүдэнд
         буулгасан сөрөг тоо ямар ч асуултгүйгээр «хэмжигдсэн 0» болж
         бичигддэг байв — `null ≠ 0` дүрмийн шууд зөрчил. Одоо тоо биш
         утгатай нэг зэрэгт «буруу» гэж тоологдоно. */
      if (Number(t) < 0) { bad += 1; continue; }
      hits.push({ row, b, v: String(Number(t)) });
    }
  }
  return { hits, skipped, bad };
}
