//
// 2-р мөрийн шошго нь блокийн ЦУВААГААР (F5 / F6 / F29) хуваагддаг — тэр нь
// барилгын төрөл (9 эсвэл 12 давхар). Багц 4.2·9F-д хоёулаа нэг хуудсанд бий,
// excel-д ч яг тэгж хуваасан байдаг.

/** Цуваа (`bld` шошгын «5/1»-ийн 5) → хэрэглэгчид харагдах барилгын нэр. */
export const SERIES_LABEL: Record<string, Record<string, string>> = {
  b1_9f: { "5": "71 айл 9 давхар" },
  b1_12f: { "29": "117 айл 12 давхар" },
  b2_9f: { "5": "71 айл 9 давхар" },
  b2_12f: { "29": "117 айл 12 давхар" },
  b31_9f: { "5": "71 айл 9 давхар" },
  b32_9f: { "5": "71 айл 9 давхар" },
  b33_9f: { "5": "71 айл 9 давхар" },
  b41_9f: { "5": "71 айл 9 давхар" },
  // ⚠️ Багц 4.2·9F — цорын ганц хос цуваатай хуудас: F5 нь 6 ширхэг 9 давхар,
  //    F6 нь 8 ширхэг 12 давхар. Excel-д ч 2-р мөр яг ингэж хоёр хуваагддаг.
  b42_9f: { "5": "71 айл 9 давхар", "6": "71 айл 12 давхар" },
  b42_12f: { "6": "71 айл 12 давхар" },
};

export type Band = { label: string; count: number };

/**
 * Блокийн жагсаалтыг цуваагаар нь дараалсан бүлгүүд болгоно.
 * `["5/1","5/2","6/1"]` → `[{«…9 давхар», 2}, {«…12 давхар», 1}]`
 */
export function seriesBands(pkgKey: string, bld: string[]): Band[] {
  const map = SERIES_LABEL[pkgKey] ?? {};
  const out: Band[] = [];
  for (const b of bld) {
    const s = b.split("/")[0];
    const label = map[s] ?? `${s}-р цуваа`;
    const last = out[out.length - 1];
    if (last && last.label === label) last.count++;
    else out.push({ label, count: 1 });
  }
  return out;
}
