// ЯГ ИЖИЛ (10/10 багц дээр шалгасан) — ялгаа нь зөвхөн толгойн дүрслэл:
//
//   1-р мөр   Ажил гүйцэтгэл (N барилга) │ Төлөвлөгөөт гүйцэтгэл │ Хуваарь
//   2-р мөр   71 айл 9 давхар            │ 71 айл 12 давхар      │ …
//   3-р мөр   5/1  5/2  5/3 …            │ 5/1 барилга …         │ 5/1 барилга
