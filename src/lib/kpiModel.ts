/** Нэг үзүүлэлт — ангиллын дотор нэг карт */
export type Metric = {
  key: string;
  cat: CategoryKey;
  label: string;
  /** Гол тоо/дүгнэлт */
  value: string;
  /** Тайлбар мөр — «яагаад» эсвэл задаргаа */
  note: string;
  level: Level;
  /** Дарахад очих харагдац. Байхгүй бол карт нь зөвхөн уншигдана. */
  view?: ViewKey;
  /**
   * Баруун талын жижиг график.
   * ⚠️ ЗӨВХӨН бодит цуваа/харьцаа байвал. Хоосон зайг дүүргэх зорилгоор хиймэл
   * дүрс ХЭЗЭЭ Ч зурахгүй — чимэглэлийн график нь өгөгдөл мэт уншигдана.
   */
  chart?: ReactNode;
  /** Зөвхөн АЛДААТАЙ үзүүлэлтэд — карт дарахад дахин татна */
  retry?: () => void;
  /**
   * ЗӨВХӨН CEO-д. Хотын даргын харагдацад ГАРАХГҮЙ.
   *
   * ⚠️ Эдгээр нь бүгд ҮЙЛ АЖИЛЛАГААНЫ нарийвчлал — багц, тайлан, хүснэгтийн
   * түвшний зүйлс. Дарга тэдгээрээр шийдвэр гаргадаггүй бөгөөд тэдгээр нь
   * түүний эрх мэдлээр ч шийдэгддэггүй.
   */
  ceoOnly?: true;
};

/** Тухайн үзэгчид харагдах эсэх */
export const forAudience = (m: Metric, a: Audience): boolean =>
  a === 'ceo' || !m.ceoOnly;

/**
 * Ангилалд харьяалагдах үзүүлэлтүүд, эрэмбэлсэн байдлаар.
 * ⚠️ Эрэмбэ нь `levelRank` — улаан эхэнд. Ижил түвшинд БАНЬСАН дараалал
 *    (тодорхойлсон дараалал) хадгалагдана: `sort` нь тогтвортой.
 */
export function byCategory(
  metrics: readonly Metric[],
  cat: CategoryKey,
  rank: (l: Level) => number,
): Metric[] {
  return metrics.filter((m) => m.cat === cat).sort((a, b) => rank(a.level) - rank(b.level));
}
