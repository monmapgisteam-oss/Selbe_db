/**
 * Үзүүлэлтийн түлхүүрээс зангилаа.
 *
 * ⚠️ ТАНИГДААГҮЙ түлхүүр `undefined` буцаана — `null` (хамрах хүрээ) -ээс
 * ЯЛГААТАЙ. Дуудагч тал шинэ үзүүлэлтийг чимээгүй хаяхгүй, «зураглалгүй» гэж
 * ялгаж чадна.
 */
export function nodeOf(key: string): SchemId | null | undefined {
  /* ⚠️ Нормын биелэлт нь бүс тутам НЭГ үзүүлэлт (`plan:far`, `plan:bcr`…) —
     тоо нь өгөгдлөөс хамаарна тул нэг бүрчлэн жагсаах боломжгүй. */
  if (key.startsWith('plan:')) return 'tolovlolt';
  return KPI_NODE[key];
}

/**
 * ХУУЧИРСАН СХЕМ-МЕТРИК — үзүүлэлт нь түүнийг ОРЛОНО.
 *
 * ⚠️ 2026-09-06-ны согог: дэлгэрэнгүй самбарт «Барилга угсралт» зангилаа
 * `buildSchem`-ийн «Гүйцэтгэл 4%» ба `execMetrics`-ийн «Барилга угсралтын
 * гүйцэтгэл 3.8%» ХОЁУЛАНГ зэрэг үзүүлж байв — нэг зүйлийн тухай ХОЁР өөр тоо
 * зэрэгцэн зогсох нь хэрэглэгчийн итгэлийг шууд эвдэнэ.
 *
 * ⚠️ АЛЬ НЬ ҮНЭН БЭ: `execMetrics`-ийнх. `progress` нь `buildProgressOf`
 * (блокоор жигнэсэн) — хэрэглэгч 2026-08-24-нд гурван өрсөлдөгч тооноос яг
 * үүнийг АЛБАН ЁСНЫ гэж сонгосон. `buildSchem`-ийн `overall.pct` нь өөр
 * аргачлалтай тул схемийн харагдацдаа үлдэнэ, нүүрэнд ОРОХГҮЙ.
 *
 * ⚠️ ШОШГООР тааруулна — `Metric` (schem) нь id-гүй, цорын ганц түлхүүр нь
 * `label`. Схемийн шошго өөрчлөгдвөл орлуулалт ЧИМЭЭГҮЙ ажиллахаа болино;
 * `kpiNodes.check.mjs` нь шошго бүр схемд БАЙГАА эсэхийг шалгадаг.
 */
export const SUPERSEDES: Record<string, readonly string[]> = {
  /* «Гүйцэтгэл» (schem, overall.pct) ← «Барилга угсралтын гүйцэтгэл» */
  progress: ['Гүйцэтгэл'],
  /* «Тайлангүй блок» (schem, ихэвчлэн null) ← «Тайлан ирээгүй блок» */
  missing: ['Тайлангүй блок'],
  /* «Хүлээгдэж буй» (schem, тоо) ← «Хяналтад хүлээгдэж буй ажил» (хугацаа) */
  review: ['Хүлээгдэж буй'],
  /* «Хуваарийн хамралт» (schem, ҮРГЭЛЖ null) ← «Хуваарийн биелэлт» */
  schedule: ['Хуваарийн хамралт'],
};

/** Тухайн зангилаанд орлуулагдсан схем-метрикийн шошгууд */
export function supersededLabels(keys: readonly string[]): Set<string> {
  const out = new Set<string>();
  for (const k of keys) for (const l of SUPERSEDES[k] ?? []) out.add(l);
  return out;
}
