import type { LayerDef } from './layerDef';
import { LAYER_BY_ID, ZONE_LAYER } from './layers';

/* ⚠️ Хуучин `DEFAULT_VISIBLE` (зөвхөн бүс) устгагдсан — хаана ч уншигддаггүй
   болсон. Анхны давхаргын ГАНЦ эх сурвалж нь `INITIAL_MAP_LAYERS`. */

/* ══════════════════════ Зурах дараалал ══════════════════════ */

/**
 * Талбай → шугам → цэг.
 *
 * ⚠️ Каталогийн дарааллаар зурвал «Зам (талбай)» нь «Дугуйн зам», «Гүүр»
 * (шугам)-ыг бүрэн дардаг — хэрэглэгч давхаргаа асаасан ч зурагт юу ч
 * өөрчлөгдөхгүй мэт харагдана.
 */
export const drawOrder = (id: string): number => {
  // Замын шугам (Бусад мэдээлэл) — ХАМГИЙН ДООР (бусад давхаргын дор суурь).
  if (id === "road" || id === "roadOld") return -2;
  // Бүс бол АГУУЛАГЧ — хамгийн доор (барилга нь дүүргэлтийнх нь дээр гарна).
  if (id === ZONE_LAYER.id) return -1;
  // ⚠️ «Гол» (ус, `sb:16`) — талбай ч гэсэн зам/гүүр/барилгын ДОР суурь болно
  //    (гүүр усны ДЭЭГҮҮР гарна). Эс бөгөөс массивын дараалалд ус бүхнийг дарна.
  if (id === "sb:16") return -0.5;
  /**
   * ЯВГАН ХҮНИЙ ЗАМ — бусад ТАЛБАЙН давхаргын ДЭЭР, шугамын ДООР
   * (2026-09-15, хэрэглэгч: «ерөнхий төлөвлөгөөний зураг дээр явган хүний
   * зам харагдахгүй байна»).
   *
   * ⚠️ Массивын дараалал хангалтгүй: `nogoon` (ногоон байгууламж) нь
   * `LAYERS`-т `et:27`-оос ХОЙШ бичигдсэн бөгөөд хоёулаа `area` (0) тул
   * ногоон нь явган замыг бүрэн дардаг байв. Массивын байрлалыг зөөх нь
   * бусад давхаргын харьцангуй эрэмбийг чимээгүй өөрчилнө — тиймээс ЭНД,
   * ил дүрмээр.
   */
  if (id === "et:27") return 0.5;
  const g = LAYER_BY_ID[id]?.geom;
  return g === "point" ? 2 : g === "line" ? 1 : 0;
};

