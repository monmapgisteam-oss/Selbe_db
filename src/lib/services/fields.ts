/**
 * № НҮДИЙГ НОРМЧЛОХ ЦОРЫН ГАНЦ ДҮРЭМ — үе шатын мөрийг таних цорын ганц эх.
 *
 * ⚠️ ЯАГААД ЭНЭ ФУНКЦ БАЙХ ЁСТОЙ ВЭ (2026-09-04-ний аудит): нэг ижил зүйлийг
 *    ГУРВАН өөр дүрмээр шалгаж байсан —
 *      `negtgelWrite`  : `dugaar = N'Б.'`            (ЯГ ТЭНЦҮҮ)
 *      `sheetRows`     : `dugaar LIKE N'Б.%'`        (цэгтэй л бол)
 *      `blockProgress` / `BuildingPanel` : `=== 'Б.'` (нормчилсны дараа)
 *    Бодит өгөгдөлд № нүд ГУРВАН хэлбэртэй: «Б. БАРИЛГА УГСРАЛТЫН АЖИЛ»
 *    (8 багц), «Б» ЦЭГГҮЙ (Багц 2·12F, Багц 3.2·9F), «Б1»…«Б5» (дэд үе шат).
 *    Үр дүнд: ЯГ ТЭНЦҮҮ хайлт 10/10 багцад 0 мөр өгч, батлагдсан гүйцэтгэл
 *    нэгтгэлд ХЭЗЭЭ Ч ордоггүй байв; LIKE хайлт нь цэггүй хоёр багцыг алдаж,
 *    тэдгээрийн блокууд газрын зурагт «мэдээлэлгүй» болдог байв.
 *
 * ⚠️ «Б1»…«Б5» нь ДЭД үе шат тул НИЙТ мөрд ХЭЗЭЭ Ч тооцогдохгүй: үсгийн ард
 *    ЦИФР ирвэл нормчлол огт хийгдэхгүй (тэдгээр нь өөрсдийн кодоороо үлдэнэ).
 *    Мөн «Б2.1», «Б3.1» гэсэн Багц 3.1-ийн дэд мөрүүд ч ижил шалтгаанаар
 *    хөндөгдөхгүй.
 *
 *   «Б»                        → «Б.»
 *   «Б.»                       → «Б.»
 *   «Б. БАРИЛГА УГСРАЛТЫН АЖИЛ» → «Б.»
 *   «А»                        → «А.»   (үе шат таних тул `levelFromNo` = 1)
 *   «Б1» · «Б2.1» · «3.2» · «7» → өөрчлөгдөхгүй
 */
export const normalizeTaskNo = (raw: unknown): string => {
  const s = String(raw ?? '').trim();
  // үсэг + (цэг | зай | мөрийн төгсгөл) — цифр залгасныг ОГТ хөндөхгүй
  const m = /^([A-Za-zА-Яа-яӨөҮү])(?:\.|\s|$)/.exec(s);
  return m ? `${m[1]}.` : s;
};

/** Энэ мөр нь БАРИЛГА УГСРАЛТЫН НИЙТ ажил мөн үү (дэд үе шат ОРОХГҮЙ)? */
export const isConstructionNo = (raw: unknown): boolean =>
  normalizeTaskNo(raw) === TASK_SHEET.constructionNo;

/**
 * НИЙТ мөрийг барих ArcGIS SQL предикат — `normalizeTaskNo`-ийн серверийн тал.
 *
 * ⚠️ `LIKE N'Б%'` БОЛОХГҮЙ: тэр нь «Б1»…«Б5» дэд үе шатуудыг ЗЭРЭГ барьж,
 *    нэгтгэлд буруу мөр бичигдэнэ (амьд distinct-ээр батлав). Тиймээс цэгтэй
 *    хэлбэрийг LIKE-ээр, цэггүй хэлбэрийг ЯГ ТЭНЦҮҮГЭЭР — хоёуланг нь.
 */
export const constructionWhere = (field: string): string => {
  const letter = TASK_SHEET.constructionNo.replace(/\./g, ''); // «Б.» → «Б»
  return `(${field} = N'${letter}' OR ${field} LIKE N'${letter}.%')`;
};

/**
 * Багцын нэр гурван эх сурвалжид гурван янз бичигдсэн:
 *   барилгын давхарга «Багц 4.1» · нэгтгэсэн хүснэгт «Багц 4-1» · master «БАГЦ-4-1»
 * Тэмдэгт/хоосон зайг хасаж том үсгээр жиших — гурвуулаа «БАГЦ41» болно.
 *
 * ⚠️ Багцгүйгээр блокийн нэрээр ганцаар жиших БОЛОХГҮЙ: «5/1» долоон багцад
 * тус бүрдээ өөр БОДИТ барилга (Багц 1-ийн 5/1 ≠ Багц 2-ын 5/1).
 */
export const bagtsKey = (v: unknown) =>
  String(v ?? "")
    .toUpperCase()
    .replace(/[^0-9А-ЯӨҮA-Z]/g, "");

/**
 * ОЛОН БАГЦЫГ ХАМАРСАН мөр мөн үү («БАГЦ 1-4», «БАГЦ 1-6\nБАГЦ 8-17»)?
 *
 * ⚠️ 2026-08-18: `bagtsKey` нь ЦЭГ, ЗУРААС, ЗАЙГ БҮГДИЙГ хаядаг — «Багц 4-1» ба
 * «Багц 4.1»-ийг тааруулахын тулд ЗААВАЛ ийм байх ёстой. Гэвч тэр дүрэм нь
 * ДИАПАЗОН бичиглэлийг ч нурааж, «БАГЦ 1-4» → «БАГЦ14» болгодог — энэ нь бодит
 * дэд бүтцийн багц «Багц 14»-ийн ЯГ түлхүүр. Үр дүнд Cashflow-гийн ТЭЗҮ 1–4
 * зураг төслийн гэрээ (2.23 тэрбум ₮) «Багц 14 · Дулаан хангамжийн нэвтрэх
 * суваг»-т наалдаж, тэр багц «санхүү бүртгэлгүй» гэхийн оронд ХУДАЛ гүйцэтгэл
 * харуулдаг байв.
 *
 * Тиймээс багц↔гэрээ тааруулах бүх газар (Санхүүжилт, Барилгын цогц хяналт)
 * диапазон мөрийг ЭНЭ шалгуураар ЭХЛЭЭД хасна. Диапазоны дүнг тодорхой нэг
 * багцад хуваарилах боломжгүй тул алдагдахгүй — зүгээр л буруу эзэнд очихгүй.
 */
export const isPkgRange = (v: unknown) => {
  const s = String(v ?? "").trim();
  // Олон мөрт нүд («БАГЦ 1-6» + шинэ мөр + «БАГЦ 8-17») — аль нэгд нь ч хамаарахгүй
  if (/[\r\n]/.test(s)) return true;
  // Таслалаар жагсаасан («БАГЦ-6.1, 6.2»)
  if (s.includes(",")) return true;
  // «БАГЦ 1-4», «БАГЦ 1- 4» — ТООН ДИАПАЗОН.
  // ⚠️ Дэд багцыг диапазонтой АНДУУРЧ БОЛОХГҮЙ. Үйлчилгээний бодит утгуудыг
  //    шалгасан (Cashflow /106): дэд багц нь ҮРГЭЛЖ ЦЭГТЭЙ («БАГЦ-3.1»,
  //    «БАГЦ-16.7», «БАГЦ - 19.1»), диапазон нь ЗУРААСТАЙ бөгөөд тоо нь ӨСНӨ.
  //    Нэмэлт хамгаалалт болгож өсөх дарааллыг шаардана — ингэснээр «Багц 4-1»
  //    хэлбэрийн дэд багц (4 > 1) орж ирсэн ч диапазон гэж тооцогдохгүй.
  const m = s.match(/(\d+)\s*[-–—]\s*(\d+)\s*$/u);
  return m != null && Number(m[2]) > Number(m[1]);
};

/**
 * Гэрээний мөрөөс БАГЦЫН түлхүүр. Диапазон/жагсаалт мөрд ХООСОН мөр буцаана —
 * багцын түлхүүрүүд хэзээ ч хоосон биш тул ийм мөр аль ч багцад наалдахгүй.
 * Багц↔гэрээ тааруулах бүх газар `bagtsKey`-ийн ОРОНД энийг хэрэглэнэ.
 */
export const pkgKeyOf = (v: unknown) => (isPkgRange(v) ? "" : bagtsKey(v));

