/** Хоосон/тоо биш → `null`. ⚠️ 0 нь жинхэнэ тэг — `null` БИШ. */
export const num = (v: unknown): number | null => {
  if (v == null || v === "") return null;
  const x = Number(v);
  return Number.isFinite(x) ? x : null;
};

