export type LayerDef = {
  /** Порталын доторх id — `et:<FeatureServer-ийн давхаргын дугаар>` */
  id: string;
  /** FeatureServer доторх давхаргын дугаар */
  n: number;
  title: string;
  topic: TopicKey;
  geom: "area" | "line" | "point";
  hue: string;
  /** Зураасны хээ — ижил гэр бүлийн шугамуудыг ялгана */
  dash?: "solid" | "dash" | "dot" | "dash-dot" | "long-dash";
  width?: number;
  fill?: number;
  marker?: "circle" | "square" | "diamond";
  size?: number;
  /**
 * Полигоны ХҮРЭЭНИЙ өнгө — өгөөгүй бол `hue` (дүүргэлттэй ижил).
   *
   * ⚠️ Урьд нь хүрээ ҮРГЭЛЖ `hue`-тэй ижил байсан тул эх үйлчилгээнд
   * ялгаатай хүрээтэй давхаргууд (ДХТ: дүүргэлт өнгөт, хүрээ саарал `#6e6e6e`;
   * Ариутгах татуургын худаг: дүүргэлт `#4ce600`, хүрээ хар ногоон `#267300`)
   * ArcGIS-ийн эх харагдацаас ЗӨРДӨГ байв.
   */
  stroke?: string;
  /** Полигоны хүрээний ХЭЭ — Холбооны худаг эх зурагт ТАСАРХАЙ хүрээтэй */
  strokeDash?: "solid" | "dash" | "dot" | "dash-dot" | "long-dash";
  /**
   * ЭХ ҮЙЛЧИЛГЭЭНИЙ СИМБОЛЫГ ЯГ ТЭР ХЭВЭЭР зурна (2026-09-14, хэрэглэгчийн
   * «яг энэ map шиг харагдацтай болго»).
   *
   * ⚠️ Энэ туг асаалттай давхаргад порталын ХОЁР загварчлалын залруулга
   * ХЭРЭГЛЭГДЭХГҮЙ: (1) `OUTLINE_SCALE` (бүх хүрээг 0.55 дахин нарийсгах),
   * (2) шугамын доорх бараан CIM ХҮРЭЭЛЭЛ (casing). Тэр хоёр нь ортофото дээр
   * уншигдац сайжруулах зорилготой ч эх ArcGIS зурагт БАЙХГҮЙ тул өнгө, зузаан,
   * тунгалаг гурвуулаа зөрүүтэй харагдуулдаг байв.
   *
   * ⚠️ Тиймээс зөвхөн эх зургаас өгөгдлөө бүрэн авсан давхаргад тавина
   * (одоогоор `infra:*`). Бусад давхаргад тавивал тэд ортофото дээр
   * уусах эрсдэлтэй — хүрээлэл нь тэднийг дэвсгэрээс таслах ганц хэрэгсэл.
   */
  srcSym?: true;
  /**
   * НЭВТРЭЛТ ШААРДЛАГАТАЙ давхарга (2026-09-15) — үйлчилгээ нэргүй хэрэглэгчид
   * асуулгыг хаасан (`allowAnonymousToQuery: false`).
   *
   * ⚠️ ЯАГААД ТУГ ХЭРЭГТЭЙ ВЭ: ийм давхарга токенгүй асуухад АЛДАА БИШ, ХООСОН
   * хариу өгдөг. SDK нэвтрэлтийн шаардлага (499) авахгүй тул `IdentityManager`
   * токеныг ӨӨРӨӨ залгадаггүй — газрын зурагт ганц ч цэг гарахгүй. Туг
   * тавьсан давхаргад `MapCanvas` зураг, томруулалт, товшилтын асуулга
   * гурвуулаа нэвтэрсэн хэрэглэгчийн эрхээр явна.
   * ⚠️ 2026-10-09 (аудит №2): зургийн давхаргад токеныг `customParameters`-д ХАДАХАА
   *    БОЛИВ (хуучирч 498 өгдөг, GET URL-д ордог байв) — `MapCanvas` давхарга бүрийн
   *    URL-д `esriId.getCredential(url, { prompt: false })`-ээр итгэмжлэл бүртгэж, SDK
   *    шинэчлэгдсэн токеныг өөрөө залгана (`authedLayers`-ийн ⚠️).
   *
   * ⚠️ `CATALOG_LAYER_IDS`-д БҮҮ оруул: давхаргын тооллого (`totals.ts`)
   * токенгүй явдаг тул каталогт «0» гэж ХУДАЛ харагдана.
   */
  auth?: true;
  /** Зөвхөн ойртоход зурагдана (олон мянган объекттой давхарга) */
  minScale?: number;
  qty?: Quantity;
  /** Ангиллын задаргаа — дашбоардад багана болж, дарахад зурагт шүүнэ */
  facets?: { field: string; label: string }[];
  /**
   * КАТАЛОГТ анхны ангиллаараа задарна — зүүн баганад давхаргын доор дэд мөр
   * болж гарч, дарахад зурагт тэр төрөл нь шүүгдэнэ.
   *
   * ⚠️ Зөвхөн ЦӨӨН УТГАТАЙ ангилалд. Каталогийн багана нь навигаци тул 40 дэд
   * мөр гарвал бусад давхарга хэдэн дэлгэц доор үлдэнэ. Мөн давхарга бүрт
   * тусдаа ArcGIS хүсэлт явна — 29 давхаргад бүгдэд нь тавьбал каталог
   * нээгдэхэд 29 нэмэлт хүсэлт явна.
   */
  catalogFacet?: true;
  /**
   * Ангиллаар ӨНГӨ ялгах (≤6 утгатай ТЕКСТ талбарт).
   *
   * ⚠️ `values` нь ГАЗРЫН ЗУРГИЙН палитр — тэнд ангиллуудыг ЗОРИУДААР нэг өнгө
   * рүү нийлүүлж болно (жиш. бүсийн 5 төрлийг «чухал/суурь» гэсэн 2 өнгө болгох).
   * Диаграмд тэр нь АЛДАА болно: 5 зүсмэг 2 өнгөтэй гарч ялгагдахаа болино.
   * Тийм давхаргад `chartValues`-ыг өгч диаграмын ТУСДАА палитрыг зааж өгнө.
   */
  paint?: {
    field: string;
    values: Record<string, string>;
    /**
     * ТҮҮХИЙ УТГЫН ХҮНИЙ НЭР (2026-09-15) — тоон кодтой талбарт ЗААВАЛ.
     *
     * ⚠️ Ихэнх давхаргад утга нь өөрөө нэр («Дулааны эх үүсвэр») тул энэ
     * шаардлагагүй. Харин `Code = 1|2` мэт кодод тайлбар байхгүй бол
     * тайлбарын хэсэг, шүүлтийн жагсаалт хоёулаа «1», «2» гэж гарна.
     */
    labels?: Record<string, string>;
    /**
     * ЭНЭ ЗАГВАР WEBMAP-ЫН СНАПШОТААС ДАВАМГАЙЛАХ УУ (2026-09-15).
     *
     * ⚠️ Анхдагчаар `false`: ихэнх давхаргад эх webmap-ийн загвар нь
     * ЗӨВ бөгөөс илүү нарийн (текстур, bloom). Зөвхөн каталогийн ангилал
     * нь webmap-д БАЙХГҮЙ мэдээлэл өгч байгаа үед (жиш. `Code` талбарын
     * хоёр төрөл) ил `true` тавина.
     */
    force?: boolean;
    emptyLabel: string;
    /**
     * `values`-д ОРООГҮЙ утгын өнгө (2026-10-08). Заагаагүй бол саарал (`ZONE_TYPE_EMPTY_HUE`).
     * ⚠️ Кран: ЗӨВХӨН «Буусан» саарал байх ёстой — төлөв хоосон/шинэ утгатай кран
     * саарал болж «буусан» мэт уншигдахгүйн тулд давхаргын өнгийг өгнө.
     */
    defaultHue?: string;
    /** Диаграмын палитр — заагаагүй бол `values` (зургийнх) хэрэглэгдэнэ */
    chartValues?: Record<string, string>;
  };
  /**
   * ТООН талбарыг завсраар өнгөөр ялгах (гүйцэтгэлийн %).
   * ⚠️ ArcGIS-ийн classBreak нь `minValue`/`maxValue` ХОЁУЛАНГ нь оруулж тоолдог.
   * Самбарын тоолол ба SQL шүүлт нь `>= min AND < max` (хагас нээлттэй) тул
   * дээд хязгаараас багахан хасаж хоёуланг нь тааруулна.
   */
  breaks?: {
    field: string;
    levels: readonly {
      label: string;
      range: string;
      min: number;
      max: number;
      color: string;
    }[];
    emptyLabel: string;
  };
  /**
   * `ZONE_ID` талбар БАЙХГҮЙ давхарга.
   * ⚠️ Бүсийн нэгдсэн шүүлт эдгээрт үйлчлэхгүй — байхгүй талбараар шүүвэл
   * `definitionExpression` бүхэлдээ унаж, давхарга зурагдахаа болино.
   */
  noZone?: true;
  /**
   * Бүсийн кодыг агуулах талбар — анхдагч `ZONE_ID`.
   * ⚠️ БҮСИЙН давхарга өөрөө өөр нэртэй (`RefName_1`) бөгөөд утга нь ч зөрдөг
   * («Багц -1» ↔ «Багц-1»). Тиймээс бүсээр шүүхдээ талбарын нэр ба утга
   * ХОЁУЛАНГ нь давхаргаас хамааруулж угсарна — `zoneWhere()` үүнийг хийнэ.
   */
  zoneField?: string;
  /**
   * ӨӨР үйлчилгээнээс ирэх давхарга — бүтэн URL.
   * ⚠️ Ихэнх давхарга `Selbe_ET_20260721`-ээс ирдэг тул `n`-ээр хаяг угсарна.
   * Барилгын хяналтын хоёр давхарга нь хуучин үйлчилгээнд үлдсэн (шинэ ЕТ-д
   * гүйцэтгэлийн өгөгдөл ОГТ байхгүй) тул хаягаа өөрөө авчирна.
   */
  /**
   * Давхаргын ТОГТМОЛ шүүлт (definitionExpression-ийн суурь).
   * ⚠️ IoT мэдрэгчид: телеметрийн мөр бүр геометрээ ДАВТДАГ (10,000 ижил цэг).
   *    `device_id IS NULL` нь суурилуулалтын ГАНЦ мөрийг үлдээнэ — зурагт
   *    мэдрэгч тус бүр НЭГ цэг болж гарна.
   */
  where?: string;
  url?: string;
  /**
   * ЗАГВАРЫН түлхүүр URL — webmap-style.json-ийн snapshot ХУУЧИН үйлчилгээний
   * хаягаар түлхүүрлэгдсэн. test_data руу шилжихэд `url` шинэчлэгдсэн ч рендерер
   * хайлт ЭНЭ хаягаар хийгдэж хуучин загвар 1:1 хадгалагдана (хэрэглэгчийн
   * шийдвэр, 2026-08-13). Байхгүй бол `layerUrl()` ашиглагдана.
   */
  styleUrl?: string;
  /* ⚠️ 2026-08-24: `cost` ба `costSrc` талбарууд ХАСАГДАВ — `negj_une` дээр
     тогтсон өртгийн загвар бүхэлдээ устсан. `costSrc` нь өртгийн асуулгыг
     ХУУЧИН ET хаягаар явуулах зориулалттай байсан (нэгтгэсэн `data`-д тэр
     талбар байхгүй); загвартайгаа хамт хэрэггүй болов. */
  /**
   * OID талбарын нэр — анхдагч `OBJECTID`.
   * ⚠️ Хуучин үйлчилгээнүүд өөр нэртэй (`FID`, `objectid`). Буруу нэрээр
   * `COUNT()` асуувал хүсэлт бүхэлдээ унана.
   */
  oid?: string;
  /**
   * Ерөнхий (каталогаас автоматаар үүсэх) дашбоардын оронд БЭСПОК самбар.
   * Гүйцэтгэлийн 16 үе шат, Survey123-ийн холбоост хүснэгтүүд зэрэг нь
   * ерөнхий «тоо + хэмжээ + ангилал» загварт багтахгүй.
   */
  detail?: "building"; // ⚠️ 2026-09-17: `"survey"` (mon:survey) төслөөс бүрэн хасагдав
  note?: string;
};

