/**
 * ХАРУУЛАХ ХУГАЦААНЫ ХҮРЭЭ.
 *
 * ⚠️ Шүүлтийг СЕРВЕР талд `where`-ээр хийхгүй: `received_datetime` нь STRING
 * тул огнооны харьцуулалт бичиглэлээс хамаарч чимээгүй хоосон буцаах эрсдэлтэй.
 * Оронд нь эрэмбэлээд ХАНГАЛТТАЙ мөр татаад клиент дээр огтолно.
 *
 * ⚠️ `limit` нь ЗАДАРСАН заалтын бодит алхам (≈60 мин) дээр биш, ТҮҮХИЙ мөрийн
 * урсгал дээр тооцоологдсон: түүхий мөр багцаар ирдэг тул хугацааны нэгжид
 * ногдох мөр нь заалтын тооноос хамаагүй их. Нөөцтэй авсан — хүрээ дүүрэхгүй
 * бол цуваа чимээгүй тасарна.
 */
export type RangeKey = '24h' | '7d' | '30d';

export const RANGES: { key: RangeKey; label: string; hours: number; limit: number }[] = [
  { key: '24h', get label() { return tr('24 цаг'); }, hours: 24, limit: 400 },
  { key: '7d', get label() { return tr('7 хоног'); }, hours: 24 * 7, limit: 1400 },
  { key: '30d', get label() { return tr('30 хоног'); }, hours: 24 * 30, limit: 4000 },
];

const rangeOf = (k: RangeKey) => RANGES.find((r) => r.key === k) ?? RANGES[1];

/**
 * ХАМГИЙН БАГА КВАДРАТААР шугаман хандлага — сүүлийн `windowH` цагийн цэгүүдээр.
 *
 * ⚠️ Зөвхөн ХОЁРООС ДЭЭШ цэгтэй, ХАМГИЙН БАГА 1 цагийн зурвасыг хамарсан үед
 * бодно. Богино зурваст налуу нь чимээнээс тэсрэх (хэдхэн минутад 0.1°
 * хэлбэлзэхэд «цагт хэдэн градус» гэж гарна) тул таамаг утгагүй болно.
 */
function fit(points: Reading[], windowH = 24): { perHour: number } | null {
  if (points.length < 3) return null;
  const last = points[points.length - 1].t;
  const from = last - windowH * 3_600_000;
  const w = points.filter((x) => x.t >= from);
  if (w.length < 3) return null;
  const spanH = (w[w.length - 1].t - w[0].t) / 3_600_000;
  if (spanH < 1) return null;
  // x-ийг ЦАГААР авна — налуу нь шууд «нэгж/цаг» болно
  const xs = w.map((x) => (x.t - w[0].t) / 3_600_000);
  const ys = w.map((x) => x.v);
  const n = xs.length;
  const mx = xs.reduce((a, b) => a + b, 0) / n;
  const my = ys.reduce((a, b) => a + b, 0) / n;
  let num = 0; let den = 0;
  for (let i = 0; i < n; i++) { num += (xs[i] - mx) * (ys[i] - my); den += (xs[i] - mx) ** 2; }
  if (den === 0) return null;
  return { perHour: num / den };
}

/**
 * Босго хүртэл хэдэн цаг үлдсэн вэ.
 * `null` — босгогүй, аль хэдийн давсан, эсвэл хурд нь босгоос ХОЛДОЖ байгаа.
 * ⚠️ 30 хоногоос цааш таамаглахгүй: тийм хол экстраполяци нь тоо болохоос
 *    мэдээлэл биш (хурд нь тэр хооронд олон удаа өөрчлөгдөнө).
 */
function eta(latest: number | null, perHour: number, alert?: { value: number }): number | null {
  if (latest == null || !alert) return null;
  const gap = alert.value - latest;
  if (gap <= 0) return null;            // аль хэдийн давсан
  if (perHour <= 0) return null;        // босго руу ойртохгүй байна
  const h = gap / perHour;
  return h > 24 * 30 ? null : h;
}

/**
 * Цуваанаас ХОНОГИЙН хэрэглээ — хуримтлагдсан тоолуурын зөрүү.
 *
 * ⚠️ 2026-09-21: хоногийн хэрэглээ = (энэ хоногийн СҮҮЛИЙН заалт) − (ӨМНӨХ
 * хоногийн СҮҮЛИЙН заалт). Урьд нь хоног ДОТОРХ max − min байсан тул өмнөх
 * хоногийн сүүлийн заалтаас энэ хоногийн эхний заалт хүртэлх хэрэглээ (шөнийн
 * хэсэг) БҮРМӨСӨН алдагдаж, ганц заалттай хоног «0» гэж худал гардаг байв.
 * Өмнөх заалтгүй (цувааны эхний) хоног ЦЭГГҮЙ — 0 биш, null ≠ 0 (`Reading.v`
 * нь `number` тул null оруулахын оронд цэгийг орхино; график цоорхой үлдээнэ).
 * Тоолуур буцаж тэглэгдсэн (сөрөг зөрүү) хоногийг мөн орхино — 0 гэж зурахгүй.
 * ⚠️ Оролт нь хугацаагаар ӨСӨХ эрэмбэтэй байх ёстой (`loadOne` тэгж өгдөг).
 * ⚠️ ЗӨВХӨН ДАРААЛСАН ХОНОГ (2026-09-25 аудит): заалтгүй хоногийн (декодер
 * алгассан г.м.) дараах хоногт урьд нь ХОЁР+ хоногийн хэрэглээ нэг цэгт
 * нийлж, «хоногийн хэрэглээ» нь хоёр дахин өсөж алдагдал мэт харагддаг байв.
 * Өмнөх заалт нь ӨЧИГДРИЙНХ (локал хуанли) биш бол цэггүй — хуваарилах
 * үндэслэлгүй тул null ≠ 0 дүрмээр цоорхой үлдээнэ.
 * ⚠️ 2026-10-09: хоногийг ХӨТӨЧИЙН локал хуанлиар биш, Asia/Ulaanbaatar-аар (`ubDay`,
 * тогтмол +08:00) хуваана — UTC-тэй машин дээр хоногийн зааг 08:00-д буудаг байв.
 * `tools/iot-verify.mjs` энэ дүрмийг БИЕ ДААН давтана — нэгийг өөрчилбөл нөгөөг дага.
 */
function dailyDiffPoints(points: Reading[]): Reading[] {
  const lastByDay = new Map<number, Reading>();
  for (const r of points) {
    const key = ubDay(r.t);
    const cur = lastByDay.get(key);
    if (!cur || r.t >= cur.t) lastByDay.set(key, r); // хоногийн СҮҮЛИЙН заалт
  }
  const days = [...lastByDay.values()].sort((a, b) => a.t - b.t);
  const out: Reading[] = [];
  for (let i = 1; i < days.length; i++) {
    if (ubDay(days[i].t) !== ubDay(days[i - 1].t) + 1) continue; // цоорхой хоног
    const v = days[i].v - days[i - 1].v;
    if (v >= 0) out.push({ t: days[i].t, v }); // цэг хоногийн сүүлийн мөчид буух нь зөв
  }
  return out;
}

/** Цувааны нэгдсэн үзүүлэлт — суурь ба уламжлал хоёулаа үүгээр бүтнэ */
/* ⚠️ `all` = хүрээгээр огтлоогүй БҮТЭН цуваа (2026-09-17): «сүүлийн заалт»/нас нь
   сонгосон хугацааны хүрээнээс хамаарах ёсгүй — 24 цагийн хүрээнд 1+ хоног хоцорсон
   мэдрэгч «заалт алга» гэж худал сэрэмжлүүлдэг байв. */
/* ⚠️ 2026-10-09: `badAt` — ТҮҮХИЙ мужаас (`rawValid`) гадуурх хамгийн сүүлийн заалтын цаг.
   Тэр нь хамгийн сүүлийнх бол `fault`, `latest = null` (дуугүй биш — `latestAt` бий).
   Физик мужаас (`valid`) гадуурх цэг ЧАРТ/доод/дээд/дундаж/хандлагад ОРОХГҮЙ (6553.5%-ийн
   ганц цэг тэнхлэгийг 6,600 хүртэл сунгаж бодит муруйг ёроолд шахдаг байв), харин
   «сүүлийн заалт» болон `fault`-д хэвээр — гэмтлийг нуухгүй. */
function summarize(
  m: Metric, pts: Reading[], total: number | null, all: Reading[] = pts, badAt: number | null = null,
  higherIsGood = false,
): MetricSeries {
  const clean = m.valid ? pts.filter((x) => !outOfRange(m, x.v)) : pts;
  const vals = clean.map((x) => x.v);
  const lastOk = all.length ? all[all.length - 1] : null;
  const badLast = badAt != null && (lastOk == null || badAt > lastOk.t);
  const last = badLast ? null : lastOk;
  const lastAt = badLast ? badAt : (lastOk?.t ?? null);
  /* ⚠️ Тугтай хэмжигдэхүүнд Л хандлага бодно — циклтэй өгөгдөл дээр налуу нь
     тоо гаргах ч утга нь ХУДАЛ (дээрх `forecast`-ийн тайлбарыг үз). */
  const f = m.forecast && !badLast ? fit(clean) : null;
  const a = m.alert;
  /* ⚠️ 2026-10-09: `{...m}` БИШ — `label`/`note` getter-ийг амьдаар нь хадгална (`liveCopy`) */
  return liveCopy(m, {
    /* ⚠️ 2026-10-09: босго давсан оргил сийрэгжүүлэлтэд алдагдахгүй (`thin`-ийн ⚠️).
       «Их нь сайн» (хөрсний чийг) бол эрсдэл нь босгоос ДООШ уналт — тэрийг хадгална. */
    points: thin(
      clean, 90,
      a ? (higherIsGood ? (x: Reading) => x.v < a.value : (x: Reading) => x.v >= a.value) : undefined,
      higherIsGood,
    ),
    latest: last?.v ?? null,
    latestAt: lastAt,
    ageHours: lastAt != null ? (Date.now() - lastAt) / 3_600_000 : null,
    total,
    min: vals.length ? Math.min(...vals) : null,
    max: vals.length ? Math.max(...vals) : null,
    avg: vals.length ? vals.reduce((s2, x) => s2 + x, 0) / vals.length : null,
    trend: f ? { perHour: f.perHour, etaHours: eta(last?.v ?? null, f.perHour, m.alert) } : null,
    fault: badLast || outOfRange(m, last?.v ?? null),
  });
}

/**
 * Нэг мэдрэгч — хэмжигдэхүүн ТУС БҮРД тусдаа query.
 *
 * ⚠️ 2026-08-18: Урьд нь ГАНЦ `where` (эхний хэмжигдэхүүнээр) бүх утгыг хаадаг
 * байв. Хогийн мэдрэгч дээр: зайтай 1,642 мөр, батерейтай 1,725 — зөвхөн
 * батерейтай 83 мөр БҮРМӨСӨН унтардаг байлаа. Үр дүнд «Батерей» карт 5 хоногийн
 * өмнөх 100%-ийг харуулж байхад 31 минутын өмнөх 98% сервер дээр байсан.
 *
 * (Тэр «Батерей» карт 2026-08-21-нд хасагдсан ч ДҮРЭМ нь хэвээр: Mononet-ийн
 * decoder талбар ТУС БҮРД өөр өөр унтардаг тул нэг where нь бусдыг нь хаана.)
 */
async function loadOne(def: SensorDef, range: RangeKey): Promise<SensorLive> {
  const { hours, limit } = rangeOf(range);
  const from = Date.now() - hours * 3_600_000;
  const per = await Promise.all(
    def.metrics.map(async (m): Promise<MetricSeries[]> => {
      const where = `${m.field} IS NOT NULL`;
      const [rows, total] = await Promise.all([
        queryFeatures(def.url, {
          where,
          outFields: ['received_datetime', m.field],
          /* ⚠️ 2026-10-06 (аудит): OBJECTID DESC (ОРУУЛСАН дараалал) — `received_datetime`
             БИШ. Тэр нь String талбар бөгөөд `parseTs`-ийн 2026-09-15-ны ⚠️-ийн дагуу
             `dd/MM/yyyy HH:mm:ss` утга ч ирдэг: мөрийн эрэмбээр «31/01/2026» нь
             «2026-09-…»-ээс ӨМНӨ/ХОЙНО санамсаргүй эрэмбэлэгдэж, хатуу `limit`-тэй
             таталт ХАМГИЙН СҮҮЛИЙН заалтуудыг огтолж орхих эрсдэлтэй байв. Мэдрэгч
             заалтаа ирэх дарааллаар бичдэг тул OID нь хугацаатай нэг чиглэлтэй;
             жинхэнэ хугацааны эрэмбийг доор `parseTs`-ээр КЛИЕНТ дээр гаргана
             (`pts.sort`). OID нь давхцалгүй тул хуудасны заагт давхардахгүй. */
          orderBy: 'OBJECTID DESC',
          limit,
        }),
        // ⚠️ `limit` нь ХАТУУ таг тул татсан мөрийн тоо ≠ нийт. Жинхэнэ тоог
        //    тусад нь асууна — эс бөгөөс «нийт заалт» нь таган дээр зогсоно.
        /* ⚠️ 2026-10-09: унавал `null` («—»), 0 БИШ — «0 цэг» нь «тоолж чадсангүй»-г худал хэлдэг */
        queryCount(def.url, where).catch((): number | null => null),
      ]);

      const pts: Reading[] = [];
      /** Түүхий мужаас гадуурх ХАМГИЙН СҮҮЛИЙН заалтын цаг (`Metric.rawValid`, 2026-10-09) */
      let badAt: number | null = null;
      for (const r of rows) {
        const t = parseTs(r.received_datetime);
        if (t == null) continue;
        const v = r[m.field];
        if (v == null || v === '') continue;
        const raw = Number(v);
        if (!Number.isFinite(raw)) continue;
        /* ⚠️ 2026-10-09: `derive`-ээс ӨМНӨ — хумилт нь 65535-ыг «0%» болгож нуудаг байв */
        if (m.rawValid && (raw < m.rawValid.min || raw > m.rawValid.max)) {
          if (badAt == null || t > badAt) badAt = t;
          continue;
        }
        // ⚠️ Хувиргалтыг ЭНД, ганц газарт — цуваа/агшин/доод/дээд бүгд дагана
        pts.push({ t, v: m.derive ? m.derive(raw) : raw });
      }
      pts.sort((x, y) => x.t - y.t); // ӨСӨХ — Trend зүүнээс баруун тийш уншина
      // ⚠️ ХҮРЭЭГЭЭР огтолно (сервер талд БИШ — дээрх `RangeKey`-ийн тайлбарыг үз)
      const inRange = pts.filter((x) => x.t >= from);

      const out = [summarize(m, inRange, total, pts, badAt, HIGHER_IS_GOOD.has(`${def.key}:${m.key}`))];
      // Хуримтлагдсан тоолуур → ХОНОГИЙН хэрэглээний тусдаа цуваа
      if (m.dailyDiff) {
        /* ⚠️ 2026-09-21: БҮТЭН цуваанаас бодоод дараа нь хүрээгээр огтолно —
           хүрээний эхний хоног өмнөх хоногийн заалтаа (хүрээнээс гадуурх) олж
           хэрэглээтэй гарна; `inRange`-ээс бодвол тэр хоног цэггүй үлдэнэ. */
        const dpAll = dailyDiffPoints(pts);
        const dp = dpAll.filter((x) => x.t >= from);
        out.push(summarize(
          liveCopy(m.dailyDiff, { field: m.field }), // ⚠️ 2026-10-09: getter амьд (`liveCopy`)
          dp,
          dp.length,
          dpAll, // ⚠️ сүүлийн заалт хүрээнээс хамаарахгүй (2026-09-17)
        ));
      }
      return out;
    }),
    // ⚠️ Алдааны ЖИНХЭНЭ мессежийг барина — «Сервис татагдсангүй» гэсэн ерөнхий
    //    мөр нь HTTP 500, эрхийн татгалзал, талбар байхгүй гурвыг ялгагдахгүй
    //    болгодог байв. UI нь энийг хэрэглэгчид ил гаргана (`error`).
  ).catch((e: unknown) => (e instanceof Error ? e.message : String(e)));

  const flat = Array.isArray(per) ? per.flat() : per;
  if (typeof flat === 'string' || !flat) {
    return liveCopy(def, { // ⚠️ 2026-10-09: getter амьд (`liveCopy`)
      series: [],
      lastAt: null,
      ageHours: null,
      n: null,
      stale: false,
      error: typeof flat === 'string' && flat ? flat : tr('Сервис татагдсангүй'),
    });
  }

  const lastAt = flat.reduce<number | null>(
    (acc, m) => (m.latestAt != null && (acc == null || m.latestAt > acc) ? m.latestAt : acc),
    null,
  );

  return liveCopy(def, { // ⚠️ 2026-10-09: getter амьд (`liveCopy`)
    series: flat,
    lastAt,
    ageHours: lastAt == null ? null : (Date.now() - lastAt) / 3_600_000,
    stale: lastAt != null && (Date.now() - lastAt) / 3_600_000 > SENSOR_STALE_H,
    // Мэдрэгчийн нийт заалт — хэмжигдэхүүнүүдийн ХАМГИЙН ИХ нь (нийлбэр биш:
    // ижил мөр олон утга агуулж болно тул нийлбэрлэвэл давхарлана).
    /* ⚠️ 2026-10-09: тооллого унасан хэмжигдэхүүн (`total = null`) тооцоонд орохгүй; бүгд унавал null */
    n: ((xs) => (xs.length ? Math.max(...xs) : null))(flat.map((m) => m.total).filter((x): x is number => x != null)),
  });
}

/**
 * ХУГАЦААТАЙ кэштэй loader — амжилтгүй амлалтыг кэшлэхгүй («дахин оролдох» сэргэнэ).
 *
 * ⚠️ 2026-08-19: TTL нэмэгдэв. Урьд нь амжилттай хариу сешн ДУУСТАЛ кэшлэгддэг
 * байв — мэдрэгчийн заалт мөн чанараараа АМЬД өгөгдөл тул тэр нь буруу: 09:00-д
 * нээсэн таб 15:00 болтол «31 мин өмнө» гэж ногоон өнгөөр хэвтэж, карт нь өөрөө
 * «шинэхэн» гэж зарладаг байлаа. Портал руу буцаж ирэхэд ч дахин татдаггүй.
 * (`live.ts`-ийн KPI-ууд нь өдөрт нэг л өөрчлөгддөг тул тэнд мөнхийн кэш зөв —
 * энэ файлын өгөгдөл ӨӨР шинжтэй.)
 */
function cached<T>(fn: () => Promise<T>, ttlMs = 5 * 60_000): () => Promise<T> {
  let p: Promise<T> | null = null;
  let at = 0;
  /* ⚠️ 2026-10-09: автобусад БҮРТГЭНЭ (хоосон `reads` — хүснэгтийн бичилт хөндөхгүй), тэгснээр
     хэл солих (`dataBus.subscribeLocale → invalidateAll`) ба «Шинэчлэх» товч энэ кэшийг ч хаяна.
     Урьд нь бүртгэлгүй тул алдааны мөр («Сервис татагдсангүй») TTL дуустал хуучин хэлээр үлддэг байв. */
  register(() => { p = null; }, []);
  return () => {
    if (!p || Date.now() - at > ttlMs) {
      at = Date.now();
      const mine = fn();
      p = mine;
      /* ⚠️ Зөвхөн ӨӨРИЙГӨӨ цэвэрлэнэ (`live.ts`-ийн 2026-09-08-ны засвар) */
      mine.catch(() => { if (p === mine) p = null; });
    }
    return p;
  };
}

/**
 * Таван мэдрэгчийг ЗЭРЭГ ачаална.
 * ⚠️ Нэг нь унасан ч бусад нь гарна (`loadOne` алдааг барьж `error` болгоно) —
 * IoT сервис нь порталын бусад хэсэгтэй ӨӨР байгууллагад тул тусад нь унаж болно.
 */
/**
 * Таван мэдрэгчийг ЗЭРЭГ ачаална — ХҮРЭЭ ТУС БҮРД тусдаа кэштэй.
 *
 * ⚠️ Кэш нь хүрээгээр түлхүүрлэгдэнэ: нэг кэш хуваалцвал хэрэглэгч «7 хоног»
 * дараад «24 цаг» руу буцахад TTL дуустал ХУУЧИН хүрээний өгөгдөл гарна.
 */
const byRange = new Map<RangeKey, () => Promise<SensorLive[]>>();

export function loadSensors(range: RangeKey = '7d'): Promise<SensorLive[]> {
  let f = byRange.get(range);
  if (!f) {
    f = cached<SensorLive[]>(() => Promise.all(SENSORS.map((d) => loadOne(d, range))));
    byRange.set(range, f);
  }
  return f();
}
