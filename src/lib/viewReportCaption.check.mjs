/**
 * Тайлангийн хүснэгтийн нэр · тайлбар (`viewReport.captionTables`).
 *   node --experimental-transform-types --import ./tools/ts-alias.mjs src/lib/viewReportCaption.check.mjs
 */
import assert from 'node:assert/strict';
import { captionTables, mergeStatLines } from './viewReport.ts';

const T = (rows) => ({ kind: 'table', head: [], rows });
const out = captionTables([
  T([['Төслийн цар хүрээ', '159.6 га'], ['Эх үүсвэр', '7']]),
  { kind: 'h', level: 3, text: 'ГАЗАР ЧӨЛӨӨЛӨЛТ' },
  { kind: 'p', text: 'төлөв · га' },
  T([['гэрээлсэн', '0.9 га'], ['Бүрэн чөлөөлсөн', '87.6 га'], ['АТД', '0.1 га']]),
  { kind: 'h', level: 1, text: 'Санхүү' },
  T([['Үнэт цаас', '1,348,197,463,311 ₮'], ['Төслийн орлого', '868,428,589,684 ₮'], ['НЗД нөөц', '3 / 5']]),
]);
const txt = out.map((b) => (b.kind === 'table' ? '[T]' : `${b.kind}:${b.text}`));
assert.deepEqual(txt, [
  'p:Хүснэгт 1. Үндсэн үзүүлэлт',
  'p:«Үндсэн үзүүлэлт» хүснэгтэд 2 үзүүлэлтийг харуулав.',
  '[T]',
  'p:Хүснэгт 2. Газар чөлөөлөлт',
  'p:«Газар чөлөөлөлт» хүснэгтэд 3 үзүүлэлтийг харуулав. Нэгж, ангилал: төлөв · га. Хамгийн их нь Бүрэн чөлөөлсөн (87.6 га).',
  '[T]',
  'h:Санхүү',
  'p:Хүснэгт 3. Санхүү',
  'p:«Санхүү» хүснэгтэд 3 үзүүлэлтийг харуулав.',
  '[T]',
]);
/* Шошго мөр («Зам») нь нэр болж хасагдана; мөр бүр өөр нэгжтэй бол «хамгийн их» гарахгүй */
const out2 = captionTables([
  T([['НИЙТ', '114,085 · объект']]),
  { kind: 'p', text: 'Зам' },
  T([['төрөл', '5'], ['км', '36.0'], ['га', '79.8']]),
  { kind: 'p', text: 'Ногоон орчин' },
  T([['Цэцэрлэг', '12 га'], ['Талбай', '30 га'], ['Зам', '4 га']]),
]);
assert.deepEqual(out2.map((b) => (b.kind === 'table' ? '[T]' : b.text)), [
  'Хүснэгт 1. Үндсэн үзүүлэлт',
  '«Үндсэн үзүүлэлт» хүснэгтэд 1 үзүүлэлтийг харуулав.',
  '[T]',
  'Хүснэгт 2. Зам',
  '«Зам» хүснэгтэд 3 үзүүлэлтийг харуулав.',
  '[T]',
  'Хүснэгт 3. Ногоон орчин',
  '«Ногоон орчин» хүснэгтэд 3 үзүүлэлтийг харуулав. Хамгийн их нь Талбай (30 га).',
  '[T]',
]);

/* «Нэр / тоо / нэгж» мөрүүд → хүснэгт (Инженерийн дэд бүтэц); ганц бүлэг хэвээр */
const P = (text) => ({ kind: 'p', text });
const m = mergeStatLines([
  P('Цэвэр ус хангамж'), P('42.2'), P('км'),
  P('Цахилгаан хангамж'), P('37.4'), P('км'),
  P('Хувь'), P('12%'),
  P('Багц 5.1 · ДХТ'),
  P('Ганц'), P('5'),
]);
assert.deepEqual(m.map((b) => (b.kind === 'table' ? b.rows : b.text)), [
  [['Цэвэр ус хангамж', '42.2 км'], ['Цахилгаан хангамж', '37.4 км'], ['Хувь', '12%']],
  'Багц 5.1 · ДХТ', 'Ганц', '5',
]);

/* График: «График N. Нэр» + өгөгдлөөс бодсон тайлбар; гарчиггүй бол өөрийн гарчиг нэр болж дотроос хасагдана */
const C = (spec) => ({ kind: 'chart', spec });
const gc = captionTables([
  { kind: 'h', level: 3, text: 'АГААРЫН ЧАНАР' },
  { kind: 'p', text: 'PM2.5 · мкг/м³' },
  C({ type: 'line', cats: ['07-01', '07-02', '07-03'], series: [{ name: '', values: [30, null, 55] }] }),
  C({ type: 'doughnut', title: 'чөлөөлсөн: 92%', cats: ['чөлөөлсөн', 'Үлдсэн'], series: [{ name: '', values: [92, 8] }], pct: true, hideLabels: [1] }),
  C({ type: 'doughnut', title: '10 барилга', cats: ['Орон сууц', 'Гэр'], series: [{ name: '', values: [7, 3] }] }),
]);
assert.deepEqual(gc.map((b) => (b.kind === 'chart' ? `[C:${b.spec.title ?? ''}]` : b.text)), [
  'График 1. Агаарын чанар',
  '«Агаарын чанар» графикт 3 цэгийн өөрчлөлтийг харуулав (эхлэл 07-01, төгсгөл 07-03). Хамгийн их нь 07-03: 55, хамгийн бага нь 07-01: 30. Сүүлийн утга 07-03: 55. 1 цэг хэмжигдээгүй тул графикт цоорхой үлдсэн. Нэгж, ангилал: PM2.5 · мкг/м³.',
  '[C:]',
  'График 2. чөлөөлсөн: 92%',
  '«чөлөөлсөн: 92%» графикт гүйцэтгэлийн хувийг харуулав: чөлөөлсөн 92%.',
  '[C:]',
  'График 3. 10 барилга',
  '«10 барилга» графикт 2 ангиллын бүтцийг харуулав, нийт 10. Хамгийн их хэсэг нь Орон сууц: 7 (70%).',
  '[C:]',
]);

console.log('✅ viewReport.captionTables — нэр · тайлбар · гарчиг солих · шошго нэр · мөр нэгтгэл · график');
