/**
 * CEO САМБАРЫН БАГЦЫН ШҮҮЛТ — задаргааны хүснэгтийг «Багц» баганаар нь шүүнэ.
 *
 * ⚠️ 2026-09-06, хэрэглэгчийн хүсэлт: нүүрийн бүх тоо ТӨСЛИЙН НИЙТ байсан тул
 * «аль багц гацсан бэ» гэдгийг харахын тулд харагдац бүр рүү тусад нь орох
 * шаардлагатай байв.
 *
 * ⚠️ ЯАГААД ХҮСНЭГТЭЭР ШҮҮДЭГ ВЭ (ачаалагчид `pkg` параметр авдаггүй).
 * `KpiResult`-ийн ГОЛ ТОО нь дүнгээр бодогдсон (56.8 тэрбум ₮ = 10 хуудасны
 * нийлбэр) тул түүнийг эргүүлэн задлах боломжгүй. Харин ЖАГСААЛТ нь мөр тус
 * бүрдээ багцаа агуулдаг — CEO-гийн жинхэнэ асуулт («ЯМАР ажил асуудалтай
 * вэ») тэндээс л хариулагдана. Тиймээс шүүлт нь хүснэгтэд үйлчилнэ, гол тоо
 * нь ТӨСЛИЙН хэвээр — энэ хоёрын ялгааг дэлгэц дээр ИЛ хэлнэ, эс бөгөөс
 * хэрэглэгч «56.8 тэрбум нь энэ багцынх» гэж ХУДАЛ уншина.
 *
 * ⚠️ ЯАГААД ТУСДАА ФАЙЛ ВЭ. Шүүлт нь React-гүй цэвэр функц тул
 * `filter.check.mjs` шууд Node дээр шалгана — «Багцаар» гэсэн НЭГТГЭСЭН
 * хүснэгтийг мөрөөр шүүх (утгагүй), багана олдохгүй үед чимээгүй хоослох зэрэг
 * согогийг шалгуур барина.
 */
import { t as tr } from '@/lib/i18nCore';
import { bagtsKey, isPkgRange } from '@/lib/services';
import type { Cell, DetailTable, KpiResult } from './kpi';

/** «Бүх багц» — шүүлтгүй төлөв */
export const ALL_PKG = '';

/**
 * Хүснэгтийн БАГЦЫН баганы индекс, эс бөгөөс `-1`.
 *
 * ⚠️ ЗӨВХӨН ЭХНИЙ таарсныг авна: зарим хүснэгтэд «Багц» ба «Дэд багц» хоёулаа
 * байж болно, гэхдээ мөрийг эзэмшигч нь эхнийх.
 */
export const pkgColOf = (t: DetailTable): number => t.cols.indexOf(tr('Багц'));

/**
 * Тухайн мөр сонгосон багцад хамаарах уу?
 * ⚠️ `bagtsKey`-ээр жишнэ — «Багц 4-1» · «Багц 4.1» · «БАГЦ-4-1» гурвуулаа нэг
 *    багц (`services.ts`-ийн баримтжуулсан дүрэм). Түүхий текстээр жишвэл
 *    хүснэгт чимээгүй хоосорно.
 */
export const rowInPkg = (row: readonly Cell[], col: number, pkg: string): boolean => {
  const v = row[col]?.v;
  return bagtsKey(v) === bagtsKey(pkg);
};

/**
 * НЭГТГЭСЭН хүснэгт мөн үү («Багцаар» — мөр бүр НЭГ БАГЦЫН дүн)?
 *
 * ⚠️ ЭДГЭЭРИЙГ ШҮҮХГҮЙ, ХАСНА. «Багцаар» хүснэгтийн утга нь БАГЦУУДЫГ ХАРЬЦУУЛАХ
 * явдал; нэг багц сонгоод түүнийг нэг мөр болтол шүүвэл харьцуулах зүйлгүй
 * болж, «Багц 3.2: 107 ажил» гэсэн ганц мөр үлдэнэ — тэр тоо нь дээрх картан
 * дээр аль хэдийн бий. Тиймээс багц сонгосон үед НУУНА.
 */
export const isPkgSummary = (t: DetailTable): boolean => (
  t.cols[0] === tr('Багц')
  && (t.title === tr('Багцаар') || t.title === tr('Багц бүрээр'))
);

/**
 * Нэг хүснэгтийг багцаар шүүнэ. `null` = энэ хүснэгтийг ОГТ харуулахгүй.
 *
 * ⚠️ БАГЦЫН БАГАНАГҮЙ хүснэгтийг ХЭВЭЭР үлдээнэ (`t` буцаана), хоослохгүй.
 * IoT мэдрэгч, тохиромжтой байдлын бүс, ажилтны компани зэрэг нь багцад
 * ХАМААРДАГГҮЙ өгөгдөл — тэднийг «энэ багцад хамаарахгүй» гэж хаявал
 * хэрэглэгч «мэдээлэл алга болов» гэж уншина.
 */
export function filterTable(t: DetailTable, pkg: string): DetailTable | null {
  if (!pkg) return t;
  if (isPkgSummary(t)) return null;
  const col = pkgColOf(t);
  if (col < 0) return t;
  const rows = t.rows.filter((r) => rowInPkg(r, col, pkg));
  /* ⚠️ Хоосон болсон хүснэгтийг ЗУРАХГҮЙ — «(хоосон)» гэсэн толгой нь чимээ */
  return rows.length ? { ...t, rows } : null;
}

/**
 * `KpiResult`-ийг багцаар шүүсэн ХУВИЛБАР.
 *
 * ⚠️ `value`/`facts`/`level` нь ХӨНДӨГДӨХГҮЙ — тэдгээр нь төслийн дүн.
 * Дэлгэц дээр «жагсаалт нь тухайн багцынх, гол тоо нь төслийнх» гэдгийг
 * ил бичих ёстой (`CeoBoard.tsx`).
 */
export function filterResult(r: KpiResult, pkg: string): KpiResult {
  if (!pkg) return r;
  const tables = r.tables.map((t) => filterTable(t, pkg)).filter((t): t is DetailTable => t != null);
  /*
   * ⚠️ АНХААРУУЛГЫГ Ч ШҮҮНЭ: тэдгээр нь «{багц} · {ажил} — …» хэлбэртэй тул
   * багцын нэрийг агуулна. Агуулаагүй бол ҮЛДЭЭНЭ — багцад хамаарахгүй
   * ерөнхий анхааруулга (жиш. «2 багцын хуудас уншигдсангүй») алга болох ёсгүй.
   */
  const key = bagtsKey(pkg);
  const issues = r.issues.filter((i) => {
    const mentions = /Багц/i.test(i.text);
    return !mentions || bagtsKey(i.text).includes(key);
  });
  return { ...r, tables, issues };
}

/**
 * Хүснэгтүүдээс БОДИТООР олдсон багцын нэрс — сонгогчийн жагсаалт.
 *
 * ⚠️ `PKG_GROUPS` (7 барилгын багц) ХАНГАЛТГҮЙ: cashflow-д «БАГЦ-16.7»,
 * «БАГЦ-19.1» гэх мэт дэд бүтцийн олон арван багц бий бөгөөд гацсан ажлын
 * ихэнх нь ЯГ тэнд байдаг. Тиймээс жагсаалтыг АМЬД өгөгдлөөс цуглуулна.
 *
 * ⚠️ `bagtsKey`-ээр давхардлыг арилгана, харин ХАРАГДАХ нэр нь эх бичиглэл
 * (эхэлж таарсан нь) — «БАГЦ-4-1» гэхээс «Багц 4-1» нь уншигдахуйц.
 */
export function pkgOptions(results: readonly KpiResult[]): string[] {
  const seen = new Map<string, string>();
  for (const r of results) {
    for (const t of r.tables) {
      const col = pkgColOf(t);
      if (col < 0) continue;
      for (const row of t.rows) {
        const raw = row[col]?.v;
        if (raw == null || typeof raw === 'number') continue;
        const label = String(raw).trim();
        /* ⚠️ «… бас N мөр» гэсэн ТАСЛАЛТЫН мөр ба «—» нь багц БИШ */
        if (!label || label === '—' || label.startsWith('…')) continue;
        /*
         * ⚠️ ЗӨВХӨН ЖИНХЭНЭ БАГЦЫН НЭР. Хүснэгтийн «Багц» баганад «Багц
         * тодорхойгүй», «БҮХ БАГЦ», «БАГЦ 1-6 БАГЦ 8-17» (диапазон) зэрэг
         * НЭГ багцыг заадаггүй утга ч тохиолдоно. Сонгогчид оруулбал
         * хэрэглэгч тэднийг сонгоод хоосон жагсаалт хардаг.
         *
         * Шалгуур: «Багц» + ТОО (цэг/зураастай дэд дугаар зөвшөөрнө) —
         * «Багц 3.2» ✓ · «БАГЦ - 19.1» ✓ · «Багц тодорхойгүй» ✗ · «БҮХ БАГЦ» ✗.
         * Диапазоныг `isPkgRange` (services.ts-ийн баримтжуулсан дүрэм) хасна.
         */
        if (!/^багц\s*[-–—]?\s*\d/i.test(label) || isPkgRange(label)) continue;
        const k = bagtsKey(label);
        if (!k || seen.has(k)) continue;
        seen.set(k, label);
      }
    }
  }
  /* ⚠️ Байгалийн эрэмбэ: «Багц 2» нь «Багц 10»-ээс ӨМНӨ (үсгийн эрэмбээр бол
     хойно орно). `numeric` сонголт нь «Багц 3.1» ба «Багц 3.2»-ыг ч зөв эрэмбэлнэ. */
  return [...seen.values()].sort((a, b) => a.localeCompare(b, 'mn', { numeric: true }));
}
