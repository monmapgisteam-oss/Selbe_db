export const finXlBandLabel = (name: string, parent: string): string => {
  const n = name.trim();
  const p = parent.trim();
  if (p === '') return n;
  const tail = ` - ${p}`.toLowerCase();
  return n.toLowerCase().endsWith(tail) ? n.slice(0, n.length - tail.length).trim() : n;
};

