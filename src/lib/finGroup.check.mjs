/**
 * БАГЦААР БҮТЭЦЛЭХИЙН ШАЛГУУР — цэвэр функц, сүлжээгүй.
 *   node --experimental-transform-types --import ./tools/ts-alias.mjs src/lib/finGroup.check.mjs
 *
 * Хамгаалж буй алдаанууд:
 *   1. МӨР АЛДАГДАХ. Бүлэглэлт нь зөвхөн ЭРЭМБЭЛНЭ — оруулсан мөрийн тоо
 *      гаралтын тоотой ЯГ тэнцүү байх ёстой. Нийлбэр/шүүлт хийвэл засвар үхнэ.
 *   2. ДИАПАЗОН МӨР БУРУУ ЭЗЭНД. `bagtsKey('БАГЦ 1-4')` = `'БАГЦ14'` нь бодит
 *      «Багц 14»-ийн ЯГ түлхүүр (services.ts-ийн `isPkgRange`).
 *      ⚠️ 2026-09-09-нөөс энэ нь ЗӨВХӨН онолын биш: шинэ `HO_IPC` эх сурвалжид
 *      «Багц-1-4» (876,465,164 ₮) ба «БАГЦ-10,  БАГЦ-11, БАГЦ-13, БАГЦ-15»
 *      (5,094,952,269 ₮) гэсэн ХОЁР диапазон мөр АМЬДААР байна. Хуучин
 *      `IPC_LOG`-д ийм мөр байгаагүй тул хамгаалалт хэрэглэгдэхгүй байв.
 *   3. ДЭД БАГЦ ОВООРОХ. CASHFLOW-д `pkg2` (навч) байхад `pkg`-ийг авбал
 *      «Багц 4.1» ба «Багц 4.2» нэг блок болно.
 *   4. ЭХ ДАРААЛАЛ ЭВДРЭХ. Багц доторх мөрийн дараалал ХАДГАЛАГДАХ ёстой.
 *   5. ОНООР ДЭД БҮЛЭГ ҮҮСЭХ. Хэрэглэгч 2026-09-01-нд «заавал он бүлэглэх
 *      шаардлагагүй» гэсэн — он нь ердийн багана хэвээр байх ёстой.
 *   6. ⚠️ ГРЕЙН НЭГТГЭГДЭХ (ШИНЭ). `HO_IPC`-д нэг гэрээ = ОЛОН мөр (45 мөр =
 *      22 гэрээ). Хэн нэг нь «нэг гэрээ нэг мөр байх нь цэвэрхэн» гэж
 *      нурааж эхэлбэл засвар (`oid:талбар`) үхэж, төлбөрийн мөр алга болно.
 */
import assert from 'node:assert/strict';
import { buildGroups, NO_PKG } from './finGroup.ts';
import { CASHFLOW_NEW, HO_IPC } from './services.ts';

/* ⚠️ 2026-09-06: 'cf' горим ХАСАГДСАН — гэрээний шинэ бүртгэл нь 'flat'.
   ⚠️ 2026-09-09: 'ipc' → 'ho' (HO_guitsetgel /196, олгосон ТӨЛБӨР). */
const CF = CASHFLOW_NEW.fields;
const C = HO_IPC.contractFields;
const P = HO_IPC.payFields;

const cf = (oid, pkg, pkg2, year, o = {}) => ({
  OBJECTID: oid, [CF.pkg]: pkg, [CF.pkg2]: pkg2, [CF.orderDate]: year, ...o,
});
/* ⚠️ HO-д ДЭД БАГЦЫН тусдаа талбар БАЙХГҮЙ — `bagts` ГАНЦААРАА («Багц-3.1»
   гэсэн дэд түвшнийг өөрөө агуулна). Тиймээс хуурамч мөр ч ганц талбартай. */
const ho = (oid, bagts, o = {}) => ({ OBJECTID: oid, [C.pkg]: bagts, ...o });
const total = (out) => out.reduce((a, p) => a + p.count, 0);

/* ── 1. Мөр АЛДАГДАХГҮЙ, дэд багц салангид, ЭХ дараалал ── */
{
  const rows = [
    cf(1, 'БАГЦ-4', 'БАГЦ-4.1', 2026),
    cf(2, 'БАГЦ-4', 'БАГЦ-4.1', 2025),
    cf(3, 'БАГЦ-4', 'БАГЦ-4.1', 2025),
    cf(4, 'БАГЦ-4', 'БАГЦ-4.2', 2025),
  ];
  const out = buildGroups(rows, 'flat');
  assert.equal(total(out), rows.length, 'мөр АЛДАГДААГҮЙ');
  assert.deepEqual(out.map((p) => p.pkg), ['БАГЦ-4.1', 'БАГЦ-4.2'], 'дэд багц салангид');
  assert.deepEqual(out[0].rows.map((r) => r.oid), [1, 2, 3],
    'багц доторх дараалал ЭХ хэвээр — оноор ЭРЭМБЭЛЭГДЭЭГҮЙ');
  assert.equal(out[0].count, 3);
}

/* ── 2. ОНООР дэд бүлэг ҮҮСГЭХГҮЙ ── */
{
  const out = buildGroups([
    cf(1, 'БАГЦ-5', '', 2026),
    cf(2, 'БАГЦ-5', '', null),
    cf(3, 'БАГЦ-5', '', 2025),
  ], 'flat');
  assert.equal(out.length, 1);
  assert.ok(!('years' in out[0]), 'оны дэд бүлэг ҮҮСЭЭГҮЙ');
  assert.deepEqual(out[0].rows.map((r) => r.oid), [1, 2, 3], 'онгүй мөр ч дараалалдаа');
  assert.equal(out[0].count, 3);
}

/* ── 3. Диапазон мөр «хуваарилагдаагүй» рүү, хамгийн сүүлд ── */
{
  const out = buildGroups([
    cf(1, 'БАГЦ 1-4', '', 2026),
    cf(2, 'БАГЦ-14', '', 2026),
  ], 'flat');
  const real = out.find((p) => p.pkg === 'БАГЦ-14');
  assert.equal(real.count, 1, 'диапазоны мөр Багц 14-т НААЛДААГҮЙ');
  assert.equal(real.rows[0].oid, 2);
  assert.equal(out[out.length - 1].key, NO_PKG, 'хуваарилагдаагүй нь хамгийн сүүлд');
}

/* ── 4. «Багц 4-1» ба «Багц 4.1» НЭГ багц; нэр нь ЭХНИЙ бичиглэл ── */
{
  const out = buildGroups([cf(1, '', 'Багц 4.1', 2026), cf(2, '', 'Багц 4-1', 2026)], 'flat');
  assert.equal(out.length, 1);
  assert.equal(out[0].pkg, 'Багц 4.1');
  assert.equal(out[0].count, 2);
}

/* ── 5. HO — багцын талбар нь ӨӨР, ганц ── */
{
  const rows = [
    ho(1, 'Багц-4.1'),
    ho(2, 'Багц-4.1'),
    ho(3, 'Багц-9'),
  ];
  const out = buildGroups(rows, 'ho');
  assert.equal(total(out), 3, 'төлбөрийн мөр АЛДАГДААГҮЙ');
  assert.deepEqual(out.map((p) => p.pkg), ['Багц-4.1', 'Багц-9']);
  assert.deepEqual(out[0].rows.map((r) => r.oid), [1, 2]);
  /* ⚠️ HO нь Cashflow-ийн талбарыг УНШИХГҮЙ — код давхцдаггүй ч ирээдүйд
     талбар нэмэгдвэл санамсаргүй холилдохоос сэргийлнэ. */
  const wrong = buildGroups([{ OBJECTID: 9, [CF.pkg]: 'БАГЦ-4' }], 'ho');
  assert.equal(wrong[0].key, NO_PKG);
}

/* ── 6. ⚠️ HO-гийн АМЬД ДИАПАЗОН МӨРҮҮД — 5.97 тэрбум ₮-ийн эрсдэл ── */
{
  /* ⚠️ ХАМГИЙН ЧУХАЛ ШАЛГУУР. Хэрэв хэн нэг нь `pkgOf`-ийн `isPkgRange`
     хамгаалалтыг «хялбарчлан» хасвал «Багц-1-4»-ийн 876,465,164 ₮ нь бодит
     «Багц 14»-ийн санхүүжилт болж наалдана — дэлгэцэн дээр төгс хэвийн
     харагдана, зөвхөн тоо нь ХУДАЛ болно. */
  const out = buildGroups([
    ho(1, 'Багц-1-4'),
    ho(2, 'БАГЦ-10,  БАГЦ-11, БАГЦ-13, БАГЦ-15'),
    ho(3, null),                 // ХО-0045 хэлбэр: гэрээний код ч, багц ч хоосон
    ho(4, 'Багц-14'),
  ], 'ho');
  const real = out.find((p) => p.pkg === 'Багц-14');
  assert.equal(real.count, 1, 'диапазоны мөр бодит Багц-14-т НААЛДААГҮЙ');
  assert.equal(real.rows[0].oid, 4);
  const none = out[out.length - 1];
  assert.equal(none.key, NO_PKG, 'хуваарилагдаагүй нь хамгийн сүүлд');
  assert.equal(none.count, 3, 'диапазон 2 + багцгүй 1 = 3 мөр ХАЯГДААГҮЙ');
  assert.deepEqual(none.rows.map((r) => r.oid), [1, 2, 3], 'эх дараалал хэвээр');
}

/* ── 7. ⚠️ ГРЕЙН — нэг гэрээний ОЛОН мөр НЭГТГЭГДЭХГҮЙ ── */
{
  /* Амьдаар Багц-4.1 нь 7 төлбөрийн мөртэй; гэрээний талбарууд (төсөв,
     гүйцэтгэгч …) 7 мөрд БҮГДЭД нь ижил утгаар давтагдана. Энэ модуль тэдгээрийг
     нэг мөр болгож НУРААХГҮЙ — 7 мөр 7 хэвээр гарна. Нураавал засвар
     (`oid:талбар`) үхэж, төлбөрийн түүх алга болно. */
  const rows = [1, 2, 3, 4, 5, 6, 7].map((i) => ho(i, 'Багц-4.1', {
    [C.code]: 'Багц-4.1',
    [C.budgetTotal]: 100,      // ⚠️ 7 мөрд ИЖИЛ — нийлүүлбэл 700 болно
    [P.amount]: i * 10,
  }));
  const out = buildGroups(rows, 'ho');
  assert.equal(out.length, 1, 'нэг багц');
  assert.equal(out[0].count, 7, '7 мөр 7 хэвээр — НЭГТГЭГДЭЭГҮЙ');
  assert.deepEqual(out[0].rows.map((r) => r.oid), [1, 2, 3, 4, 5, 6, 7]);
  /* ⚠️ Мөн энэ модуль ямар ч НИЙЛБЭР бодоогүй байх ёстой (санаатай шийдвэр,
     finGroup.ts-ийн толгойн ⚠️). Гэрээний нийлбэрийг ЗӨВХӨН ipc.ts бодно. */
  assert.ok(!('sum' in out[0]) && !('total' in out[0]),
    'блокт НИЙЛБЭР талбар ҮҮСЭЭГҮЙ — грейний давхардлыг үүсгэх зам хаалттай');
}

/* ── 8. OID-гүй мөр (нийтлээгүй) ── */
{
  const out = buildGroups([{ [CF.pkg]: 'БАГЦ-7', [CF.year]: 2026 }], 'flat');
  assert.equal(out[0].rows[0].oid, null, 'OID байхгүй бол null — 0 БИШ');
}

/* ── 9. Хоосон оролт ── */
assert.deepEqual(buildGroups([], 'flat'), []);
assert.deepEqual(buildGroups([], 'ho'), []);

console.log('finGroup.check.mjs — БҮГД ТЭНЦЛЭЭ');
