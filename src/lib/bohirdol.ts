/**
 * ГЭР ХОРООЛЛЫН БОХИРДЛЫН ТООЦОО — «Иргэдэд хүрэх үр өгөөж»-ийн «ӨМНӨ» тал.
 *
 * ⚠️ ЭНЭ НЬ ХЭМЖИЛТ БИШ, ТООЦООЛОЛ. Сэлбэ дээр гэрийн зуухны утаа, нүхэн
 * жорлонгийн бохирдлыг хэмждэг мэдрэгч БАЙХГҮЙ. Тиймээс бодит тоо (өрх, хүн
 * ам, жорлонгийн цэг) дээр ОЛОН УЛСЫН/ҮНДЭСНИЙ НОРМАТИВ коэффициент үржүүлж
 * жилийн ачааллыг гаргана. Карт бүр дээр «тооцоолол» гэж ИЛ бичигдэнэ, мөр бүр
 * өөрийн эх сурвалжийг дагуулна — уншигч тоог хаанаас гарсныг шалгаж чадна.
 *
 * ⚠️ Коэффициент солих бол ЗӨВХӨН ЭНД. Тоог модуль дотор хатуу бичихгүй:
 * эх сурвалж шинэчлэгдэхэд нэг газраас засна.
 */

/* ── ГЭРИЙН ЗУУХ ──────────────────────────────────────────────────────────── */

/**
 * Нэг өрхийн жилийн ТҮҮХИЙ НҮҮРСНИЙ хэрэглээ (тн).
 *
 * Эх: Дэлхийн банк — «Mongolia: Heating in Poor, Peri-urban Ger Areas of
 * Ulaanbaatar» (ASTAE, 2012): «On average, each household in ger areas burns
 * about 5 tons of coal and approximately 3 m³ of wood per year.»
 * Улаанбаатарын гэр хорооллын нийт хэрэглээ ~0.4 сая тн/жил гэсэн тоотой
 * нийцнэ (80,000–100,000 өрх × 5 тн ≈ 0.4–0.5 сая тн).
 */
export const COAL_T_PER_HH = 5;

/**
 * Түүхий нүүрсний ЦЭВЭР илчлэг (МЖ/кг).
 *
 * Багануур, Налайхын нүүрс 3,500–4,000 ккал/кг (14.6–16.7 МЖ/кг). Дунджаар
 * 16 МЖ/кг авав — доод хязгаараар авбал PM2.5 ялгарал БАГА гарах тул
 * болгоомжтой (консерватив) тал руугаа дундажийг сонгов.
 */
export const COAL_MJ_PER_KG = 16;

/**
 * Уламжлалт (сайжруулаагүй) зуухны PM2.5 ЯЛГАРАЛЫН КОЭФФИЦИЕНТ (мг/цэвэр МЖ).
 *
 * Эх: «Mongolia National Low Emission Stove Strategy» (2014, SEET лабораторийн
 * хэмжилт): уламжлалт зуух Налайхын нүүрсээр ~600–700 мг/цэвэр МЖ. Дундаж 650.

 */
export const PM25_MG_PER_MJ = 650;

/** Нэг тонн нүүрснээс ялгарах PM2.5 (кг/тн) — дээрх хоёроос бодогдоно. */
export const PM25_KG_PER_T_COAL = (PM25_MG_PER_MJ * COAL_MJ_PER_KG) / 1_000;

/* ── НҮХЭН ЖОРЛОН ─────────────────────────────────────────────────────────── */

/**
 * Нэг хүнээс жилд хуримтлагдах ялгадасны эзэлхүүн (м³).
 *
 * Эх: WHO/SuSanA-гийн жорлонгийн зураг төслийн норматив — хуурай нүхэн
 * жорлонд 40–60 л/хүн/жил (0.04–0.06 м³). Дундаж 0.05 авав.
 */
export const SLUDGE_M3_PER_PERSON = 0.05;

/**
 * Нэг хүнээс жилд ялгарах АЗОТ (кг N).
 *
 * Эх: Jönsson & Vinnerås — «Human excreta for plant production» (2004):
 * нийт 4.5 кг N/хүн/жил, үүний ~4 кг нь шээсэнд. Битүүмжлэлгүй нүхнээс энэ
 * азот хөрсөнд, улмаар гүний усанд НИТРАТ болж нэвчинэ — Улаанбаатарын гэр
 * хорооллын худгуудад NO₃⁻ > 10 мг/л гарч буйн гол эх үүсвэр.
 */
export const N_KG_PER_PERSON = 4.5;

/**
 * Нэг өрхийн дундаж хүний тоо (Улаанбаатар).
 *
 * Эх: ҮСХ — Улаанбаатар хотын өрхийн дундаж хэмжээ ~3.6 хүн. Нүхэн жорлонгийн
 * ачаалал нь ХҮНЭЭР бодогддог тул барилгын тооноос хүн ам руу шилжүүлэхэд
 * хэрэгтэй.
 *
 * ⚠️ Төслийн «Хамрагдах хүн ам» (43,287) ХЭРЭГЛЭХГҮЙ: тэр нь шинэ орон сууцанд
 * ОРОХ хүн ам буюу ТӨЛӨВЛӨГӨӨ. «Өмнө» талын тооцоонд төлөвлөгөөт тоо орвол
 * «одоо ямар байна» гэдэг асуултад ирээдүйн тоогоор хариулах болно.
 */
export const PERSONS_PER_HH = 3.6;

/* ── ТООЦООНЫ ФУНКЦУУД ────────────────────────────────────────────────────── */

/**
 * Гэрийн зуухны жилийн ачаалал.
 * `hh` — ЗУУХТАЙ ОРОН СУУЦНЫ тоо (гэр + гэр хорооллын байшин), төлөвлөгөөт
 * өрхийн тоо БИШ.
 */
export function stoveLoad(hh: number) {
  const coalT = hh * COAL_T_PER_HH;
  return {
    /** Түүхий нүүрс, тн/жил */
    coalT,
    /** PM2.5, тн/жил */
    pm25T: (coalT * PM25_KG_PER_T_COAL) / 1_000,
    /** Нэг өрхөд ногдох PM2.5, кг/жил */
    pm25KgPerHh: COAL_T_PER_HH * PM25_KG_PER_T_COAL,
  };
}

/**
 * Нүхэн жорлонгийн жилийн ачаалал.
 *
 * `latrines` — БҮРТГЭГДСЭН нүхэн жорлонгийн тоо. Нэг жорлонг НЭГ ӨРХ хэрэглэдэг
 * тул үйлчлэх хүн ам нь жорлонгийн тоо × өрхийн дундаж хэмжээ.
 *
 * ⚠️ Орон сууцны НИЙТ тоог (6,627) энд өгвөл ҮГҮЙ: 23,857 хүнийг 1,675 жорлонд
 * хуваавал нэг нүхэнд 14 хүн ногдох буюу бодит бус. Бүртгэгдсэн жорлон нь
 * судалгаанд хамрагдсан хэсэг — ачааллыг зөвхөн ТҮҮГЭЭР бодно.
 */
export function latrineLoad(latrines: number) {
  const pop = latrines * PERSONS_PER_HH;
  return {
    /** Тооцоонд орсон хүн ам */
    pop,
    /** Ялгадас, м³/жил */
    sludgeM3: pop * SLUDGE_M3_PER_PERSON,
    /** Азот, тн/жил */
    nitrogenT: (pop * N_KG_PER_PERSON) / 1_000,
  };
}
