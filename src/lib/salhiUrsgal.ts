'use client';

/**
 * САЛХИНЫ УРСГАЛЫН АНИМАЦ — тоосонцор canvas дээр, МОНГОЛ ОРНЫ хэмжээнд.
 *
 * `WIND-MODULE.md` §6-гийн `leaflet-velocity` давхаргын ОРЛУУЛАГЧ. Эх модуль нь
 * Leaflet-ийн плагин дээр тогтдог бөгөөд энэ портал ArcGIS дээр ажилладаг тул
 * плагиныг ШУУД авах боломжгүй. Оронд нь `uyr.ts`-ийн ҮЕРИЙН растерын хэв
 * загварыг дагана: canvas → `ImageElement` → `MediaLayer`. Тэр зам нь 2D, 3D,
 * BIM гуравт ижил ажилладаг нь аль хэдийн батлагдсан.
 *
 * ══════════════════ ЗАРЧИМ ══════════════════
 *
 * Тоосонцор бүр торны U/V талбар дээр «хөвж» (advection), өнгөрсөн замаа
 * бүдгэрч буй сүүл болгон үлдээнэ. Сүүл нь ГАНЦ хуримтлалын canvas дээр
 * үлддэг; фрейм тутамд түүнийг бүхэлд нь бага зэрэг ТУНГАЛАГ болгож
 * (`destination-out`) хуучин зам аажим арилна.
 *
 * ⚠️ ХАРАНХУЙ ӨНГӨӨР БҮДГЭРҮҮЛЖ БОЛОХГҮЙ. Хар өнгийн бага alpha-гаар дүүргэвэл
 * сүүл нь арилахын оронд ХАР болж, зурган дээр бохир хөшиг үүснэ. Тиймээс
 * `globalCompositeOperation = 'destination-out'` — өнгө нэмэхгүй, зөвхөн
 * alpha-г хасна.
 *
 * ⚠️ ГАНЦ CANVAS ДЭЭР ГАРАЛТ ӨГӨХГҮЙ. `uyr.ts`-ийн сургамж: `ImageElement`
 * нь canvas-ыг ХОЖИМ уншдаг тул дараагийн фрейм ижил canvas дээр бичигдвэл
 * өмнөх элемент ШИНЭ агуулгыг харуулж, зураг чичирнэ. Тиймээс гаралт нь
 * ЭЭЛЖЛЭХ хоёр canvas.
 *
 * ══════════════════ ПРОЕКЦ — ЯАГААД MERCATOR ДОТОР БОДДОГ ВЭ ══════════════════
 *
 * ⚠️ Тор нь 40°–53°N буюу 13° ӨРГӨРГИЙГ хамарна. Энэ мужид Web Mercator-ын
 * сунгалт 1.31→1.66 дахин өөрчлөгддөг тул canvas-ийн мөрийг өргөрөгт ШУГАМААР
 * буулгавал зураг 20 гаруй хувиар гажина — салхи хойд хэсэгт удаан, урд
 * хэсэгт хурдан мэт харагдана. Тиймээс тоосонцрыг MERCATOR орон зайд (canvas-
 * тай ШУУГААР пропорционал) хадгалж, талбарын хайлтад л өргөрөг рүү урвуулж
 * хөрвүүлнэ.
 *
 * ⚠️ Mercator нь КОНФОРМАЛ: газрын (u, v) м/с вектор нь проекцод хоёр тэнхлэгт
 * ИЖИЛ (1/cos φ) масштабтайгаар буудаг — эргэлт үүсэхгүй. Тиймээс px рүү
 * шилжүүлэхэд ганц `1/cos φ` үржигдэхүүн хангалттай.
 */

import { GRID_BBOX, windAt, type WindField } from '@/lib/salhiTor';

/* ══════════════════ Тохируулах параметрүүд (§10) ══════════════════ */

/** Гаралтын canvas-ийн ӨРГӨН (px). Өндөр нь Mercator-ын харьцаагаар гарна. */
const W = 896;
/** Өнгөний хуваарийн дээд хурд (м/с) — эх модулийн `maxVelocity` */
const MAX_V = 16;
/**
 * Тоосонцрын хурд — ПИКСЕЛ/ФРЕЙМ, `speed^SPEED_P` тутамд (экваторт).
 *
 * ⚠️ Эх модулийн `velocityScale = 0.013`-ыг ШУУД АВЧ БОЛОХГҮЙ: тэр нь
 * Leaflet-ийн проекц, өөр хэмжээст торонд тохируулагдсан. Энд ХЭРЭГЛЭГЧИЙН
 * ӨГСӨН зорилтот уртаас (2026-09-03) буцаж бодов:
 *
 *   2 м/с → 150 px · 7 м/с → 279 px  ⇒  p = ln(279/150)/ln(7/2) ≈ 0.495
 *   SCALE = 279 · cos48° / (7^0.495 · 76 фрейм) ≈ 0.935
 */
const SCALE = 0.935;

/**
 * ХУРДНЫ ИЛТГЭГЧ — сүүлийн урт нь хурдны ЯМАР зэрэгт пропорциональ вэ.
 *
 * ⚠️ 1.0 (шугаман) байсныг 0.5 (квадрат язгуур) болгов. Шалтгаан нь
 * ХЭРЭГЛЭГЧИЙН ӨГСӨН зорилтот тоо: шугаман үед 2 ба 7 м/с-ийн сүүл 3.5
 * дахин зөрдөг (80 ба 279 px) бөгөөд намуухан бүсийн зураас бараг цэг
 * болж уншигдахаа больдог. 0.495-д тэр харьцаа 1.86 болж, сул салхи ч
 * ХАРАГДАХУЙЦ сүүлтэй үлдэнэ.
 *
 * ⚠️ ЭНЭ НЬ ХӨДӨЛГӨӨНИЙГ ГАЖУУДУУЛНА: тоосонцрын хурд нь салхины хурдтай
 * ШУУД пропорциональ БАЙХАА БОЛИНО — 14 м/с нь 2 м/с-ээс 7 биш, 2.6 дахин
 * л хурдан харагдана. Хурдны ЯЛГААГ ӨНГӨ (`hue`) үүрсээр байгаа тул
 * мэдээлэл алдагдахгүй, харин «хэр хурдан» гэдгийг ХӨДӨЛГӨӨНӨӨР бус
 * ӨНГӨӨР унших ёстой.
 */
const SPEED_P = 0.495;
/**
 * Тоосонцрын амьдрах хугацаа (фрейм) — эх модулийн `particleAge`.
 *
 * ⚠️ `FADE`-ЭЭС ГАРАХ СҮҮЛЭЭС УРТ БАЙХ ЁСТОЙ. Сүүл нь `ln(0.03)/ln(1−FADE)`
 * фрейм харагддаг; наслалт түүнээс богино бол тоосонцор сүүлээ бүрэн
 * татаж амжихгүй УХАРНА — `FADE`-ийг хэдий багасгасан ч зураас уртсахаа
 * болино. 0.045 үед сүүл ≈68 фрейм тул наслалтыг 120 болгов (нөөцтэй).
 */
const AGE = 120;

/**
 * Сүүл арилах хурд — фрейм тутамд хасагдах alpha.
 *
 * ⚠️ ЭНЭ УТГА СҮҮЛИЙН УРТЫГ ШИЙДНЭ, `AGE` БИШ. Alpha нь фрейм тутам
 * `(1 − FADE)` дахин буурдаг тул харагдах урт ≈ `ln(0.03) / ln(1 − FADE)`
 * фрейм. 0.055 үед тэр нь ≈60 фрейм = 5.2 px/фрейм × 60 ≈ 310 px — өөрөөр
 * хэлбэл дэлгэцийн 1/3-ыг гаталсан УРТ ХЯЛГАС. Зум ойртуулахад талбар нь
 * жигд болдог тул тэдгээр нь ЗЭРЭГЦЭЭ шулуун болж, зураг «самнасан үс» шиг
 * харагдана (хэрэглэгчийн 2026-09-03-ны скриншот).
 *
 * ⚠️ 0.045 — ХЭРЭГЛЭГЧИЙН ХҮСЭЛТЭЭР УРТ (2026-09-03). ≈68 фрейм ≈ 250 px
 * (7 м/с). 0.16 (74) → 0.10 (122) → 0.075 (165) → 0.045 гэж дөрвөн алхмаар
 * уртасгав.
 *
 * ⚠️ `AGE`-тэй ХАМТ өөрчилнө: наслалт нь сүүлээс богино бол тоосонцор
 * сүүлээ татаж амжихгүй ухарч, `FADE` багасгасан нь үр дүнгүй болно.
 *
 * ⚠️ Анхны 0.055-ын 310 px рүү БУЦААГҮЙ — тэр нь зум ойртуулахад зэрэгцээ
 * шулуун «самнасан үс» болдог (хэрэглэгчийн өмнөх скриншот).
 */
const FADE = 0.045;

/* ══════════════════ Mercator ══════════════════ */

const R = 20037508.34 / 180;
const RAD = Math.PI / 180;

const mercX = (lon: number) => lon * R;
const mercY = (lat: number) => (Math.log(Math.tan((90 + lat) * (Math.PI / 360))) / RAD) * R;
/** Урвуу — Mercator y → өргөрөг */
const latOf = (y: number) => (Math.atan(Math.exp((y / R) * RAD)) / (Math.PI / 360)) - 90;

/** Талбарын БҮРЭН хүрээ — үүнээс гадуур өгөгдөл байхгүй */
export const FIELD_MERC = {
  xmin: mercX(GRID_BBOX.xmin),
  xmax: mercX(GRID_BBOX.xmax),
  ymin: mercY(GRID_BBOX.ymin),
  ymax: mercY(GRID_BBOX.ymax),
};

/** Web Mercator дөрвөлжин — зурах хүрээ */
export type MercBox = { xmin: number; ymin: number; xmax: number; ymax: number };

/**
 * ЗУРАХ ХҮРЭЭ — ХАРАГДАЦЫН муж, талбарын хүрээгээр ХАЗААРСАН.
 *
 * ⚠️ 2026-09-03 (хэрэглэгчийн хүсэлт): урьд нь растер нь МОНГОЛ ОРНЫГ бүхэлд
 * нь тогтмол 896 px-д зурдаг байв. Сэлбэ дүүрэг тэр зургийн ≈0.1%-ийг эзэлдэг
 * тул зум ойртуулахад хэдхэн зураас, тэр нь ч 1000 дахин томорсон бүдэг
 * пиксел болж харагдана. Одоо растер нь ХАРАГДАЖ БУЙ мужийг л зурна: зум
 * ойртох тусам ижил 896 px нь бага талбайд ногдож, зураас олон бөгөөд тод
 * болно — «оron нутгийн салхи» шиг.
 *
 * ⚠️ Талбарын хүрээгээр ХАЗААРНА: гадуур нь `windAt` захын утгаар хазаардаг
 * тул зурвал хиймэл «хөлдсөн» урсгал гарна.
 */
export const clampBox = (b: MercBox): MercBox => ({
  xmin: Math.max(FIELD_MERC.xmin, b.xmin),
  ymin: Math.max(FIELD_MERC.ymin, b.ymin),
  xmax: Math.min(FIELD_MERC.xmax, b.xmax),
  ymax: Math.min(FIELD_MERC.ymax, b.ymax),
});

/* ══════════════════ Өнгө ══════════════════ */

/**
 * ХУРД → ӨНГӨ. Намуухан салхи цайвар цэнхэр, хүчтэй нь цагаан.
 *
 * ⚠️ Аюулын мужийн улаан-улбар шар гэр бүлээс ЗАЙДУУ өнгө сонгов: сэвсгэрийн
 * бүсүүд (`ersdelGeom.airBands` — `#7f1d1d`, `#b45309`, `#ca8a04`) яг доор нь
 * зурагддаг тул ижил өнгөөр урсгал зурвал хоёр давхарга нийлж, аль нь
 * бохирдол, аль нь салхи болох нь ялгагдахгүй болно.
 */
const hue = (speed: number): string => {
  const t = Math.max(0, Math.min(1, speed / MAX_V));
  /**
   * ⚠️ ГУРВАН ТҮШИГ: хөх-ногоон (намуухан) → ногоон (дунд) → шар (хүчтэй).
   * Урьд нь цайвар цэнхэрээс цагаан руу шилждэг байсан нь хиймэл дагуулын
   * саарал-цагаан дэвсгэр дээр ХУРДНЫ ЯЛГАА уншигдахгүй болгож байв —
   * хүчтэй салхи ч сул нь ч ижил цайвар. Шар нь дэвсгэрээс хамгийн тод
   * ялгардаг тул оргил хурдыг тэнд өгөв.
   */
  /* ⚠️ 2026-09-03: түшигүүдийг ТОДРУУЛАВ (хэрэглэгчийн хүсэлт). Хиймэл
     дагуулын дэвсгэр нь ногоон-хүрэн өнгөт, дунд зэргийн гэрэлтэйгээс болж
     өмнөх ханалт бага утгууд түүнд шингэж байв. */
  const stops: [number, number, number][] = [
    [90, 240, 240],
    [175, 250, 150],
    [255, 250, 120],
  ];
  const k = t * 2;
  const i = k < 1 ? 0 : 1;
  const f = k - i;
  const a = stops[i];
  const b = stops[i + 1];
  const c = (n: number) => Math.round(a[n] + (b[n] - a[n]) * f);
  /* ⚠️ Доод зах 0.6 → 0.78 → 0.9: намуухан салхи ч дэвсгэрт тод үлдэнэ
     (лавлагаа зурагт сул бүсийн хөх-ногоон нь мөн адил тод). */
  return `rgba(${c(0)},${c(1)},${c(2)},${0.9 + 0.1 * t})`;
};

/* ══════════════════ Урсгал ══════════════════ */

export type Flow = {
  /** Дараагийн фреймийг зурж, БЭЛЭН canvas буцаана */
  step(h: number): HTMLCanvasElement;
  /** Тоосонцрыг дахин тарааж, сүүлийг арилгана (огноо/цаг солиход) */
  reset(): void;
};

/** Тоосонцор — байрлал нь НОРМЧИЛСОН Mercator (0…1), нас нь фреймээр */
type P = { x: number; y: number; age: number };

/**
 * @param box ЗУРАХ хүрээ (Web Mercator). Ихэвчлэн газрын зургийн харагдац —
 *   `clampBox`-оор талбарын хүрээнд багтаасан байх ёстой.
 */
export function buildFlow(field: WindField, box: MercBox): Flow {
  const X0 = box.xmin;
  const X1 = box.xmax;
  const Y0 = box.ymin;
  const Y1 = box.ymax;
  /** Өндөр нь Mercator-ын харьцаагаар — тоосонцор сунахгүй, дугуй хөдөлнө */
  const H = Math.max(64, Math.round((W * (Y1 - Y0)) / (X1 - X0)));
  /**
   * Тоосонцрын тоо — эх модулийн `particleMultiplier` (1/240 × пиксел).
   *
   * ⚠️ /4.5 — лавлагаа зурагт тохирсон нягт (2026-09-03). /6 нь хэт сийрэг,
   * /3.5 нь зум ойртуулахад зургийг бүрхдэг байв.
   */
  const COUNT = Math.round((W * H) / 240 / 4.5);

  /** Хуримтлалын canvas — сүүл ЭНД үлдэнэ */
  const acc = document.createElement('canvas');
  acc.width = W;
  acc.height = H;
  const ac = acc.getContext('2d')!;

  /* ⚠️ ЭЭЛЖЛЭХ гаралт (файлын толгойн тайлбар) */
  const out: HTMLCanvasElement[] = [0, 1].map(() => {
    const c = document.createElement('canvas');
    c.width = W;
    c.height = H;
    return c;
  });
  let flip = 0;

  const spanY = Y1 - Y0;
  /* ⚠️ Уртраг нь Mercator-д ШУГАМАН тул хуваарь шууд; өргөрөг нь БИШ —
     доор `latOf` урвуу хөрвүүлэлт хийнэ. */
  const lon0 = X0 / R;
  const lonSpan = (X1 - X0) / R;

  const ps: P[] = [];
  const spawn = (p: P) => {
    p.x = Math.random();
    p.y = Math.random();
    /* ⚠️ Насыг САНАМСАРГҮЙ өгнө — эс бөгөөс бүх тоосонцор ЗЭРЭГ үхэж,
       анимац бүхэлдээ цохилж (pulse) харагдана. */
    p.age = Math.floor(Math.random() * AGE);
  };
  for (let i = 0; i < COUNT; i++) {
    const p: P = { x: 0, y: 0, age: 0 };
    spawn(p);
    ps.push(p);
  }

  /* Нормчилсон Mercator → canvas пиксел (y нь УРВУУ: хойд дээшээ) */
  const px = (x: number) => x * W;
  const py = (y: number) => (1 - y) * H;

  const reset = () => {
    ac.clearRect(0, 0, W, H);
    for (const p of ps) spawn(p);
  };

  const step = (h: number): HTMLCanvasElement => {
    /* 1. Хуучин сүүлийг бүдгэрүүлнэ — өнгө НЭМЭХГҮЙ, зөвхөн alpha хасна */
    ac.globalCompositeOperation = 'destination-out';
    ac.fillStyle = `rgba(0,0,0,${FADE})`;
    ac.fillRect(0, 0, W, H);
    ac.globalCompositeOperation = 'source-over';

    /* 2. Тоосонцор бүрийг зөөж, зам нь зурагдана */
    /* ⚠️ 1.8 — лавлагаа зурагт шугам нь ТОД, БҮДҮҮН (2026-09-03). Нягт
       дунд зэрэг (/4.5) тул зэрэгцэн нийлэхгүй. */
    ac.lineWidth = 1.8;
    ac.lineCap = 'round';
    /**
     * ⚠️ ГЭРЭЛТЭЛТ (`shadowBlur`) — лавлагаа зургийн шугам нь өөрөө ГЭРЭЛТЭЖ
     * байгаа мэт харагддаг (хэрэглэгчийн скриншот). Canvas дээр үүнийг
     * зураасны ӨӨРИЙН өнгөөр бүдгэрүүлсэн сүүдрээр гаргана.
     *
     * ⚠️ `shadowColor` нь зураас БҮРД шинэчлэгдэнэ (доор) — нэг удаа тавьбал
     * бүх шугам эхнийхийн өнгөөр гэрэлтэж, хурдны шатлал алдагдана.
     *
     * ⚠️ 3-аас их утга нь фрейм тутам мэдэгдэхүйц удаашруулна (320 зураас ×
     * blur). 2.5 нь гэрэлтэлт мэдрэгдэх ХАМГИЙН бага утга.
     */
    ac.shadowBlur = 2.5;
    for (const p of ps) {
      const lon = lon0 + p.x * lonSpan;
      const lat = latOf(Y0 + p.y * spanY);
      const w = windAt(field, h, lat, lon);

      const x0 = px(p.x);
      const y0 = py(p.y);

      /**
       * ⚠️ Mercator нь КОНФОРМАЛ тул газрын вектор проекцод хоёр тэнхлэгт
       * ИЖИЛ (1/cos φ) масштабтай буудаг. Пикселийн шилжилтийг тэр
       * үржигдэхүүнээр л засна — тэнхлэг тус бүрд өөр коэффициент хэрэггүй.
       */
      /* ⚠️ Хурдны илтгэгч — дээрх `SPEED_P`-ийн тайлбарыг үз. `speed` нь
         вектор БИШ уртыг л засна; чиглэл нь `u/v`-ийн харьцаагаар хэвээр. */
      const mag = w.speed > 0 ? Math.pow(w.speed, SPEED_P) / w.speed : 0;
      const k = (SCALE * mag) / Math.max(0.2, Math.cos(lat * RAD));
      p.x += (w.u * k) / W;
      p.y += (w.v * k) / H;
      p.age += 1;

      /* Хүрээнээс гарсан эсвэл наслалт дууссан бол дахин төрнө */
      if (p.age > AGE || p.x < 0 || p.x > 1 || p.y < 0 || p.y > 1) {
        spawn(p);
        continue;
      }

      const col = hue(w.speed);
      ac.strokeStyle = col;
      /* ⚠️ Гэрэлтэлт нь зураасны ӨӨРИЙН өнгөөр — дээрх тайлбарыг үз */
      ac.shadowColor = col;
      ac.beginPath();
      ac.moveTo(x0, y0);
      ac.lineTo(px(p.x), py(p.y));
      ac.stroke();
    }

    /* 3. Хуримтлалыг ЭЭЛЖЛЭХ гаралт руу хуулна */
    flip ^= 1;
    const c = out[flip];
    const cc = c.getContext('2d')!;
    cc.clearRect(0, 0, W, H);
    cc.drawImage(acc, 0, 0);
    return c;
  };

  return { step, reset };
}
