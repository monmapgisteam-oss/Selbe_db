export type SimProgress = { step: number; total: number; minute: number };

/**
 * ЗАГВАРЧЛАХ ТАЛБАЙ — хэрэглэгчийн зурсан полигон (Web Mercator цагирагууд).
 *
 * ⚠️ Байвал ЗАГВАРЧЛАЛЫН ДОМЭЙН нь ЭНЭ болно: бороо зөвхөн энэ дотор орж,
 * ус зөвхөн энэ дотор урсаж, хилээр нь ГАРНА. Байхгүй бол өндрийн торны
 * бүх талбай.
 *
 * ⚠️ Полигон нь торны хүрээнээс ХАЛЬЖ болно — огтлолцол нь домэйн болно.
 * Огтлолцол хэт жижиг бол ил алдаа өгнө (чимээгүй хоосон үр дүн БУРУУ).
 */
export type SimArea = number[][][];

/**
 * Цэг полигон дотор уу — тэгш/сондгой (even-odd) туяаны арга.
 *
 * ⚠️ Цагираг БҮРИЙГ нэг дор тоолно: гадна цагираг ба НҮХ хоёр ижил
 * дүрмээр огтлолцлыг сольдог тул нүх нь өөрөө домэйноос ХАСАГДАНА.
 */
function inRings(rings: SimArea, x: number, y: number): boolean {
  let inside = false;
  for (const r of rings) {
    for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
      const xi = r[i][0];
      const yi = r[i][1];
      const xj = r[j][0];
      const yj = r[j][1];
      if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
    }
  }
  return inside;
}

/**
 * ҮЕРИЙГ БОДНО.
 *
 * ГИНЖИН ХЭЛХЭЭ (ArcGIS Flood Simulation-тай ижил дараалал):
 *
 *   1. ХУР ТУНАДАС (`rain`, мм/ц)
 *   2. → ОРГИЛ УРСАЦ  — рациональ арга (`peakInflow`)
 *   3. → ГИДРОГРАФ    — өсөлт · оргил · татралт (`hydroQ`)
 *   4. → ХОЙД захын СУВГААР торонд орно
 *   5. → 2D инерцийн шийдэл: ус нь ЗӨВХӨН өндрийн зөрүүгээр тархана
 *   6. → гүн · хурд · чиглэл (24 агшин) + дээд гүн/хурд + ирэх хугацаа
 *
 * ⚠️ ЯАГААД ЖИГД БОРОО БИШ ВЭ: 2026-09-07-нд бүх торонд жигд бороо буулгаж
 * үзсэн нь бүх гадаргууг 7 см усан хальсаар бүрхэж, «усанд автсан» талбай
 * домэйны 68% гэж гаргаж байлаа. Тэр нь үер БИШ, борооны хальс. Голын
 * үер нь ДЭЭД УРСГАЛААС ирдэг.
 *
 * @param level  аюулын түвшин — `FLOOD_LEVELS`-ээс хур тунадас
 * @param onProgress явцыг мэдэгдэх (UI-ийн явцын мөр)
 */
export async function simulateFlood(
  level: LevelKey,
  onProgress?: (p: SimProgress) => void,
  /** Хэрэглэгчийн зурсан талбай — байвал домэйн нь ЭНЭ (`SimArea` §тайлбар) */
  area?: SimArea | null,
): Promise<FloodData> {
  const dsm = await loadDsm();
  const p = FLOOD_LEVELS[level];

  /* ── 1. Тооцооны тор — DSM-ээс сийрэгжүүлнэ (блокийн ХАМГИЙН БАГА өндөр) ── */
  const G0 = dsm.meta.grid;
  const f = Math.max(1, Math.round(G0 / SIM));
  const N = Math.floor(G0 / f);
  const z = new Float32Array(N * N);
  /** ТООЦООНЫ ДОМЭЙН — 1 = өндөр мэдэгдэх (ус урсаж болно) */
  const dom = new Uint8Array(N * N);
  /**
   * СУДАЛГААНЫ ТАЛБАЙ — 3D mesh байгаа нүд.
   * ⚠️ ХУР ТУНАДАС ЗӨВХӨН ЭНД ордог (2026-09-10-ны шаардлага). Бусад талбай
   * нь зөвхөн ус ГАРАХ, эсвэл дээрээс УРСАЖ ОРОХ зам.
   */
  const meshCell = new Uint8Array(N * N);
  let domCells = 0;
  for (let y = 0; y < N; y++) {
    for (let x = 0; x < N; x++) {
      /**
       * ⚠️ ДУНДАЖ, харин `min` БИШ.
       *
       * DSM өөрөө аль хэдийн нүд бүрийн ХАМГИЙН БАГА өндрөөр гаргагдсан
       * (`tools/dsm-mesh.py`). Дээр нь дахин `min` авбал суваг давхар
       * гүнзгийрч, бодит байдлаас нарийн, гүн «суваг» үүсдэг — тэр нь бүх
       * усыг багтааж, үер эрэг давахгүй болно.
       */
      let sum = 0;
      let ok = 0;
      let mh = 0;
      for (let dy = 0; dy < f; dy++) {
        for (let dx = 0; dx < f; dx++) {
          const k = (y * f + dy) * G0 + (x * f + dx);
          sum += dsm.z[k];
          ok += dsm.valid[k];
          mh += dsm.mesh[k];
        }
      }
      z[y * N + x] = sum / (f * f);
      /* ⚠️ ОЛОНХИЙН дүрэм: блокийн хагасаас олон дэд нүд нь mesh-ээс гарсан
         бол тооцоонд орно. Ганц дэд нүдээр шийдвэл mesh-ийн ирмэг дээр
         «шүдтэй» домэйн үүсч, ус тэнд гацна. */
      dom[y * N + x] = ok * 2 >= f * f ? 1 : 0;
      /* ⚠️ MESH-ийн маск ч ОЛОНХИЙН дүрмээр — оёдол дээр «шүдтэй» хил гарахгүй */
      meshCell[y * N + x] = mh * 2 >= f * f ? 1 : 0;
    }
  }
  const dx = dsm.meta.cellM * f;              // нүдний газрын хэмжээ (м)

  /**
   * ⚠️ ХЭРЭГЛЭГЧИЙН ТАЛБАЙ — домэйныг ЗУРСАН полигоноор хязгаарлана.
   *
   * Загварчлал нь торны БҮХ талбайд ажиллах шаардлагагүй: хэрэглэгч сонирхож
   * буй хэсгээ зураад тэр дээр нь бодуулна (2026-09-09-ны хүсэлт). Гадна
   * үлдсэн нүд нь домэйноос гарах ба захын ЧӨЛӨӨТ ГАРЦ нь полигоны ирмэг
   * дээр өөрөө үүснэ.
   */
  if (area && area.length) {
    const e0 = dsm.meta.extent;
    const cw = (e0.xmax - e0.xmin) / N;
    const chh = (e0.ymax - e0.ymin) / N;
    for (let y = 0; y < N; y++) {
      const wy = e0.ymax - (y + 0.5) * chh;
      for (let x = 0; x < N; x++) {
        const i = y * N + x;
        if (!dom[i]) continue;
        if (!inRings(area, e0.xmin + (x + 0.5) * cw, wy)) dom[i] = 0;
      }
    }
  }
  {
    let nd = 0;
    for (let i = 0; i < N * N; i++) nd += dom[i];
    domCells = nd;
  }
  /* ⚠️ Хэт жижиг домэйн дээр CFL, оролт, гарц бүгд утгагүй — ил уначихна */
  if (domCells < 200) {
    throw new Error(tr('Зурсан талбай хэт жижиг эсвэл өндрийн торноос гадуур ({0} нүд)', domCells));
  }

  /* ── 1б. ГИДРОЛОГИЙН ГИНЖ (ArcGIS Spatial Analyst-ийн зарчмаар) ──
   *
   *   Fill → FlowDirection (MFD) → FlowAccumulation
   *
   * ⚠️ ЭНЭ ГУРАВ нь ДИНАМИК ШИЙДЛИЙН ОРОЛТ, орлуулагч БИШ. Гүн, хурд,
   * чиглэл, хугацаа бүгд доорх 2D инерцийн шийдлээс гарна. Эндээс гарах нь:
   *   · дүүргэсэн гадаргуу — ус хиймэл нүхэнд түгжигдэхгүй
   *   · хураах талбай      — «энэ цэгт хэдэн га-гийн ус цуглана»
   *   · сувгийн сүлжээ     — Маннингийн барзгар байдлыг ЗӨВ өгнө
   */
  /**
   * ХОНХОР ДҮҮРГЭХ — ArcGIS `Fill`-тэй ижил (Priority-Flood).
   *
   * ⚠️ Урьд нь 12 удаагийн ДАВТАЛТААР («бүх хөршөөсөө нам нүдийг өргө»)
   * хийж байсан нь ГҮН, ӨРГӨН хонхор дээр ДУТУУ дүүргэдэг байв — тогтмол
   * давталтын тоо нь хэдэн зуун нүд өргөн хонхорт хүрдэггүй. Priority-Flood
   * нь нэг дамжилтаар ЯГ ЗӨВ дүүргэнэ.
   *
   * ⚠️ Домэйны маскийг ӨГНӨ: домэйны зах нь ГАРЦ бөгөөс түүнийг мэдэхгүй
   * бол домэйн бүхэлдээ нэг том хонхор мэт дүүргэгдэнэ.
   */
  const zf = fillSinks(z, N, dom);
  /**
   * ⚠️ ШИЙДЭЛД БҮРЭН ДҮҮРГЭСЭН гадаргуу ХЭРЭГЛЭХГҮЙ.
   *
   * ArcGIS-д ч `Fill` нь `FlowDirection`/`FlowAccumulation`-ы ОРОЛТ бөгөөд
   * гидравликийн загварын гадаргуу БИШ. Учир нь DSM дээрх хонхрын ихэнх нь
   * БОДИТ: барилгын хашаа, ухсан талбай, гүүрний доорх нам газар — тэнд ус
   * ЦУГЛАРАХ ЁСТОЙ. Бүгдийг нь дүүргэвэл тэдгээр нь тэгш тавцан болж, ус
   * хаана ч тогтохгүй тархана (амьдаар хэмжив: дээд гүн 16.4 м, усанд
   * автсан талбай 325 га — 1-р түвшин 3-тайгаа бараг ижил болж, ялгаа алга).
   *
   * Тиймээс ArcGIS-ийн `Fill`-ийн `z_limit` семантикийг дагана: ЗӨВХӨН
   * `FILL_LIMIT_M`-ээс ГҮЕХЭН хонхрыг дүүргэнэ. Тэдгээр нь mesh-ийн нүх,
   * гурвалжны алдаанаас үүссэн ХИЙМЭЛ нүх; гүн хонхор нь бодит.
   */
  const zSim = new Float32Array(z.length);
  for (let i = 0; i < z.length; i++) {
    zSim[i] = Math.min(zf[i], z[i] + FILL_LIMIT_M);
  }
  z.set(zSim);

  /**
   * ХУРААХ ТАЛБАЙ — ArcGIS `FlowAccumulation` (MFD).
   * ⚠️ ЖИНГҮЙ: гаралт нь «хэдэн НҮДНИЙ ус цуглав». Га руу хөрвүүлэхийн
   * тулд нүдний талбайгаар үржүүлнэ (доор).
   */
  /* ⚠️ `zf` — БҮРЭН дүүргэсэн. Хуримтлал нь битүү хонхроор ТАСРАХГҮЙ байх
     ёстой: ArcGIS-д ч `FlowAccumulation` нь `Fill`-ийн гаралт дээр ажилладаг. */
  const accCells = flowAccum(zf, N, undefined, dom);

  /**
   * БАРЗГАР БАЙДАЛ — сувгийн СҮЛЖЭЭНЭЭС (ArcGIS `DeriveStreamAsRaster`).
   *
   * ⚠️ Урьд нь «7×7 цонхны дунджаас нам бол суваг» гэж РЕЛЬЕФЭЭР ялгадаг
   * байсан нь хотод ажиллахгүй: барилгын хашаа, ухсан талбай, замын хонхор
   * бүгд «суваг» болно. ХУРААХ ТАЛБАЙ нь гидрологийн ЗӨВ шалгуур — усны
   * сүлжээ нь газрын хэлбэрээс биш, УС ХААНА ЦУГЛАРАХААС тодорхойлогдоно.
   */
  const cellHaTmp = (dx * dx) / 10000;
  const stream = streamMask(accCells, cellHaTmp, STREAM_HA);
  const n2Cell = new Float32Array(N * N);
  for (let i = 0; i < N * N; i++) {
    const n = stream[i] ? MANNING_CHANNEL : MANNING_PLAIN;
    n2Cell[i] = n * n;
  }
  /**
   * ── ДОМЭЙНЫ ЗАХЫН ЧӨЛӨӨТ ГАРЦ (open boundary) ──
   *
   * ⚠️ Mesh/домэйны ГАДНА нүдний өндөр нь нөхөөс эсвэл огт байхгүй. Инерцийн
   * схемийн урсгалын гүн `hf = max(w) − max(z)` нь тийм хөрш рүү 0 гардаг тул
   * зах нь НЭВТРЭШГҮЙ ХАНА болж, ус доод урсгалын ирмэг дээр овоордог
   * (амьдаар хэмжив: 560,000 м³ голын ус мөр үлдээлгүй алга болж байв).
   *
   * Одоо зах дээр НОРМАЛЬ ГҮНИЙ (Manning) гаралт тавина:
   *
   *     q_гар = (1/n) · h^(5/3) · √S      [м²/с, нэг нүүрэнд]
   *
   * `S` — тухайн нүүрний ГАЗРЫН налуу ГАДАГШАА. Энэ нь «ус домэйноос цааш
   * ижил налуугаар үргэлжлэн урсана» гэсэн гидравликийн стандарт нөхцөл.
   *
   * ⚠️ Налуу ГАДАГШАА бол л гаргана — уулын энгэрийн дээд зах дээр газар
   * гадагшаа ӨГСДӨГ; тэнд гаргавал домэйн руу орох ёстой борооны усыг
   * сорж хаяна.
   */
  const outCoef = new Float32Array(N * N);
  {
    /* ⚠️ Доод хязгаар: яг тэгш зах дээр ч ус зогсох ёсгүй (0.5‰ налуу) */
    const S_MIN = 0.0005;
    const nbo = [-1, 1, -N, N];
    for (let y = 1; y < N - 1; y++) {
      for (let x = 1; x < N - 1; x++) {
        const i = y * N + x;
        if (!dom[i]) continue;
        let cc = 0;
        for (const dnb of nbo) {
          const j = i + dnb;
          const outside = !dom[j]
            || (dnb === -1 && x === 1) || (dnb === 1 && x === N - 2)
            || (dnb === -N && y === 1) || (dnb === N && y === N - 2);
          if (!outside) continue;
          const k = i - dnb;
          if (k < 0 || k >= N * N || !dom[k]) continue;
          const sl = (z[k] - z[i]) / dx;
          if (sl <= 0) continue;                 // газар ГАДАГШАА өгсөж байна
          cc += Math.sqrt(sl < S_MIN ? S_MIN : sl);
        }
        outCoef[i] = cc;
      }
    }
  }

  /* ── 2. Төлөв ── */
  const P = N * N;
  const d = new Float32Array(P);              // усны гүн (м)
  const qx = new Float32Array(P);             // +x чиглэлийн урсгал (м²/с)
  const qy = new Float32Array(P);             // +y чиглэлийн урсгал (м²/с)

  /**
   * ОРОЛТ нь ГОЛЫН ОРГИЛ УРСАЦ (`peak`, м³/с) — ЖИГД БОРОО БИШ.
   *
   * ⚠️ 2026-09-07: Эхэндээ хур тунадсыг бүх торонд жигд буулгаж байсан нь
   * ноцтой алдаа байв: 72 мм гэдэг нь 24 ЦАГИЙН нийлбэр бөгөөд түүнийг 10
   * минутад асгавал 100 дахин эрчимтэй болно. Түүнээс ч дор нь — бүх гадаргуу
   * 7 см усан хальсаар бүрхэгдэж, «усанд автсан» талбай 296 га (домэйны 68%)
   * гэж гарч байлаа. Тэр нь үер БИШ, борооны хальс.
   *
   * Одоо ус нь ХОЙД (дээд урсгалын) захын СУВГААР орж ирнэ — голын үер яг
   * ингэж болдог. Ус хаашаа тархах нь ЗӨВХӨН өндрөөс хамаарна.
   */
  const totalS = SIM_MIN * 60;
  /**
   * ── ХУР ТУНАДАС УНАХ ТАЛБАЙ ──
   *
   * ⚠️ 2026-09-10-ны шаардлага: бороо нь ЗӨВХӨН 3D mesh байгаа талбайд
   * (судалгааны талбай) ордог. Домэйн нь түүнээс өргөн — DEM-ийн хэсэг нь
   * зөвхөн (1) ус ГАРАХ, (2) mesh дотор ӨНДРӨӨС УРСАЖ ОРОХ зам болно.
   *
   * ⚠️ Урьд нь бороо БҮХ домэйнд (1,292 га, уул хамруулаад) ордог байсан
   * нь «боломжгүй газраас ус гарч ирж байна» гэсэн шүүмжийн шалтгаан: 2 км
   * зайд, уулын оройд ус үүсэж, тэндээсээ доошоо гүйдэг байв.
   *
   * ⚠️ Зурсан талбай (\`area\`) байвал ТҮҮНТЭЙ огтлолцоно. Огтлолцол хоосон
   * бол (хэрэглэгч mesh-ээс гадуур зурсан) зурсан талбайг өөрийг нь авна —
   * чимээгүй «юу ч болохгүй» байхаас дээр.
   */
  const rainDom = new Uint8Array(P);
  let rainCells = 0;
  for (let i = 0; i < P; i++) {
    if (dom[i] && meshCell[i]) { rainDom[i] = 1; rainCells++; }
  }
  let rainOnMesh = true;
  if (rainCells < 100) {
    rainOnMesh = false;
    rainCells = 0;
    for (let i = 0; i < P; i++) {
      rainDom[i] = dom[i];
      rainCells += dom[i];
    }
  }

  /**
   * ── СУВГИЙН ОРОЛТ — УРСГАЛЫН СҮЛЖЭЭ ХААНА ОРЖ ИРЭХ ВЭ ──
   *
   * ⚠️ 2026-09-10 (гурав дахь засвар). Урьд нь «домэйны дээд 30%-ийн хамгийн
   * НАМ нүд» гэж сонгодог байсан нь домэйныг өргөсгөсний дараа буруу болов:
   * хамгийн нам цэг нь голын орох цэг БИШ, уулын хормойн санамсаргүй хотгор
   * байж болно. Тэндээс 389 м³/с цутгахад ус «боломжгүй газраас» оргилж
   * гарна (хэрэглэгчийн шүүмж).
   *
   * Одоо ХУРААХ ТАЛБАЙГААР сонгоно: гол нь тодорхойлолтоороо хамгийн их
   * усыг хураадаг зам. Судалгааны талбайн ирмэг дээрх нүднүүдээс хуримтлал
   * хамгийн ИХ нь — яг голын орох цэг.
   */
  const inlet: number[] = [];
  {
    const cand: { i: number; a: number }[] = [];
    for (let y = 2; y < N - 2; y++) {
      for (let x = 2; x < N - 2; x++) {
        const i = y * N + x;
        if (!rainDom[i]) continue;
        /* Судалгааны талбайн ИРМЭГ — гадна талтай хиллэдэг */
        const edge = !rainDom[i - 1] || !rainDom[i + 1]
          || !rainDom[i - N] || !rainDom[i + N];
        if (!edge) continue;
        /* ⚠️ ДЭЭД урсгалын тал: гол хойноос урагш урсдаг. Адаг талын ирмэг
           дээр хуримтлал бүр их байдаг тул чиглэлгүй бол ус ГАРАХ цэгээр
           орж ирнэ. */
        if (y > N * 0.6) continue;
        cand.push({ i, a: accCells[i] });
      }
    }
    cand.sort((p1, p2) => p2.a - p1.a);
    /* ⚠️ Хэт цөөн нүдэнд шахвал ус багана шиг өндөрсөж тоон задрал өгнө;
       хэт олонд тараавал сувгийн оронд «хана» болно. Голын өргөнтэй ойролцоо. */
    const take = Math.max(3, Math.min(cand.length, 8));
    for (let k = 0; k < take; k++) inlet.push(cand[k].i);
  }

  /* Q (м³/с) → нэг оролтын нүдэн дэх гүний өсөлт (м/с) */
  const inletArea = dx * dx * inlet.length;
  /** Оргил урсац — хур тунадаснаас (`peakInflow` §тайлбар) */
  const qPeak = peakInflow(p.rain);

  /**
   * ── ГАДАРГУУГИЙН БОРОО (rain-on-grid) — БҮХ МЕШИЙН ТАЛБАЙД ──
   *
   * ⚠️ 2026-09-09 (хэрэглэгч: «бүх 3D mesh дээр шинжил, одоо цөөхөн газарт л
   * ажиллаж байна»). Зөвхөн голын оролттой бол шинжилгээ нь голын хөндийн
   * нарийн тууз л болно — бороо орж, гудамжаар урсаж, хонхорт цуглах ХОТЫН
   * үер (pluvial) огт гарахгүй.
   *
   * ArcGIS Flood Simulation-д энэ нь тусдаа оролт («rainfall»). Хоёулаа
   * зэрэг ажиллана:
   *   · ГОЛЫН ОРОЛТ — домэйны ГАДНАХ 50 км² сав газраас
   *   · БОРОО       — домэйны ДОТОРХ 4.7 км²-т шууд
   * Давхардал ҮГҮЙ: сав газар нь домэйны дээд урсгалд, огтлолцохгүй.
   *
   * ⚠️ АЛДАГДЛЫГ хассан: бороо бүхэлдээ урсац болдоггүй (шингээлт, ууршилт).
   * `RAIN_C` (0.6) нь яг тэр — эс бөгөөс бүх гадаргуу усан хальсаар
   * бүрхэгдэнэ (2026-09-07-ны алдаа).
   */
  /** Хугацааны ХЭЛБЭР (нэгж оргилтой) — гидрографтай ИЖИЛ хэмнэл */
  const shapeAt = (tt: number) => hydroQ(1, tt, totalS);
  /** Хэлбэрийн дундаж — нийт борооны гүнийг ЗӨВ болгоход */
  let shapeMean = 0;
  for (let k = 0; k < 240; k++) shapeMean += shapeAt(((k + 0.5) / 240) * totalS);
  shapeMean /= 240;
  /** Нийт үр ашигт бороо (м) — `rain` мм/ц × хугацаа × урсацын коэффициент */
  const rainTotalM = (RAIN_C * p.rain * (SIM_MIN / 60)) / 1000;
  /** Борооны эрчим (м/с) хугацаанд `tt` */
  const rainRate = (tt: number) => (rainTotalM / totalS) * (shapeAt(tt) / shapeMean);

  const out: { d: Float32Array; u: Float32Array; v: Float32Array }[] = [];
  const snapAt = Array.from({ length: SLICES }, (_, i) => ((i + 1) / SLICES) * totalS);
  let snap = 0;

  /**
   * ХУРИМТЛАГДСАН ГАРАЛТ — ArcGIS Flood Simulation-ы «maximum» багц.
   *
   * ⚠️ Эдгээр нь ЗҮСМЭЛЭЭС гарахгүй: хамгийн их гүн нь нэг нүдэнд 12-р
   * минутад, хөрш нүдэнд 40-р минутад тохиолдож болно. Тиймээс алхам БҮРД
   * хуримтлуулна — эс бөгөөс «хамгийн муу тохиолдол» гэсэн зураг худал болно.
   */
  const maxD = new Float32Array(P);
  const maxS = new Float32Array(P);
  /** Ус ХЭЗЭЭ ирсэн бэ (сек); хэзээ ч ирээгүй бол −1 */
  const arrival = new Float32Array(P).fill(-1);
  /** «Усанд автсан» гэх босго (м) — талбай, ирэх хугацаа ЭНДЭЭС */
  const wetTh = 0.05;
  /**
   * ЗУРАХ босго (м) — энгэрийн хуудас урсгал 2–4 см тул үүнээс эхэлнэ.
   * ⚠️ Тоонд ОРОХГҮЙ, зөвхөн зурагдана (`uyr.ts` §drawM).
   */
  const drawTh = 0.02;

  let t = 0;
  let step = 0;
  /** Гидрографийн бодит утга — метад бичихийн тулд зүсмэл бүрд авна */
  const qSeries: number[] = [];

  while (t < totalS && step < MAX_STEPS) {
    /* ── Алхмын урт: CFL (гүн ус = хурдан долгион = богино алхам) ── */
    let hMax = 0;
    for (let i = 0; i < P; i++) if (d[i] > hMax) hMax = d[i];
    const dt = Math.min(
      totalS - t,
      Math.max(DT_MIN, Math.min(6, (CFL * dx) / Math.sqrt(G * Math.max(0.02, hMax)))),
    );

    /* ── Голын оролт — ГИДРОГРАФААР (өсөлт → оргил → татралт) ── */
    {
      /* ⚠️ Алхмын ДУНДЫГ авна: гидрограф огцом өөрчлөгддөг тул зөвхөн эхний
         утгыг авбал өсөх үед дутуу, татрах үед илүү ус орно. */
      const q = hydroQ(qPeak, t + dt / 2, totalS);
      const add = (q / inletArea) * dt;
      for (const i of inlet) d[i] += add;
    }

    /* ── Гадаргуугийн бороо — домэйны БҮХ нүдэнд ── */
    {
      const add = rainRate(t + dt / 2) * dt;
      /* ⚠️ ЗӨВХӨН судалгааны талбайд (`rainDom`) — уулын цаана бороо орвол
         «боломжгүй газраас ус гарч ирнэ» */
      if (add > 0) for (let i = 0; i < P; i++) if (rainDom[i]) d[i] += add;
    }

    /* ── Урсгал: x ба y тэнхлэгээр ── */
    for (let y = 0; y < N; y++) {
      for (let x = 0; x < N - 1; x++) {
        const i = y * N + x;
        const j = i + 1;
        const wi = z[i] + d[i];
        const wj = z[j] + d[j];
        const hf = Math.max(wi, wj) - Math.max(z[i], z[j]);
        if (hf <= H_MIN) { qx[i] = 0; continue; }
        const s = (wi - wj) / dx;
        const q0 = qx[i];
        let q = (q0 + G * hf * dt * s)
          / (1 + (G * dt * (n2Cell[i] + n2Cell[j]) * 0.5 * Math.abs(q0)) / Math.pow(hf, 7 / 3));
        /* ⚠️ ХУРДНЫ таг: `hf` тэг рүү тэмүүлэхэд илэрхийлэл хязгааргүй өснө */
        const lim = hf * V_MAX;
        if (q > lim) q = lim; else if (q < -lim) q = -lim;
        /* ⚠️ ЭЗЭЛХҮҮНИЙ таг: нэг алхамд нүдэнд БАЙГААГААС илүү ус гарч
           болохгүй — эс бөгөөс сөрөг гүн үүсч схем задарна */
        const av = (q > 0 ? d[i] : d[j]) * dx / dt;
        if (q > av) q = av; else if (q < -av) q = -av;
        qx[i] = q;
      }
    }
    for (let y = 0; y < N - 1; y++) {
      for (let x = 0; x < N; x++) {
        const i = y * N + x;
        const j = i + N;                       // мөр өсөх = УРАГШ
        const wi = z[i] + d[i];
        const wj = z[j] + d[j];
        const hf = Math.max(wi, wj) - Math.max(z[i], z[j]);
        if (hf <= H_MIN) { qy[i] = 0; continue; }
        const s = (wi - wj) / dx;
        const q0 = qy[i];
        let q = (q0 + G * hf * dt * s)
          / (1 + (G * dt * (n2Cell[i] + n2Cell[j]) * 0.5 * Math.abs(q0)) / Math.pow(hf, 7 / 3));
        const lim = hf * V_MAX;
        if (q > lim) q = lim; else if (q < -lim) q = -lim;
        const av = (q > 0 ? d[i] : d[j]) * dx / dt;
        if (q > av) q = av; else if (q < -av) q = -av;
        qy[i] = q;
      }
    }

    /* ── Гүний шинэчлэл ── */
    const c = dt / dx;
    for (let y = 0; y < N; y++) {
      for (let x = 0; x < N; x++) {
        const i = y * N + x;
        let dv = 0;
        if (x > 0) dv += qx[i - 1];
        if (x < N - 1) dv -= qx[i];
        if (y > 0) dv += qy[i - N];
        if (y < N - 1) dv -= qy[i];
        const nd = d[i] + dv * c;
        /* ⚠️ Сөрөг ба NaN гүн гарч болохгүй: тоон алдаа хуримтлагдаж схем
           задардаг. `!(nd > 0)` нь NaN-ыг ч барина (NaN > 0 = false). */
        d[i] = nd > 0 ? (nd < 50 ? nd : 50) : 0;
      }
    }

    /**
     * ЧӨЛӨӨТ ГАРЦ — ДОМЭЙНЫ захаар ус ГАРНА (`outCoef` §тайлбар).
     *
     * ⚠️ Гаралт нь нэг алхамд нүдний усны ТАЛААС илүүг авахгүй — эс бөгөөс
     * сөрөг гүн үүсч схем задарна.
     */
    for (let i = 0; i < P; i++) {
      const c = outCoef[i];
      if (c === 0) continue;
      const h = d[i];
      if (h <= H_MIN) continue;
      const q = (Math.pow(h, 5 / 3) * c) / Math.sqrt(n2Cell[i]);
      let dd = (q * dt) / dx;
      if (dd > h * 0.5) dd = h * 0.5;
      d[i] = h - dd;
    }
    /* ⚠️ Торны ХАМГИЙН гадна цагираг — домэйнд огт ороогүй ч аюулгүйн тулд */
    for (let x = 0; x < N; x++) { d[x] = 0; d[(N - 1) * N + x] = 0; }
    for (let y = 0; y < N; y++) { d[y * N] = 0; d[y * N + N - 1] = 0; }
    /* ⚠️ Домэйны ГАДНА ус байх ёсгүй: нөхөөсийн өндөр нь хиймэл тул тэнд
       тархсан ус утгагүй. Дээрх гарцаар ус аль хэдийн ГАРСАН — энэ нь зөвхөн
       тоон гоожилтыг цэвэрлэнэ. */
    for (let i = 0; i < P; i++) if (!dom[i]) d[i] = 0;

    t += dt;
    step++;

    /**
     * ── ХУРИМТЛАЛ: дээд гүн · дээд хурд · ирэх хугацаа ──
     *
     * ⚠️ Алхам БҮРД бодвол 260 сая давталт болох тул `ACC_EVERY` тутамд.
     * Ус нэг алхамд нэг нүднээс илүү явахгүй (CFL) тул ирэх хугацааны алдаа
     * нь дээд тал нь 5 алхам ≈ 5 сек — 60 минутын түүхэнд мэдэгдэхгүй.
     */
    if (step % ACC_EVERY === 0 || t >= totalS) {
      for (let i = 0; i < P; i++) {
        const h = d[i];
        /* ⚠️ ДЭЭД ГҮН нь НИМГЭН уснаас эхэлж бичигдэнэ — энгэрийн урсгалыг
           3D гадаргуу ба хайлт олж харах ёстой. Харин ИРЭХ ХУГАЦАА нь
           «усанд автсан» босгоор: 2 см ус ирсэн нь нүүлгэн шилжүүлэх шалтгаан
           болохгүй. */
        if (h < drawTh) continue;
        if (h > maxD[i]) maxD[i] = h;
        if (h >= wetTh && arrival[i] < 0) arrival[i] = t;
        const ax = ((i % N) > 0 ? qx[i - 1] : 0) + qx[i];
        const ay = (i >= N ? qy[i - N] : 0) + qy[i];
        const sp = Math.hypot(ax, ay) / (2 * h);
        if (sp > maxS[i]) maxS[i] = sp > V_MAX ? V_MAX : sp;
      }
    }

    /* ── Агшин хадгалах ── */
    while (snap < SLICES && t >= snapAt[snap]) {
      const sd = new Float32Array(P);
      const su = new Float32Array(P);
      const sv = new Float32Array(P);
      for (let i = 0; i < P; i++) {
        sd[i] = d[i];
        /* Хурд = урсгал / гүн. Хоёр талын урсгалын дундаж — нүдний ТӨВД. */
        const h = d[i] > H_MIN ? d[i] : 0;
        if (h > 0) {
          const ax = ((i % N) > 0 ? qx[i - 1] : 0) + qx[i];
          const ay = (i >= N ? qy[i - N] : 0) + qy[i];
          let vx = ax / (2 * h);
          /* ⚠️ `qy` нь мөр өсөх (УРАГШ) чиглэлд эерэг; `v` нь ХОЙШ эерэг тул
             тэмдгийг эргүүлнэ — эс бөгөөс сум, долгион эсрэг чиглэнэ. */
          let vy = -ay / (2 * h);
          /* ⚠️ Бүрэлдэхүүн тус бүрийг таглавал ВЕКТОРЫН УРТ нь √2·V_MAX
             хүртэл хүрдэг (хэмжив: 11.3 м/с). Уртаар нь таглана. */
          const sp0 = Math.hypot(vx, vy);
          if (sp0 > V_MAX) { const r = V_MAX / sp0; vx *= r; vy *= r; }
          su[i] = vx;
          sv[i] = vy;
        }
      }
      out.push({ d: sd, u: su, v: sv });
      /* Гидрографийн тухайн агшны урсац — UI-д муруй болж зурагдана */
      qSeries.push(Math.round(hydroQ(qPeak, t, totalS) * 10) / 10);
      snap++;
    }

    if (step % YIELD_EVERY === 0) {
      onProgress?.({ step, total: MAX_STEPS, minute: t / 60 });
      // Хөтөчид амьсгал өгнө — эс бөгөөс UI хөлддөг
      await new Promise((r) => setTimeout(r, 0));
    }
  }
  /* Хугацаа дуусахаас өмнө алхам дуусвал үлдсэн зүсмэлийг сүүлийн төлөвөөр дүүргэнэ */
  while (out.length < SLICES) {
    const last = out[out.length - 1];
    out.push(last ?? { d: new Float32Array(P), u: new Float32Array(P), v: new Float32Array(P) });
    qSeries.push(qSeries[qSeries.length - 1] ?? 0);
  }

  /* ── 3. `FloodData`-гийн буфер болгон савлана ── */
  const stride = P * 2 * 3;
  const buf = new ArrayBuffer(stride * SLICES);
  const stats: FloodMeta['stats'] = [];
  const cellHa = (dx * dx) / 10000;
  let peak = 0;
  const everWet = new Uint8Array(P);
  for (let s = 0; s < SLICES; s++) {
    const o = s * stride;
    const dv = new Uint16Array(buf, o, P);
    const uv = new Int16Array(buf, o + P * 2, P);
    const vv = new Int16Array(buf, o + P * 4, P);
    let wet = 0;
    let pk = 0;
    let mx = 0;
    for (let i = 0; i < P; i++) {
      const dd = out[s].d[i];
      dv[i] = Math.max(0, Math.min(65535, Math.round(dd * 1000)));
      uv[i] = Math.max(-32767, Math.min(32767, Math.round(out[s].u[i] * 100)));
      vv[i] = Math.max(-32767, Math.min(32767, Math.round(out[s].v[i] * 100)));
      if (dd >= 0.05) {
        wet++;
        everWet[i] = 1;
        if (dd > pk) pk = dd;
        const sp = Math.hypot(out[s].u[i], out[s].v[i]);
        if (sp > mx) mx = sp;
      }
    }
    if (pk > peak) peak = pk;
    stats.push({
      wetHa: Math.round(wet * cellHa * 100) / 100,
      peakM: Math.round(pk * 1000) / 1000,
      maxSpeed: Math.round(mx * 100) / 100,
    });
  }
  let everHa = 0;
  for (let i = 0; i < P; i++) if (everWet[i]) everHa += cellHa;

  /**
   * ГҮНИЙ ӨНГӨНИЙ ХАНАЛТ — нойтон нүднүүдийн 95 хувийн квантиль.
   *
   * ⚠️ ДЭЭД гүнээр ханавал эсрэг алдаа гарна: ганц 8 м гүн нүх бүх зургийг
   * цайруулж, 1 м гүн үер «гүехэн» мэт харагдана. Квантиль нь цөөн хэдэн
   * онцгой нүдийг тоохгүй.
   *
   * ⚠️ Хязгаар [0.8, 6] м: доод хязгааргүй бол бага үерт өнгө хэт хурдан
   * ханаж, дээдгүй бол хотын үерийн ердийн 0.3–1 м бүдгэрнэ.
   */
  const wetDepths: number[] = [];
  for (let i = 0; i < P; i++) if (maxD[i] >= 0.05) wetDepths.push(maxD[i]);
  wetDepths.sort((a2, b2) => a2 - b2);
  const rampMax = wetDepths.length
    ? Math.max(0.8, Math.min(6, Math.round(wetDepths[Math.floor(wetDepths.length * 0.95)] * 10) / 10))
    : 1.5;

  /* Хугацааны тэмдэглэгээ — эхлэл нь «одоо», алхам нь тэнцүү */
  const t0 = Date.now();
  const stepMs = (totalS * 1000) / SLICES;
  const meta: FloodMeta = {
    source: `mesh DSM · ${dsm.meta.source}`,
    width: N,
    height: N,
    slices: SLICES,
    order: ['depth', 'u', 'v'],
    scale: { depth: 1000, u: 100, v: 100 },
    units: 'meters',
    wkid: 102100,
    extent: dsm.meta.extent,
    cellM: dx,
    srcCellM: dsm.meta.cellM,
    times: Array.from({ length: SLICES }, (_, i) =>
      new Date(t0 + (i + 1) * stepMs).toISOString()),
    wetM: 0.05,
    drawM: 0.02,
    stats,
    totalWetHa: Math.round(everHa * 100) / 100,
    peakDepthM: Math.round(peak * 1000) / 1000,
    simMin: SIM_MIN,
    peakQ: Math.round(qPeak * 10) / 10,
    hydroQ: qSeries.slice(0, SLICES),
    manning: [MANNING_CHANNEL, MANNING_PLAIN],
    /* ⚠️ Шинжилгээнд БОДИТООР орсон талбай — mesh-ийн хүрээ, торны хүрээ БИШ */
    domainHa: Math.round(domCells * cellHa * 10) / 10,
    rainMmH: p.rain,
    rampMaxM: rampMax,
    /* ⚠️ ХОЁР ӨӨР талбай: `domainHa` — ус УРСАЖ болох, `rainHa` — бороо УНАХ */
    rainHa: Math.round(rainCells * cellHa * 10) / 10,
    rainOnMesh,
    meshPct: dsm.meta.meshCells
      ? Math.round((dsm.meta.meshCells * 1000) / (dsm.meta.grid * dsm.meta.grid)) / 10
      : undefined,
  };
  /**
   * ⚠️ Газрын өндөр ба ХУРИМТЛАГДСАН гурван тор ХАМТ явна:
   *   · `terrainZ` — 3D-д усны ГАДАРГУУ (`z + гүн`) бодоход (`uyrSurface.ts`)
   *   · `maxDepth` / `maxSpeed` — «хамгийн муу тохиолдол»-ын зураг
   *   · `arrivalS` — ус хэдэн минутад ирэх вэ (нүүлгэн шилжүүлэлтийн хугацаа)
   * Эдгээр нь зүсмэлээс ДАХИН бодогдохгүй: нүд бүрийн оргил өөр өөр агшинд
   * тохиолддог тул нэг зүсмэлээс гаргавал дутуу гарна.
   */
  /* ⚠️ Нүдний тоо → ГА. `flowAccum` нь жингүй ажилласан тул гаралт нь
     «хэдэн нүдний ус цуглав» — түүнийг нүдний талбайгаар үржүүлнэ. */
  const accHa = new Float32Array(P);
  for (let i = 0; i < P; i++) accHa[i] = accCells[i] * cellHa;

  return floodDataFromBuffer(meta, buf, {
    terrainZ: z, maxDepth: maxD, maxSpeed: maxS, arrivalS: arrival, accHa,
  });
}
