/**
 * ГАРААР БИЧСЭН ОГНОО ЗАДЛАХ (2026-10-04, хэрэглэгч: «бодит эхэлсэн/дууссан мөн адил
 * календараас сонголгүй гараар бичиж өгөх боломжтой болгох»).
 *
 * Хүлээж авах хэлбэр (хэрэглэгчийн сонголт «олон хэлбэр»):
 *   2026-10-04 · 2026.10.04 · 2026/10/04 · 2026 10 04 · 20261004 · 2026-1-5
 * Бүгд `YYYY-MM-DD` болж буцна.
 *
 * ⚠️ «04.10.2026» (өдөр эхэндээ) ЗӨВШӨӨРӨХГҮЙ — сар/өдөр аль нь вэ гэдэг хоёрдмол
 *    (04.10 = 10-р сарын 4 үү, 4-р сарын 10 уу) тул буруу өдөр ЧИМЭЭГҮЙ тавигдана.
 * ⚠️ БАЙХГҮЙ ӨДӨР (2026-02-30) нь `null` — `Date.UTC` шиг 03-02 руу гулсуулахгүй
 *    (`huvaari/util.dayToMs` гулсуулдаг тул түүнд өгөхийн ӨМНӨ энд шалгана).
 * ⚠️ Он 1900–2100 — «0202» г.м. товчлолын алдааг огноо болгохгүй.
 *
 * Буцаах: `''` — хоосон (огноо арилгах) · `'YYYY-MM-DD'` — зөв · `null` — буруу.
 */
export function parseDayInput(raw: string): string | null {
  const s = raw.trim();
  if (!s) return '';
  const m = /^(\d{4})[-./ ](\d{1,2})[-./ ](\d{1,2})$/.exec(s) ?? /^(\d{4})(\d{2})(\d{2})$/.exec(s);
  if (!m) return null;
  const y = Number(m[1]);
  const mo = Number(m[2]);
  const d = Number(m[3]);
  if (y < 1900 || y > 2100 || mo < 1 || mo > 12 || d < 1 || d > 31) return null;
  const ms = Date.UTC(y, mo - 1, d);
  const out = new Date(ms).toISOString().slice(0, 10);
  /* Сарын хязгаараас хэтэрсэн өдөр (02-30) — UTC нь дараа сар руу гулсдаг */
  if (Number(out.slice(5, 7)) !== mo || Number(out.slice(8, 10)) !== d) return null;
  return out;
}
