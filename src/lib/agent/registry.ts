/** Хэрэглэгчийн эрх — `resolveAccess()`-ийн үр дүнгээс шууд өгнө */
export type AgentScope = ViewKey[] | 'all';

/**
 * Агентын асууж болох НЭГДСЭН эх сурвалж — давхарга ба өгөгдөл хоёулаа энэ
 * хэлбэрт хөрвөнө. Хэрэгслүүд зөвхөн үүнийг мэднэ.
 */
export type AgentSource = {
  id: string;
  title: string;
  url: string;
  oidField: string;
  kind: 'layer' | 'dataset';
  note?: string;
  warn?: string;
  /** Машины нэр → хүний ойлгох утга */
  fields?: Record<string, string>;
};

/**
 * Зөвшөөрөгдсөн давхаргууд — эрхээс тооцно.
 *
 * ⚠️ `VIEWS[].layers` дотор `LAYERS`-д БАЙХГҮЙ id-ууд бий (2D төлөвлөгөөний
 * зурган давхаргууд). Тэдгээр нь асуулгын хаяггүй тул шүүж хаяна.
 */
export function allowedLayers(scope: AgentScope): LayerDef[] {
  if (scope === 'all') return LAYERS;
  const ids = new Set<string>();
  for (const key of scope) {
    for (const id of VIEW_BY_KEY[key]?.layers ?? []) ids.add(id);
  }
  return LAYERS.filter((l) => ids.has(l.id));
}

/** Зөвшөөрөгдсөн өгөгдлийн эх сурвалжууд — `Dataset.view` эрхэд байх ёстой */
export function allowedDatasets(scope: AgentScope): Dataset[] {
  if (scope === 'all') return DATASETS;
  return DATASETS.filter((d) => scope.includes(d.view));
}

const layerSource = (l: LayerDef): AgentSource => {
  const n = noteFor(l.id);
  return {
    id: l.id,
    title: l.title,
    url: layerUrl(l),
    oidField: oidOf(l),
    kind: 'layer',
    note: l.note,
    warn: n?.warn,
    fields: n?.fields,
  };
};

const datasetSource = (d: Dataset): AgentSource => ({
  id: d.id,
  title: d.title,
  url: d.url,
  oidField: d.oid ?? OID,
  kind: 'dataset',
  note: d.note,
  warn: d.warn,
  fields: d.fields,
});

/** id-аар эх сурвалж олох — эрхээр шүүгдсэн. Олдохгүй бол `null` */
export function resolveSource(id: string, scope: AgentScope): AgentSource | null {
  const d = DATASET_BY_ID[id];
  if (d) return allowedDatasets(scope).some((x) => x.id === d.id) ? datasetSource(d) : null;

  const l = LAYER_BY_ID[id];
  if (!l) return null;
  if (scope === 'all') return layerSource(l);
  return allowedLayers(scope).some((x) => x.id === l.id) ? layerSource(l) : null;
}

/** Каталогийн НЭГ мөр — агент эх сурвалж сонгоход хэрэгтэй бүхнийг багтаана */
function layerLine(l: LayerDef): string {
  const bits: string[] = [`- \`${l.id}\` «${l.title}» [${topicTitle(l.topic)}/${l.geom}]`];
  if (l.qty) bits.push(tr('хэмжээ:{0}({1})', l.qty.field, l.qty.unit));
  if (l.facets?.length) bits.push(tr('ангилал:{0}', l.facets.map((f) => f.field).join(',')));
  if (l.breaks) bits.push(tr('завсар:{0}', l.breaks.field));
  if (l.noZone) bits.push(tr('⚠ZONE_ID байхгүй'));
  else if (l.zoneField) bits.push(tr('бүсийн талбар:{0}', l.zoneField));

  const n = noteFor(l.id);
  if (n?.synonyms?.length) bits.push(tr('синоним:{0}', n.synonyms.join('/')));
  if (l.note) bits.push(`— ${l.note}`);
  return bits.join(' · ');
}

function datasetLine(d: Dataset): string {
  const bits: string[] = [`- \`${d.id}\` «${d.title}» [${d.view}]`];
  if (d.fields) bits.push(tr('талбар:{0}', Object.keys(d.fields).slice(0, 8).join(',')));
  if (d.synonyms?.length) bits.push(tr('синоним:{0}', d.synonyms.join('/')));
  if (d.note) bits.push(`— ${d.note}`);
  return bits.join(' · ');
}

/** Онцгой анхааруулгатай эх сурвалжууд — системийн зааварт тусад нь тодруулна */
function warningLines(layers: LayerDef[], datasets: Dataset[]): string[] {
  const out: string[] = [];
  for (const l of layers) {
    const w = noteFor(l.id)?.warn;
    if (w) out.push(`- \`${l.id}\` «${l.title}»: ${w}`);
  }
  for (const d of datasets) if (d.warn) out.push(`- \`${d.id}\` «${d.title}»: ${d.warn}`);
  return out;
}

