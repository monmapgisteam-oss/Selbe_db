/**
 * ⚠️ Нэгжүүдийг УРТААС нь эхлүүлж жагсаана. Богиноос эхлүүлбэл «тэрбум»-ын «м»
 * түрүүлж таарч, үлдсэн «тэрбу» нь тоо биш болно.
 *
 * ⚠️ `\b` ХЭРЭГЛЭХГҮЙ — JavaScript-ийн үгийн хязгаар нь ASCII суурьтай тул
 * кирилл болон `%`, `₮` тэмдэгттэй буруу ажиллана.
 */
const UNITS = /их наяд|тэрбум|мянга|хоног|нэгж|блок|өдөр|өрх|сая|цаг|айл|м²|м³|км|га|ш|м|%|₮/gi;

/**
 * Тод бичсэн хэсэг нь ТООН УТГА мөн үү.
 *
 * ⚠️ Зөвхөн тоог шараар тодруулна. Бүлгийн гарчиг («Гүйцэтгэлийн байдал»),
 * нэр («Багц 4.1») зэрэг нь тод боловч ЦАГААН үлдэнэ — эс бөгөөс бүх зүйл шар
 * болж, хэрэглэгчийн нүд гол тоог ялгахаа болино.
 *
 * Арга: нэгжийн үгсийг хасаад үлдсэн нь зөвхөн цифр/цэг/таслал бол ТОО.
 *   «21.6%» ✓ · «115.1 тэрбум ₮» ✓ · «5/7» ✓
 *   «Багц 4.1» ✗ («Багц» үлдэнэ) · «Анхаарах зүйл» ✗ (цифргүй)
 */
export function isNumeric(s: string): boolean {
  if (!/\d/.test(s)) return false;
  const rest = s.replace(UNITS, '').replace(/[\d\s.,:;+\-–—/()·]/g, '');
  return rest === '';
}
