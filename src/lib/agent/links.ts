/** `## ӨГӨГДЛИЙН ЗУРАГ` — нэгж, түлхүүр, нэг өгөгдлийн олон id, урсгал, зөв эх */
export function dataMapLines(has: HasSource): string[] {
  const alias = aliasLines(has);
  const flow = flowLines();
  return [
    '',
    tr('## ӨГӨГДЛИЙН ЗУРАГ — юу юутай холбогддог вэ'),
    '',
    tr('### Нэгж ба холбох түлхүүр'),
    ...keyLines(),
    ...(alias.length ? ['', tr('### НЭГ өгөгдөл — хэд хэдэн id (давхар тоолохгүй)'), ...alias] : []),
    ...(flow.length ? ['', tr('### Тоо хаанаас гарч ирдэг вэ (боловсруулалтын урсгал)'), ...flow] : []),
    '',
    tr('### АЛЬ ТООГ АЛЬ ЭХЭЭС (хамгийн чухал)'),
    ...sourceOfTruthLines(),
  ];
}

/** `## ЖОРУУД` — зөвхөн хэрэглэгчид нээлттэй эх сурвалжтай жорууд */
export function recipeLines(has: HasSource): string[] {
  const list = RECIPES().filter((r) => r.needs.every(has));
  if (!list.length) return [];
  return [
    '',
    tr('## ЖОРУУД — түгээмэл асуултын ЗӨВ ЗАМ'),
    ...list.map((r) => `- «${r.ask}» → ${r.how}`),
  ];
}
