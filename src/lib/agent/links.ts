/* ══════════════ АВТО — `dataCatalog()`-оос ══════════════ */

/**
 * НЭГ ФИЗИК хүснэгтийг заадаг олон id.
 * ⚠️ Агент эдгээрийг тусдаа эх сурвалж гэж үзвэл нэг тоог ХОЁР ДАХИН тоолно.
 */
function aliasLines(has: HasSource): string[] {
  const out: string[] = [];
  for (const e of dataCatalog()) {
    if (e.aliases.length < 2) continue;
    const ids = e.aliases.filter(has);
    if (ids.length < 2) continue;
    out.push(`- ${ids.map((i) => `\`${i}\``).join(' = ')} — «${e.name}»`);
  }
  return out;
}

/**
 * БОЛОВСРУУЛАЛТЫН УРСГАЛ — «энэ тоо хаанаас гарав». Ижил гинжтэй хүснэгтүүдийг
 * (жиш. 24 бөглөх хуудас) НЭГ мөрөнд нэгтгэнэ — эс бөгөөс заавар 24 ижил мөрөөр
 * хавагдана.
 */
function flowLines(): string[] {
  /* ⚠️ Хаалтанд бичигдсэн ҮЙЛЧИЛГЭЭНИЙ нэрийг (жиш. «Архивт шинэ хуулбар (Bagts_1_9f)»)
     хасаж жишнэ — эс бөгөөс 24 бөглөх хуудас 24 ӨӨР гинж болж, заавар хавагдана. */
  const generic = (s: string) => s.replace(/\s*\([^)]*\)/g, '').trim();
  const byChain = new Map<string, { n: number; first: string; group: CatGroup }>();
  for (const e of dataCatalog()) {
    if (e.kind !== 'table' || e.closed) continue;
    const chain = e.chain().map((st) => generic(st.label)).filter(Boolean).join(' → ');
    if (!chain) continue;
    const hit = byChain.get(chain);
    if (hit) hit.n += 1;
    else byChain.set(chain, { n: 1, first: e.name, group: e.group });
  }
  const label = (g: CatGroup) => CAT_GROUPS.find((x) => x.key === g)?.label() ?? g;
  return [...byChain.entries()]
    .sort((a, b) => b[1].n - a[1].n)
    .map(([chain, v]) => (v.n > 1
      ? `- ${tr('«{0}» бүлгийн {1} хүснэгт', label(v.group), v.n)}: ${chain}`
      : `- «${v.first}»: ${chain}`));
}

