near(t7['Норм нормативын сан'].contract, 293661052, 1, 'Норм сан · гэрээ (скан 293,661,052)');
near(t7['Гүйцэтгэгчид төлөх дүн'].now, 8688815634.35, 2, 'Гүйцэтгэгчид төлөх · одоо (скан 8,688,815,634.35)');
near(t7['Гүйцэтгэгчид төлөх дүн'].contract, 173620571193.66, 0.05, 'Гүйцэтгэгчид төлөх · гэрээ (скан БУА-г бүхэл төгрөгөөр тасалдаг — ≤5 мөнгө)');
assert.equal(t7['Урьдчилгаа эргэн төлөлт'].now, null, 'эргэн төлөлт эхлээгүй — хоосон (0 биш)');
console.log('✅ Хүснэгт 7 — Багц 3.2 IPC-1-ийн скан тоог давтав');

const g1 = Object.fromEntries(doc.g1.map((r) => [r.label, r]));
near(g1['Барилга угсралтын ажлын дүн'].now, 8312985556, 1, 'БУА · тайлант (скан 8,312,985,556)');
near(g1['Барилга угсралтын ажлын дүн'].contract, 163145028888, 1, 'БУА · гэрээ (скан 163,145,028,888)');
near(g1['НӨАТ'].now, 831298556, 1, 'НӨАТ (скан 831,298,556)');
