near(g1['Захиалагчийн зардлын задаргааны нийт дүн'].contract, 8157251444, 2, 'Захиалагчийн зардал · гэрээ (скан 8,157,251,444)');
near(g1['БҮГД ДҮН'].now, 9408637053, 1, 'БҮГД ДҮН (скан 9,408,637,053)');
