assert.equal(g1['Ажиллах хүчний зардал'].now, null, 'зардлын элемент задаргаагүй — хоосон (0 биш)');
assert.equal(g1['Магадлашгүй ажлын зардал'].now, 0, 'магадлашгүй ажил гүйцэтгэлд 0');
console.log('✅ Гүйцэтгэл-1 — БУА·НӨАТ·ДҮН·захиалагчийн зардал·БҮГД скан тоонд таарна');

near(doc.h12Total.now, 9408637053, 1, 'Хавсралт 12 · тайлант нийт');
near(doc.h12Total.planCost, 187910444274, 1, 'Хавсралт 12 · төлөвлөгөөт нийт');
near(doc.h12[0].planCost, 15659203689.5, 1, 'блокийн төлөвлөгөөт зардал (скан 15,659,203,689)');
