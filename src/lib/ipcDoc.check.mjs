near(t7['Захиалагчийн хяналтын зардал'].prev, 535115679.80, 0.01, 'Захиалагчийн хяналт · өмнөх (скан 535,115,679.80)');
near(t7['Захиалагчийн хяналтын зардал'].contract, 3262900577.76, 0.05, 'Захиалагчийн хяналт · гэрээ (скан 3,262,900,577.76)');
near(t7['Зохиогчийн хяналтын зардал'].now, 83129855, 1, 'Зохиогчийн хяналт · одоо (скан 83,129,855)');
near(t7['Барьцаа'].now, 470431852.65, 1, 'Барьцаа · одоо (скан 470,431,852.65)');
