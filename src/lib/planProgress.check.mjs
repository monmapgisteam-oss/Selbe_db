import assert from 'node:assert/strict';
import fs from 'node:fs';

const SRC = fs.readFileSync('src/lib/planProgress.ts', 'utf8');
const SHEET = fs.readFileSync('src/modules/sheet/bagtsSheet.ts', 'utf8');

/* ── 1. ХУУДАСНЫ ТООЦООЛЛЫГ ашиглана — өөрийн томъёо БИЧИХГҮЙ ── */
assert.match(SRC, /import\s*\{[^}]*loadRows[^}]*planCurve[^}]*\}\s*from\s*'@\/modules\/sheet\/bagtsSheet'/,
  '`loadRows` ба `planCurve`-ийг хуудасны модулиас авах ёстой');
assert.match(SRC, /planCurve\(sh\.rows,\s*sh\.nBld,\s*asOfs/,
  'муруйг `planCurve`-ээр бодох ёстой');
assert.ok(!/\bplanAt\s*\(/.test(SRC),
  '`planAt`-ыг ЭНД дуудаж болохгүй — жигнэлт нь `planCurve`-ийнх');
/* ⚠️ Талбарыг УНШИХЫГ хориглоно — тайлбарт дурдахыг БИШ (тайлбар нь яагаад
   мөнгөн жинтэй хэвээр байгааг тайлбарладаг). */
assert.ok(!/a\[sc\.f\.wD\]|a\[sc\.f\.wC\]|sc\.f\.wD\s*\?|Number\(a\[sc\.f\.w/.test(SRC),
  'жингийн талбарыг ЭНД уншиж болохгүй — жигнэлт нь `planCurve`-ийнх');

/* ── 2. БҮЛГИЙН ОГНОО ЦЭВЭРЛЭГДЭХГҮЙ (2026-10-01, хэрэглэгчийн шийдвэр) ──
   ⚠️ Урьд нь (Согог №3) бүлгийн огноог энд цэвэрлэдэг байв. Одоо `planCurve` өөрөө бүлгийн
   огноог ЗӨВХӨН дэд ажил хуваарьгүй үед хэрэглэдэг (`planCurveShape.check` §3) тул цэвэрлэвэл
   хуудас ба муруй ЗӨРНӨ — хуудастай НЭГ дүрэм байх ёстой. */
assert.doesNotMatch(SRC, /row\.group\s*\?\s*\{\s*\.\.\.row,\s*start:\s*row\.start\.map\(\(\)\s*=>\s*null\)/,
  'бүлгийн огноог муруйд зориулж цэвэрлэх ёсгүй — хуудастай зөрнө');
assert.match(SRC, /rows: rows,|rows,\s*$/m,
  'мөрүүд `planCurve`-д дамжина');

/* ── 3. ЗӨВХӨН барилга угсралтын мөр ── */
assert.match(SRC, /isConstructionNo/,
  'муруй нь «Б.» (барилга угсралт) мөрөөс гарна — бэлтгэл ажил ОРОХГҮЙ');

/* ── 4. САРЫН ЗАДАРГАА дамжина ── */
assert.match(SRC, /import\s*\{[^}]*loadPkgPlan[^}]*planPctFromMonths[^}]*\}\s*from\s*'\.\/huvaariObyem'/,
  'сарын задаргааны модулийг импортлох ёстой');
assert.match(SRC, /planCurve\([^)]*sh\.planPct\)/,
  'сарын задаргаа `planCurve`-д дамжих ёстой');
assert.match(SRC, /loadPkgPlan\(pkg\.key\)[\s\S]{0,90}\.catch\(\(\)\s*=>\s*null\)/,
  '`loadPkgPlan`-ийн уналт чимээгүй байх ёстой');

/* ── 5. `planCurve` ба `computeAll` ИЖИЛ чадвартай ──
   ⚠️ Аль нэгэнд нь задаргаа нэмээд нөгөөд нь мартвал график ба хуудасны тоо
   чимээгүй зөрнө (`bagtsSheet`-ийн толгойн ⚠️). */
for (const fn of ['computeAll', 'planCurve']) {
  const i = SHEET.indexOf(`export function ${fn}(`);
  assert.ok(i > 0, `${fn} олдсонгүй`);
  assert.ok(SHEET.slice(i, i + 12000).includes('planPct'),
    `${fn} нь сарын задаргааг дэмжих ёстой`);
}

/* ── 6. ГУРВАН ГАДАРГУУ НЭГ ДҮРЭМ ── */
for (const [f, what] of [
  ['src/modules/sheet/FillNew.tsx', '«Гүйцэтгэл бөглөх»'],
  ['src/lib/hyanaltStore.ts', 'архивт бичих зам'],
]) {
  const t = fs.readFileSync(f, 'utf8');
  assert.ok(t.includes('planPctFromMonths'), `${what} нь задаргааг ашиглах ёстой (${f})`);
}

/* ── 7. ОБЬЁМООР ЖИГНЭХ ЗАМ ХААЛТТАЙ ──
   ⚠️ 2026-09-09-нд туршиж ҮЗСЭН: түүхий обьёмоор жигнэвэл м³ · м² · ш · тн
   ХОЛИЛДОНО. Багц 1-д «55,200 м кабель» мэт нэг мөр бүхэл багцын жингийн
   дийлэнхийг эзэлж, төлөвлөгөө 78% → 6% болж унасан. Хэмжсэн: хуваарьтай
   ажлын обьём нийт обьёмын ердөө 2.5%. Нэгж хольсон нийлбэр нь утгагүй —
   `bagtsSheet` өөрөө үүнийг тэмдэглэсэн («Бүлгийн мөрд обьём НИЙЛҮҮЛЭХГҮЙ»). */
assert.ok(!/planCurve\([^)]*'obyem'\)/.test(SRC),
  'муруйг ТҮҮХИЙ обьёмоор жигнэж болохгүй — нэгж холилдоно');

/* ── 8. ХУВААРЬГҮЙ САРД ЦЭГ ГАРАХГҮЙ ──
   ⚠️ 2026-09-09: Багц 2 · 12F-ийн ажил 2027-05-16-нд дуусдаг атлаа муруй нь
   2027-12 хүртэл 100% гэсэн ХАВТГАЙ сүүл татаж, төлөвлөгөөгүй саруудад
   «төлөвлөгөө бий» мэт уншигдаж байв. Хуудас ба багц ХОЁУЛАА өөрийн
   хуваарийн мужаар тасрах ёстой. */
assert.ok(SRC.includes('a.label < startYm || a.label > endYm'),
  'хуудасны цэг нь хуваарийн мужаас гадуур гарах ёсгүй');
assert.match(SRC, /gRange/,
  'багцын муруй ч мөн мужаараа тасрах ёстой');
/* ⚠️ ГЭХДЭЭ нэгтгэлд үлдэнэ — эс бөгөөс багц дуусах бүрд нийт муруй унана. */
assert.match(SRC, /gArr\[i\]\.s \+= plan \* sh\.nBld;[\s\S]{0,160}return;/,
  'мужаас гадуурх хуудас НЭГТГЭЛД тоологдсоор байх ёстой');

/* ── 9. Эвдэрсэн огноо мужаас хасагдана ──
   ⚠️ Багц 3.2-т excel-ийн 0 сериал (1899-12-30) хоёр нүд бий. */
assert.match(SRC, /OK_LO|sane\(/, 'эвдэрсэн огнооны хамгаалалт үлдэх ёстой');

/* ── 10. `planPctAt` — ШУУД тест (2026-09-25, аудит 8) ──
   ⚠️ Урьд нь энэ функц зөвхөн `negtgel.check`-ийн `housingPlanOf`-оор дам
   шалгагддаг байв; `Finance.lagOf` · PkgProg · execReport · negtgelAuto ДӨРВҮҮЛЭЭ
   энэ дүрмээр хоцрогдол боддог тул хазайлт нь бүх дэлгэцийг зэрэг худал болгоно. */
{
  const { planPctAt } = await import('./planProgress.ts');
  const S = [{ label: '2026-08', pct: 20 }, { label: '2026-09', pct: 50 }];
  assert.equal(planPctAt(S, '2026-09-15'), 35, 'сарын дундуур — өмнөх сарын эцэс → энэ сарын эцэс шугаман');
  assert.equal(planPctAt(S, '2026-09-30'), 50, 'сарын сүүлийн өдөр = сарын цэг');
  assert.equal(planPctAt(S, '2026-09-31'), 50, '`-31` сарын уртаас их → сарын эцэс');
  assert.equal(planPctAt(S, '2026-08-31'), 20, 'өмнөх сарын цэггүй = хуваарь энэ сард эхэлсэн → 0-ээс');
  assert.ok(Math.abs(planPctAt(S, '2026-08-15') - 20 * (15 / 31)) < 1e-9, 'эхний сар: 0 → 20 шугаман (15/31)');
  assert.equal(planPctAt(S, '2026-11-10'), 50, 'муж өнгөрсөн → сүүлийн өнгөрсөн цэг');
  assert.equal(planPctAt(S, '2026-07-10'), null, 'бүх цэг ирээдүйд → null (төлөвлөгөөгүй ≠ 0)');
  assert.equal(planPctAt(S, 'хог'), null, 'эвдэрсэн огноо → null');
  assert.equal(planPctAt([], '2026-09-15'), null, 'хоосон муруй → null');
}

/* ── 11. (2026-10-01, хэрэглэгч: бүгдийг зас) САР ДОТОРХ ХУВЬ АЖЛЫН ӨДРӨӨР · КЭШ ──
   ⚠️ Сарын задаргааны хувь (`planPctFromMonths`) нь ажлын эхлэх–дуусах мужийг авна —
   `bagtsSheet.planAt`-тай НЭГ томъёо (`plan.spanFrac`). Сарын эцсийн цэгүүд (энэ муруй)
   хөдлөхгүй ч, муж дамжуулахгүй бол өдрийн `asOf`-тай дуудагч (`planCurve`) зөрнө.
   ⚠️ Муруй `HUVAARI_OBYEM`-ээр ч бүртгэгдэнэ — зөвхөн обьём өөрчилсөн батлалтын дараа
   (`applyPlanEdits`) тэр дор нь хаягдана. */
assert.ok(/register\(\(\) => \{ curveP = null; \}, \[[^\]]*'BAGTS_SHEET'[^\]]*'HUVAARI_OBYEM'[^\]]*\]\)/.test(SRC),
  'муруй BAGTS_SHEET ба HUVAARI_OBYEM хоёуланд бүртгэгдэх ёстой');
assert.ok(/planPctFromMonths\(m, asOf, sane\(s\) && sane\(e\) \? \{ start: s, end: e \} : null\)/.test(SRC),
  'сар доторх хувьд ажлын муж (эвдэрсэн огноо бол null) дамжих ёстой');
assert.ok(/return spanFrac\(\{ start: s, end: e \}, asOf\);/.test(SHEET),
  '`planAt` нь `plan.spanFrac`-ийг дуудах ёстой — нэг томъёо');

