/** `WBS_ID`-уудын djb2 — `NEG_TREE.hash`-тай жишнэ */
export function negTreeHash(codes: readonly string[]): number {
  const s = codes.join('|');
  let h = 5381;
  for (let k = 0; k < s.length; k += 1) h = ((h * 33) ^ s.charCodeAt(k)) >>> 0;
  return h;
}
